// Прогон: средства перехвата выключаются на время измерения и возвращаются.
//
// Зачем он нужен. Все прочие прогоны начинаются с остановки zapret и ему
// подобных: при работающем перехватчике измеряется сумма двух воздействий, и
// отличить «сработала наша стратегия» от «сработал zapret» нельзя. Значит сама
// эта остановка — часть измерительного инструмента, и она обязана быть
// проверенной: сломайся она молча, все остальные прогоны стали бы врать, не
// подавая признаков.
//
// Вторая половина проверки важнее первой: перехватчик обязан вернуться.
// zapret нужен владельцу для повседневной работы, и прогон, оставивший его
// выключенным, ломает человеку доступ в сеть ради своего измерения.
package main

import (
	"github.com/fitting-1c/evasion/internal/interception"
	"github.com/fitting-1c/evasion/tests/harness"
)

func main() {
	// Этот прогон не пользуется StartRun: тот сам останавливает перехватчики, а
	// здесь именно остановка и есть предмет проверки, и делать её надо явно.
	run := harness.NewRun(
		"interception-tools-stopped-and-restored",
		"средства перехвата обнаруживаются, останавливаются на время прогона и возвращаются обратно")
	defer run.Finish()

	icept, err := harness.StopInterception()
	if err != nil {
		run.Fail("поиск средств перехвата не удался: %v", err)
		return
	}
	run.Step("поиск завершён: %s", icept.Report())

	if !icept.Stopped() {
		// Это законный исход, а не пропуск. Но «не нашли» и «не искали» —
		// разные ответы, и выдавать второе за первое нельзя (9.3): на
		// не-Windows поиск неприменим вовсе, а на Windows он может пройти не
		// до конца при отказе системной команды.
		if icept.Searched {
			run.Fact("средств перехвата не найдено: останавливать нечего, измерение чистое и без вмешательства")
		} else {
			run.Fact("средства перехвата не проверялись: поиск неприменим или прошёл не полностью — " +
				"чистоту измерения подтвердить нечем")
			for _, note := range icept.Notes {
				run.Fact("пометка поиска: %s", note)
			}
		}
		run.Fact("проверка возврата не состоялась — ей нужен хотя бы один работающий перехватчик")
		return
	}

	run.Require(icept.Elevated,
		"остановить удалось не всё: нужны права администратора, иначе прогоны измеряют сумму двух воздействий")
	for _, t := range icept.Found {
		run.Fact("остановлено: %s", t)
		// Сравнение именно с машинным видом, а не с подписью.
		//
		// Здесь была мина: прежде вид хранился русской строкой, и проверка
		// писалась как t.Kind != "процесс". После перевода вида в машинный
		// токен такое сравнение **скомпилировалось бы** (Kind — именованный
		// строковый тип) и стало бы всегда истинным, то есть проверка молча
		// превратилась бы в украшение. Ровно тот класс дефекта, против
		// которого в проекте заведена батарея мутаций.
		run.Require(t.Kind != interception.KindProcess || t.Command != "",
			"для процесса %s не удалось узнать команду запуска: вернуть его автоматически не получится", t.Name)
	}

	// Возврат — и сразу проверка, что он удался.
	harness.RestoreInterception(icept)
	for _, t := range icept.Found {
		run.Require(t.Restored,
			"средство перехвата %s не возвращено (%s): запустите его сами, иначе обход останется выключенным",
			t.Name, t.RestoreErr)
		if t.Restored {
			// Подпись, а не машинный токен: это строка для человека.
			run.Fact("возвращено: %s", t)
		}
	}
}
