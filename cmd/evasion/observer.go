package main

import (
	"github.com/fitting-1c/evasion/internal/control"
	"github.com/fitting-1c/evasion/internal/core"
	"github.com/fitting-1c/evasion/internal/proxy"
	"github.com/fitting-1c/evasion/internal/store"
)

// observationSink — то, что умеет принять наблюдение для решений.
//
// Узкий интерфейс вместо прямого обращения к контуру: так перевод исходов
// проверяется без запуска движка. Реализация — control.Engine.
type observationSink interface {
	Observe(control.Observation) bool
}

// archiveSink — то, что умеет принять наблюдение на хранение.
//
// Отдельно от observationSink, потому что это разные потребители с разными
// требованиями: контуру наблюдение нужно немедленно и в памяти, журналу — с
// полным составом полей и асинхронно. Реализация — store.Writer.
type archiveSink interface {
	Enqueue(store.Observation) bool
}

// outcomeObserver переводит исходы соединений прокси в наблюдения контура.
//
// Зачем он здесь, а не в одном из пакетов. Прокси объявляет, что он наблюдал
// (proxy.OutcomeSink), контур — что он принимает (control.Observation), и ни
// один из них не должен знать о другом: иначе контур потащил бы за собой
// зависимости прокси и перестал бы переезжать на этап 1 без изменений
// (4.7 п. 4). Перевод — работа того, кто собирает движок, то есть команды.
//
// Это шов, которого не хватало автопилоту: до него контур умел принимать
// наблюдения, но получать их было неоткуда, и обучение шло только с проб.
type outcomeObserver struct {
	// sink — контур управления: ему наблюдение нужно для решений.
	sink observationSink
	// archive — журнал наблюдений; nil означает «не хранить». Движок обязан
	// работать и без архива: потеря истории хуже, но не смертельна.
	archive archiveSink
	// vantage — точка наблюдения. Часть ключа любого наблюдения (6.1), и
	// контур подставляет её сам, а журналу её надо передать явно.
	vantage core.VantageID
}

// ConnOutcome переводит исход соединения в наблюдение и отдаёт контуру.
//
// Соединения без выбранной стратегии пропускаются молча, и это не потеря
// данных: вне радиуса поражения стратегия не выбиралась, значит относить
// исход не к чему. Считать такие соединения непригодными наблюдениями было бы
// неправдой — ничего непригодного в них нет.
//
// Наблюдения с исходом «не определено» передаются наравне с остальными. Вес у
// них нулевой (5.7), но считаются они обязательно: высокая доля неопределённых
// поднимает требуемый объём наблюдений (5.5), и выбросить их значило бы
// скрыть, что измерению в этих условиях верить нельзя.
//
// Отбрасывание при переполнении очереди здесь не обрабатывается нарочно: это
// решение контура, и оно у него уже принято — потери считаются и видны в
// status. Писать о каждой потере в журнал значило бы шуметь ровно тогда, когда
// движок и без того перегружен.
func (o *outcomeObserver) ConnOutcome(c proxy.ConnOutcome) {
	if c.StrategyID == "" {
		return
	}
	// Цель берётся из выбора, а не из имени соединения: наблюдение относится к
	// цели радиуса. Если её нет, наблюдение неотносимо — контур посчитает его
	// непригодным, и это станет видно в status, вместо того чтобы попасть в
	// чужую оценку.
	o.sink.Observe(control.Observation{
		StrategyID: c.StrategyID,
		Target:     c.Target,
		Outcome:    c.Outcome,
		// Живой трафик: условия известны, стратегию выбирали мы, исход видели
		// сами. Это не пассивное наблюдение с пониженным весом (5.10) — то
		// придёт отдельно, из ретрансмиссий.
		Source: store.SourceLiveTraffic,
		Trial:  c.Trial,
		At:     c.At,
	})

	if o.archive == nil {
		return
	}
	// В журнал идёт то же наблюдение, но с полным составом полей: оценки в
	// памяти исчезнут при перезапуске, а наблюдение добыто живым соединением,
	// и повторить его нельзя (6.4).
	o.archive.Enqueue(store.Observation{
		At:         c.At,
		StrategyID: c.StrategyID,
		Target:     c.Target,
		VantageID:  o.vantage,
		// Быстрый уровень: исход выведен по рукопожатию, а не по форме полосы
		// (5.3). Медленный уровень на пользовательском трафике неприменим —
		// окно замера портит сам пользователь.
		Phase:           core.PhaseFast,
		Outcome:         c.Outcome,
		Reason:          c.Reason,
		Source:          store.SourceLiveTraffic,
		StrategyApplied: c.StrategyApplied,
		// Время установки соединения измеряет прокси; это ближайшее к RTT,
		// что известно о пользовательском соединении.
		RTT:         c.Connect,
		RTTMeasured: c.ConnectMeasured,
		// Скорость не измеряется намеренно: на пользовательском трафике окно
		// замера определяет пользователь, и полученное число говорило бы о
		// его поведении, а не о стратегии. Признак измерения поэтому ложен —
		// нулевая скорость иначе читалась бы как «очень медленно».
		ThroughputMeasured: false,
	})
}
