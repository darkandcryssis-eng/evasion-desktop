//go:build !windows

package main

// elevated на не-Windows возвращает «проверка не выполнялась».
//
// Сам движок предназначен для Windows (3.1), и понятие «права администратора»
// в его смысле есть только там: на этапе 1 они нужны для драйвера перехвата.
// На прочих ОС (здесь они служат только сборке и тестам) ответ о правах ничего
// не значил бы, поэтому checked = false — честнее, чем выдать выдуманное
// значение.
func elevated() (ok bool, checked bool) { return false, false }
