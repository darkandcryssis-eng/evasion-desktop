// Пакет scoring — бандит с затуханием: как оценивать стратегии и как их
// сравнивать.
//
// Зачем существует. Решаемая задача — не «настроить обход», а удержать его
// рабочим, когда работавшая стратегия перестала работать (1.1). Значит нужна
// оценка, которая забывает прошлое: стратегия, безупречная три дня назад, не
// должна выигрывать у сегодняшней только за счёт накопленной истории.
//
// Что знает: как превратить поток исходов в сопоставимые числа, сколько
// наблюдений нужно для доверия и когда претендент достаточно лучше
// действующего.
//
// Чего знать не должен: когда именно переключать (это control: там время и
// выдержка), как измерять (probe), где хранить (store). Пакет отвечает «какая
// лучше и можно ли ей верить», но не «пора ли менять».
//
// # Два разных числа, и путать их нельзя
//
// Оценка и доказательность — не одно и то же, и считаются они по-разному:
//
//	Score      затухающая взвешенная сумма исходов. Служит РАНЖИРОВАНИЮ:
//	           какая стратегия сейчас лучше. Забывает прошлое по полужизни.
//
//	Evidence   незатухающие количества наблюдений. Служит ПОРОГУ ДОВЕРИЯ:
//	           достаточно ли вообще данных, чтобы судить (5.5).
//
// Почему доказательность не затухает. Задание называет порог в наблюдениях:
// «база 20 наблюдений» (5.5). Если бы счёт затухал, двадцать наблюдений
// превратились бы в «двадцать условных единиц свежести», и смысл порога стал
// бы неочевиден, а при редких пробах порог оказался бы недостижим в принципе.
// Устаревание доказательств выражается отдельно — временем последнего
// наблюдения (признак freshness из 4.5), и это честнее: видно и сколько
// данных, и насколько они свежие.
//
// # Базовая линия: с чем сравнивается успех стратегии
//
// Третье число, без которого первые два лгут. Оценка отвечает «какая
// стратегия лучше», порог доверия — «хватает ли данных», но ни один из них не
// отвечает на вопрос, который важнее обоих: а блокировалась ли цель вообще.
//
// Базовая линия — наблюдения ПО ТОЙ ЖЕ ЦЕЛИ БЕЗ СТРАТЕГИИ (BaselineKey, ключ
// с пустым StrategyID). Лежит в той же таблице и по тем же правилам затухает,
// но в отборе стратегий не участвует (Rank её пропускает): она эталон, а не
// участник.
//
// Правило: исход стратегии значим лишь настолько, насколько он отличается от
// базовой линии той же цели. Выражено в EvaluatePromotion третьим условием —
// нижняя граница доли успехов стратегии обязана превышать ВЕРХНЮЮ границу
// базовой линии не меньше чем на BaselineMargin.
//
// Требования такого в задании нет: оно выведено из первого же измерения
// пробами. Стратегия прошла рукопожатие к discord.gg, и это выглядело первым
// положительным исходом в проекте — а эта цель отвечает и без стратегии.
// Последствия отсутствия правила хуже, чем кажется:
//
//   - бандит поднимает оценку стратегии за доступность цели;
//   - генератор (M7) принимает доступные цели за доказательство
//     работоспособности мутантов, то есть ищет по испорченной функции
//     приспособленности;
//   - движок тем увереннее в стратегии, чем меньше цель блокировалась.
//
// Отсутствие базовой линии НЕ означает её нулевого значения. Ноль означает
// «цель заблокирована» — сильнейший довод в пользу стратегии, и подменять им
// незнание нельзя (признак BaselineKnown). Без базовой линии повышения не
// происходит вовсе: цена названа — пока базовая проба по цели не отработала,
// кандидаты по ней стоят.
//
// Сравнение идёт с верхней границей, а не с наблюдённой долей, чтобы объём
// базовой линии регулировался самой статистикой и не потребовал ещё одного
// порога в конфиге. Подробнее — в BaselineUpperBound.
//
// # Почему «не определено» не входит в знаменатель
//
// Вес такого наблюдения равен нулю (5.7) — оно не учитывается вовсе. Если бы
// оно попадало в знаменатель доли успехов, стратегия с множеством
// неопределённых исходов выглядела бы неудачной, не будучи проверенной ни
// разу. Но считать их всё равно нужно: высокая доля неопределённых повышает
// требуемый объём наблюдений (5.5), потому что измерению в таких условиях
// нельзя доверять.
//
// # Все числа — из конфигурации
//
// Полужизнь, веса исходов, пороги и границы объёма заданы в Config. В коде нет
// ни одного из этих чисел (10.1): их подбор — вопрос наблюдения за работой
// движка, а не свойство алгоритма.
