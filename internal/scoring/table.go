// Key — ключ оценки.
//
// Это та самая четвёрка из 6.1 без времени: время живёт внутри оценки как
// затухание и как дата последнего наблюдения. Плоского ключа «стратегия» быть
// не может: поведение DPI различается между целями и операторами, и одна
// стратегия имеет столько оценок, сколько пар «цель × точка наблюдения».
type Key struct {
	StrategyID core.StrategyID
	Target     string
	VantageID  core.VantageID
}

// BaselineKey возвращает ключ базовой линии цели — наблюдений без стратегии.
//
// Базовая линия отвечает на вопрос, на который движок до сих пор не умел
// отвечать: жива ли цель сама по себе. Без неё положительный исход
// двусмыслен — стратегия получает кредит за цель, которая и не блокировалась.
//
// Ключ тот же, что у стратегий, с пустым StrategyID: так базовая линия
// затухает, копится и переживает перезапуск по тем же правилам, и второго
// механизма учёта в движке не появляется. Хранилище такое наблюдение уже
// допускает именно как базовую линию (store.Observation.StrategyID).
func BaselineKey(target string, vantage core.VantageID) Key {
	return Key{Target: target, VantageID: vantage}
}

// IsBaseline сообщает, что ключ описывает базовую линию, а не стратегию.
func (k Key) IsBaseline() bool { return k.StrategyID == "" }

// Estimate — оценка по одному ключу.
//
// Отдаётся копией: это снимок, по которому принимается решение, и он не должен
// меняться под принимающим.
type Estimate struct {
	Key Key

	// Score — затухающая взвешенная сумма исходов. Служит ранжированию.
	Score float64

	// Observations — всего учтённых наблюдений, НЕ затухая. Служит порогу
	// доверия (5.5): задание называет порог в наблюдениях, и затухающий счёт
	// сделал бы его недостижимым при редких пробах.
	Observations int
	// Successes — из них успешных.
	Successes int
	// Conclusive — из них определённых, то есть пригодных для доли успехов.
	//
	// Неопределённые в знаменатель не входят: иначе стратегия с множеством
	// неопределённых исходов выглядела бы неудачной, не будучи проверенной ни
	// разу (5.7, вес нулевой).
	Conclusive int
	// Inconclusive — сколько наблюдений оказались неопределёнными. Нужны
	// эскалации требуемого объёма (5.5): измерению в таких условиях нельзя
	// доверять.
	Inconclusive int

	// FailStreak — провалов подряд на текущий момент. Быстрый контур реакции:
	// ждать затухания оценки при срыве слишком долго.
	FailStreak int
	// Alternations — сколько раз исход менялся с успеха на неуспех и обратно.
	// Признак неустойчивости, повышающий требуемый объём (5.5).
	Alternations int

	// First, Last — время первого и последнего наблюдения. Last выражает
	// свежесть (4.5): оценка по старым наблюдениям недействительна, и видно
	// это именно по времени, а не по величине.
	First, Last time.Time
}

// SuccessRate возвращает наблюдённую долю успехов среди определённых исходов.
//
// Возвращает ноль при отсутствии определённых наблюдений: отсутствие данных не
// должно выглядеть ни успехом, ни провалом. Судить по доле без проверки объёма
// нельзя — для этого есть SuccessLowerBound.
func (e Estimate) SuccessRate() float64 {
	if e.Conclusive == 0 {
		return 0
	}
	return float64(e.Successes) / float64(e.Conclusive)
}

// InconclusiveShare возвращает долю неопределённых исходов среди всех.
func (e Estimate) InconclusiveShare() float64 {
	if e.Observations == 0 {
		return 0
	}
	return float64(e.Inconclusive) / float64(e.Observations)
}

// Table — оценки по всем ключам.
//
// Не потокобезопасна намеренно. Таблицей владеет единственная горутина
// контура управления, которая и обновляет оценки (4.2, правило 2). Мьютекс
// здесь создал бы ложное чувство безопасности: защитив отдельные обращения, он
// не защитил бы последовательность «прочитать оценку, решить, записать» — а
// именно в ней и возникают трудноуловимые ошибки вида «оценка обновилась
// посреди принятия решения».
type Table struct {
	cfg Config
	est map[Key]*Estimate
}

// NewTable создаёт таблицу оценок.
func NewTable(cfg Config) (*Table, error) {
	if err := cfg.validate(); err != nil {
		return nil, err
	}
	return &Table{cfg: cfg, est: make(map[Key]*Estimate)}, nil
}

// Config возвращает действующие параметры.
func (t *Table) Config() Config { return t.cfg }

// Reconfigure заменяет параметры оценки, сохраняя накопленные наблюдения.
//
// Нужна для перечитывания конфигурации без перезапуска (10.5): параметры
// автопилота задание требует применять на ходу. Пересоздать таблицу вместо
// этого нельзя — вместе с ней пропали бы все наблюдения, то есть ровно то, что
// движок добывает дороже всего.
//
// Цена, и она неустранима: накопленные оценки посчитаны по прежним весам и
// прежней полужизни, а новые параметры применятся к ним задним числом. Меняя
// полужизнь, владелец переосмысливает прошлое, а не только будущее. Количества
// наблюдений при этом не искажаются: они не взвешиваются и не затухают.
//
// Вызывается только горутиной-владельцем (таблица не потокобезопасна).
func (t *Table) Reconfigure(cfg Config) error {
	if err := cfg.validate(); err != nil {
		return err
	}
	t.cfg = cfg
	return nil
}

// Observe учитывает наблюдение.
//
// Порядок действий важен: сначала затухание до момента наблюдения, затем учёт
// вклада. Обратный порядок означал бы, что свежее наблюдение тоже затухает, то
// есть вклад зависел бы от того, когда таблицу обновляли, а не когда произошло
// событие.
//
// Наблюдения с временем раньше последнего учтённого не «оживляют» оценку:
// затухание к прошлому не применяется, иначе порядок поступления менял бы
// результат. Такое возможно при разборе накопленной истории.
func (t *Table) Observe(k Key, outcome core.Outcome, source store.Source, at time.Time) {
	e := t.est[k]
	if e == nil {
		e = &Estimate{Key: k, First: at, Last: at}
		t.est[k] = e
	}

	if at.After(e.Last) {
		e.Score *= t.decayFactor(at.Sub(e.Last))
		e.Last = at
	}
	if at.Before(e.First) {
		e.First = at
	}

	// Вес источника берётся из store: таблица весов одна для всего движка,
	// иначе разошедшиеся копии дали бы несопоставимые оценки (5.7).
	sourceWeight := float64(store.WeightPermille(source)) / 1000
	e.Score += t.cfg.weightOf(outcome) * sourceWeight

	// Пассивное наблюдение (5.10) НЕ ведёт быстрый контур срыва.
	//
	// FailStreak и Alternations — это «быстрая реакция» (5.7), счёт подряд без
	// веса. Пассивный сигнал (повтор ClientHello) для него непригоден: задание
	// прямо требует делать выводы «по накоплению, а не по единичному событию»
	// (5.10), потому что ретрансмиссия случается и от обычной потери пакета.
	// Поэтому пассив влияет на затухающую оценку (ранжирование и старение) и на
	// объём наблюдений, но серию провалов и чередования ведут только
	// контролируемые наблюдения — проба и живой трафик с выбранной нами
	// стратегией. Так случайная потеря пакета не вызовет мгновенную смену
	// стратегии, а накопление пассивных провалов всё равно опустит оценку.
	passive := source == store.SourcePassive

	e.Observations++
	switch outcome {
	case core.OutcomeInconclusive:
		// Не определено: в знаменатель доли не идёт, серию провалов не
		// продолжает и не обрывает. Такое наблюдение просто не состоялось как
		// проверка, и делать из него выводы нельзя ни в одну сторону.
		e.Inconclusive++
		return
	case core.OutcomeOK:
		e.Conclusive++
		e.Successes++
		if !passive {
			if e.FailStreak > 0 {
				e.Alternations++
			}
			e.FailStreak = 0
		}
	default:
		// Замедление и провал оба считаются неуспехом для доли успехов:
		// замедление отличается весом в оценке, но доступом не является.
		e.Conclusive++
		if !passive {
			if e.FailStreak == 0 && e.Conclusive > 1 {
				e.Alternations++
			}
			e.FailStreak++
		}
	}
}

// decayFactor возвращает множитель затухания за прошедшее время.
//
// Экспоненциальное затухание с заданной полужизнью: за HalfLife вклад
// уменьшается вдвое. Выражение через ln2 обязательно — простое деление дало бы
// линейное убывание, при котором старые наблюдения обнулялись бы скачком, а не
// постепенно.
func (t *Table) decayFactor(elapsed time.Duration) float64 {
	if elapsed <= 0 {
		return 1
	}
	return math.Exp(-math.Ln2 * elapsed.Seconds() / t.cfg.HalfLife.Seconds())
}

// Estimate возвращает оценку по ключу, приведённую к моменту now.
//
// Приведение обязательно: без него оценка стратегии, по которой давно нет
// наблюдений, осталась бы на прежней величине и выигрывала бы у свежей. Именно
// это и есть «забывание» — оно должно работать и когда наблюдений не
// поступает.
func (t *Table) Estimate(k Key, now time.Time) (Estimate, bool) {
	e := t.est[k]
	if e == nil {
		return Estimate{Key: k}, false
	}
	out := *e
	if now.After(out.Last) {
		out.Score *= t.decayFactor(now.Sub(out.Last))
	}
	return out, true
}

// SuccessLowerBound возвращает нижнюю границу доверительного интервала доли
// успехов по Уилсону.
//
// Почему именно Уилсон, а не обычное приближение по нормальному распределению.
// При малом числе наблюдений и доле, близкой к единице, обычное приближение
// даёт интервал, выходящий за пределы отрезка от нуля до единицы, и при трёх
// успехах из трёх объявляет нижнюю границу равной единице. Это ровно тот
// случай, который задание велит не допускать: короткую удачную серию легко
// набрать случайно (5.5). Интервал Уилсона при трёх из трёх даёт около 0.44 —
// то есть честно сообщает, что данных мало.
//
// Ноль при отсутствии определённых наблюдений: нет данных — нет доверия.
func (t *Table) SuccessLowerBound(k Key) float64 {
	e := t.est[k]
	if e == nil || e.Conclusive == 0 {
		return 0
	}
	return wilsonLowerBound(e.Successes, e.Conclusive, t.cfg.ConfidenceZ)
}

// Baseline возвращает базовую линию цели, приведённую к моменту now.
//
// Второй результат отличает «базовой линии нет» от «базовая линия нулевая».
// Различать обязательно: нулевая доля успехов означает «цель заблокирована» и
// является сильнейшим доводом в пользу стратегии, а отсутствие данных не
// означает ничего. Нулевое значение не подменяет отсутствие данных.
func (t *Table) Baseline(target string, vantage core.VantageID, now time.Time) (Estimate, bool) {
	return t.Estimate(BaselineKey(target, vantage), now)
}

// BaselineUpperBound возвращает верхнюю границу доверительного интервала доли
// успехов базовой линии.
//
// Второй результат ложен, когда определённых наблюдений без стратегии нет:
// сравнивать не с чем.
//
// Почему верхняя граница, а не наблюдённая доля. Сравнение с долей потребовало
// бы отдельного порога на объём базовой линии, и любое его значение было бы
// произвольным: 20 наблюдений (как у стратегий) заморозили бы повышение на
// часы, а одного наблюдения мало — единственный провал базовой пробы случается
// и при обычном обрыве, и по нему нельзя объявлять цель заблокированной.
// Верхняя граница решает это сама: при одном провале из одного она около 0.79,
// и кредита стратегии не даёт, а по мере накопления провалов опускается, и
// порог открывается. Объём учитывается самой статистикой, без второго числа в
// конфиге — тот же довод, по которому на стороне стратегии выбран Уилсон (5.5).
func (t *Table) BaselineUpperBound(target string, vantage core.VantageID) (float64, bool) {
	e := t.est[BaselineKey(target, vantage)]
	if e == nil || e.Conclusive == 0 {
		return 0, false
	}
	return wilsonUpperBound(e.Successes, e.Conclusive, t.cfg.ConfidenceZ), true
}

// wilsonLowerBound вычисляет нижнюю границу интервала Уилсона для доли.
//
// successes — число успехов, total — число испытаний, z — квантиль нормального
// распределения для нужного уровня доверия.
func wilsonLowerBound(successes, total int, z float64) float64 {
	center, margin, denom, ok := wilsonInterval(successes, total, z)
	if !ok {
		return 0
	}
	lower := (center - margin) / denom
	if lower < 0 {
		return 0
	}
	return lower
}

// wilsonUpperBound вычисляет верхнюю границу интервала Уилсона для доли.
//
// Нужна базовой линии: по ней судят, насколько цель может быть доступна сама
// по себе при имеющемся объёме наблюдений. Граница сверху, а не снизу, потому
// что сомнение здесь обязано работать против стратегии: пока о доступности
// цели известно мало, кредит стратегии не выдаётся.
func wilsonUpperBound(successes, total int, z float64) float64 {
	center, margin, denom, ok := wilsonInterval(successes, total, z)
	if !ok {
		return 0
	}
	upper := (center + margin) / denom
	if upper > 1 {
		return 1
	}
	return upper
}

// wilsonInterval считает части интервала Уилсона, общие для обеих границ.
//
// Выделено в одну функцию, чтобы арифметика жила в единственном месте:
// разойдясь, две копии дали бы интервал, у которого нижняя граница не
// соответствует верхней, и заметить это было бы нечем.
func wilsonInterval(successes, total int, z float64) (center, margin, denom float64, ok bool) {
	if total <= 0 {
		return 0, 0, 0, false
	}
	n := float64(total)
	phat := float64(successes) / n
	z2 := z * z

	// Центр интервала смещён к 1/2 тем сильнее, чем меньше наблюдений: это и
	// есть поправка, которой нет в обычном приближении.
	denom = 1 + z2/n
	center = phat + z2/(2*n)
	margin = z * math.Sqrt(phat*(1-phat)/n+z2/(4*n*n))
	return center, margin, denom, true
}

// RequiredObservations возвращает требуемый объём наблюдений для повышения.
//
// Порог адаптивный (5.5): база — нижняя граница, но объём поднимается до
// верхней, если измерению нельзя доверять. Причины эскалации независимы, и
// достаточно любой:
//
//   - исходы чередуются — признак неустойчивости, а не работающей стратегии;
//   - высокая доля неопределённых — измерение ненадёжно;
//   - обнаружен побочный вред — цена ошибки выше;
//   - стратегия ранее деградировала — однажды она уже обманула.
//
// Два последних признака таблице неизвестны: побочный вред измеряется по
// контрольным целям, а история деградаций хранится в журнале событий. Поэтому
// они передаются снаружи, а не выводятся здесь.
func (t *Table) RequiredObservations(k Key, hadCollateral, previouslyDegraded bool) int {
	e := t.est[k]
	if e == nil {
		return t.cfg.MinObservations
	}

	escalate := hadCollateral || previouslyDegraded
	if e.Alternations > 0 {
		escalate = true
	}
	if e.InconclusiveShare() >= t.cfg.InconclusiveShareEscalate {
		escalate = true
	}

	if escalate {
		return t.cfg.MaxObservations
	}
	return t.cfg.MinObservations
}

// PromotionDecision — решение о допуске кандидата к пробе на реальном трафике.
//
// Отдаётся вместе с причиной, а не одним признаком: «ещё не готов» и «проверен
// и плох» — разные состояния, и смешивать их нельзя. Первое означает «собирай
// данные», второе — «не трать на него бюджет».
type PromotionDecision struct {
	// Ready — порог пройден, кандидата можно допускать к доле реального
	// трафика (5.1).
	Ready bool
	// Required — сколько наблюдений требуется.
	Required int
	// Have — сколько есть.
	Have int
	// LowerBound — достигнутая нижняя граница доли успехов.
	LowerBound float64
	// Reason — машинно-читаемая причина отказа; пусто при Ready.
	Reason string

	// Baseline — верхняя граница доли успехов цели без стратегии.
	//
	// Осмысленна только при BaselineKnown. Ноль законен и означает «цель
	// заблокирована наглухо» — сильнейший довод в пользу стратегии, а не
	// отсутствие данных.
	Baseline float64
	// BaselineKnown — базовая линия цели измерена.
	//
	// Отдельный признак по тому же правилу, что StrategyApplied и
	// ThroughputMeasured: ноль в соседнем числовом поле законен, значит рядом
	// обязан стоять признак измерения. Без него «базовой линии нет»
	// читалось бы как «цель заблокирована», то есть выдавало бы стратегии
	// кредит ровно в том случае, когда о цели не известно ничего.
	BaselineKnown bool
	// BaselineObservations — сколько определённых наблюдений без стратегии
	// набрано. Для журнала и doctor: «почему кандидат не повышается» — законный
	// вопрос, и «базовой линии мало» должно быть видно числом.
	BaselineObservations int
}

// Причины отказа в повышении.
const (
	ReasonNotEnoughEvidence = "not_enough_evidence"
	ReasonLowerBoundTooLow  = "lower_bound_too_low"
	ReasonNoEstimate        = "no_estimate"
	// ReasonNoBaseline — базовой линии цели нет: неизвестно, блокируется ли
	// цель вообще, и приписывать стратегии успех не на чем.
	ReasonNoBaseline = "no_baseline"
	// ReasonNoBaselineAdvantage — цель доступна и без стратегии: успех
	// принадлежит цели, а не стратегии.
	ReasonNoBaselineAdvantage = "no_baseline_advantage"
	// ReasonBaselineNotPromotable — повышать пытаются саму базовую линию.
	// Признак дефекта вызывающего: базовая линия не стратегия.
	ReasonBaselineNotPromotable = "baseline_not_promotable"
)

// EvaluatePromotion решает, готов ли кандидат к допуску на реальный трафик.
//
// Проверяются ТРИ условия: объём наблюдений, статистическая граница и
// превосходство над базовой линией цели.
// Счёт «успехов подряд» не используется вовсе (5.5): короткую серию легко
// набрать случайно, и без порогов портфель наполнился бы фантомами.
//
// Третье условие — отдельное требование, которого в задании нет: оно выведено
// из первого же измерения пробами. Стратегия прошла рукопожатие к discord.gg, и
// это выглядело успехом, хотя та же цель отвечает и без стратегии. Без
// сравнения с базовой линией бандит поднимал бы оценку за чужую заслугу, а
// генератор (M7) принял бы доступные цели за доказательство работоспособности
// своих мутантов — то есть искал бы по испорченной функции приспособленности.
func (t *Table) EvaluatePromotion(k Key, hadCollateral, previouslyDegraded bool) PromotionDecision {
	if k.IsBaseline() {
		// Базовая линия не стратегия, применять её нельзя: «применить
		// отсутствие стратегии» означает прозрачный пропуск, и повышать тут
		// нечего. Отказ явный, а не тихий: молчаливое согласие означало бы,
		// что эталон попал в отбор, то есть дефект вызывающего остался бы
		// незамеченным (4.7 п. 2 — отказывать явной ошибкой).
		return PromotionDecision{
			Required: t.cfg.MinObservations,
			Reason:   ReasonBaselineNotPromotable,
		}
	}

	e := t.est[k]
	if e == nil {
		return PromotionDecision{
			Required: t.cfg.MinObservations,
			Reason:   ReasonNoEstimate,
		}
	}

	required := t.RequiredObservations(k, hadCollateral, previouslyDegraded)
	lower := t.SuccessLowerBound(k)
	d := PromotionDecision{
		Required:   required,
		Have:       e.Observations,
		LowerBound: lower,
	}

	// Объём считается по ВСЕМ наблюдениям, включая неопределённые: они тоже
	// потратили бюджет живых прогонов. Но на долю успехов они не влияют, и
	// при их обилии порог уже поднят эскалацией.
	if e.Observations < required {
		d.Reason = ReasonNotEnoughEvidence
		return d
	}
	if lower <= t.cfg.PromoteLowerBound {
		d.Reason = ReasonLowerBoundTooLow
		return d
	}

	// Базовая линия проверяется последней: сначала стратегия обязана доказать
	// себя, и только потом — что доказала именно она, а не доступность цели.
	// Порядок выбран по полезности причины для человека: у кандидата с двумя
	// наблюдениями честный ответ «доказательств мало», а не «нет базовой
	// линии».
	baseline, known := t.BaselineUpperBound(k.Target, k.VantageID)
	d.Baseline = baseline
	d.BaselineKnown = known
	if b := t.est[BaselineKey(k.Target, k.VantageID)]; b != nil {
		d.BaselineObservations = b.Conclusive
	}
	if !known {
		// Неизвестно, блокируется ли цель вообще. Отказ, а не допуск: принять
		// отсутствие базовой линии за нулевую означало бы выдать стратегии
		// кредит именно тогда, когда о цели не известно ничего.
		//
		// Цена названа прямо: пока базовая проба по цели не отработала, ни
		// один кандидат по ней не повышается. Расплата приемлема — базовая
		// проба идёт тем же расписанием и стоит одно соединение, а по
		// деградированной цели ещё и чаще (5.7).
		d.Reason = ReasonNoBaseline
		return d
	}
	if lower-baseline < t.cfg.BaselineMargin {
		// Цель доступна и без стратегии: засчитывать ей этот успех не за что.
		d.Reason = ReasonNoBaselineAdvantage
		return d
	}

	d.Ready = true
	return d
}

// Broken сообщает, что стратегия сорвалась: провалов подряд не меньше порога.
//
// Быстрый контур реакции отдельно от затухания (5.7): пока оценка затухает,
// пользователь уже сидит без доступа. Поэтому срыв определяется по
// последовательности, а не по величине оценки.
func (t *Table) Broken(k Key) bool {
	e := t.est[k]
	return e != nil && e.FailStreak >= t.cfg.FailureStreak
}

// Ranked — стратегия с её оценкой в упорядоченном списке.
type Ranked struct {
	Estimate
}

// Rank возвращает оценки для цели и точки наблюдения по убыванию оценки.
//
// Порядок устойчив: при равных оценках сравниваются идентификаторы. Без этого
// список менялся бы от запуска к запуску, потому что обход карты в Go
// намеренно случаен, — и выбор стратегии стал бы невоспроизводимым.
//
// Базовая линия в список не входит. Она эталон, а не участник отбора: попав в
// ранжирование, она была бы выбрана как стратегия — на доступной цели с
// лучшей оценкой, чем у любой настоящей стратегии, — и движок «применил бы»
// отсутствие стратегии, приписав ей чужой успех. Это ровно та подмена, против
// которой базовая линия и введена.
func (t *Table) Rank(target string, vantage core.VantageID, now time.Time) []Ranked {
	var out []Ranked
	for k := range t.est {
		if k.Target != target || k.VantageID != vantage {
			continue
		}
		if k.IsBaseline() {
			continue
		}
		e, _ := t.Estimate(k, now)
		out = append(out, Ranked{Estimate: e})
	}
	sort.Slice(out, func(i, j int) bool {
		if out[i].Score != out[j].Score {
			return out[i].Score > out[j].Score
		}
		return out[i].Key.StrategyID < out[j].Key.StrategyID
	})
	return out
}

// Challenger возвращает претендента, который достаточно лучше действующей
// стратегии.
//
// «Достаточно» задано порогом превосходства (5.7): без него автопилот менял бы
// стратегию на каждое случайное колебание оценки. Порог проверяется по
// разности оценок, а не по отношению: оценка может быть отрицательной, и
// отношение при переходе через ноль теряет смысл.
//
// Пустой текущий идентификатор означает, что действующей стратегии нет: тогда
// претендентом становится лучший из имеющихся без всякого порога — хуже, чем
// ничего, он быть не может.
func (t *Table) Challenger(target string, vantage core.VantageID, current core.StrategyID, now time.Time) (Ranked, bool) {
	ranked := t.Rank(target, vantage, now)
	if len(ranked) == 0 {
		return Ranked{}, false
	}

	best := ranked[0]
	if current == "" {
		return best, true
	}
	if best.Key.StrategyID == current {
		return Ranked{}, false
	}

	cur, ok := t.Estimate(Key{StrategyID: current, Target: target, VantageID: vantage}, now)
	if !ok {
		// О действующей стратегии нет наблюдений: сравнивать нечем, и
		// подменять её на этом основании нельзя. Это не застой — наблюдения
		// по действующей стратегии поступают с живого трафика постоянно, и
		// их отсутствие само означает неполадку.
		return Ranked{}, false
	}
	if best.Score-cur.Score < t.cfg.SuperiorityMargin {
		return Ranked{}, false
	}
	return best, true
}

// Evidence — сводка наблюдений об одной стратегии в одной точке наблюдения,
// по всем целям сразу.
//
// Нужна признаку freshness из 4.5 и выводу doctor (5.9: «состояние портфеля:
// сколько стратегий, в каких статусах, их свежесть»). Статус у стратегии один,
// значит и свежесть у неё должна быть одна — а оценки ключуются целью, и по
// отдельности каждая отвечает только про свою цель.
type Evidence struct {
	// Observations — всего наблюдений о стратегии по всем целям этой точки
	// наблюдения.
	//
	// ВНИМАНИЕ: это сумма по целям, и сравнивать её с порогом повышения
	// нельзя. Порог (5.5) задан на пару «цель × точка наблюдения», и
	// стратегия с двадцатью наблюдениями, размазанными по десяти целям, порога
	// не прошла ни на одной. Поле существует для ответа на вопрос «сколько
	// движок вообще знает об этой стратегии», а не для решений.
	Observations int
	// Targets — по скольким целям есть наблюдения. Без этого числа
	// Observations вводит в заблуждение: двадцать наблюдений по одной цели и
	// по двадцати целям — разные состояния знания.
	Targets int
	// Last — время последнего наблюдения о стратегии. Это и есть свежесть:
	// оценка по старым наблюдениям недействительна, и видно это по времени, а
	// не по величине (4.5).
	//
	// Нулевое время означает «наблюдений нет вовсе» и законно: стратегия
	// могла только что попасть в портфель.
	Last time.Time
}

// Evidence собирает сводку наблюдений о стратегии.
//
// Обход всех ключей таблицы, а не карты по стратегии: вторая карта означала бы
// второй источник одних данных, который рано или поздно разойдётся с первым.
// Стоимость не важна — функция вызывается при сборке состояния (раз в
// секунды), а не на горячем пути.
//
// Базовая линия сюда попасть не может: у неё пустой идентификатор, а пустой
// идентификатор стратегией не является.
func (t *Table) Evidence(id core.StrategyID, vantage core.VantageID) Evidence {
	var ev Evidence
	if id == "" {
		return ev
	}
	for k, e := range t.est {
		if k.StrategyID != id || k.VantageID != vantage {
			continue
		}
		ev.Observations += e.Observations
		ev.Targets++
		if e.Last.After(ev.Last) {
			ev.Last = e.Last
		}
	}
	return ev
}

// Len возвращает число ключей в таблице.
func (t *Table) Len() int { return len(t.est) }

// Forget удаляет оценку по ключу.
//
// Нужен выводу стратегии: держать оценку выведенной стратегии незачем, а
// расти без предела таблица не должна.
func (t *Table) Forget(k Key) { delete(t.est, k) }
