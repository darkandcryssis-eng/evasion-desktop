// Пакет quicwatch накапливает признак «приложение работает только по QUIC».
//
// Зачем существует. Блокировка QUIC (3.3) роняет исходящие QUIC Initial к
// доменам радиуса, чтобы приложение откатилось на TCP, где работает десинк. Но
// часть приложений на TCP не откатывается — для них блокировка означает потерю
// связи, а не откат. Задание требует, чтобы doctor об этом сообщал (3.3, 5.9).
// Определить такое одним снимком нельзя: нужен накопленный за время работы
// сигнал, как и у пассивного наблюдения (5.10).
//
// Что пакет знает: по каждому имени сервера (SNI) из радиуса — сколько QUIC
// Initial сброшено, когда последний раз, и видели ли после этого TCP
// ClientHello с тем же именем (признак состоявшегося отката). Чего знать не
// должен: самих стратегий, оценок, политики — это чистый счётчик наблюдений,
// отдельный от контура управления, поэтому его можно вести на этапе 1, не
// трогая control (4.7 п. 4).
//
// Эвристика честна ровно настолько, насколько честен её источник: приложение
// могло просто не повторить запрос или уйти на TCP под другим именем. Поэтому
// вывод — «по признакам», накоплением (MinDrops), и в doctor он warn, а не fail.
