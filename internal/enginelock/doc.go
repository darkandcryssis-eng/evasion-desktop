// Пакет enginelock обеспечивает, что в системе одновременно работает ровно
// один экземпляр движка (или несколько — но на непересекающихся фильтрах
// WinDivert).
//
// Зачем существует. Два movok-engine, слушающих одни и те же пакеты, не
// усиливают обход — они его ломают: десинк накладывается сам на себя, часть
// сегментов уходит дважды, часть — после битых сумм, DPI вместо
// «запутанного рукопожатия» получает «обрыв по RST» (`net_error -101`),
// соединение зависает на `AUTHENTICATING`. Это один из самых частых случаев
// «ничего не работает» в прежних итерациях, пока проблему не поймали.
//
// Прежняя защита — `taskkill /F /IM evasion.exe` в `scripts\start-discord.bat`.
// Обходится: прямой запуск `evasion.exe run` минует лаунчер, и защита не
// срабатывает.
//
// Инвариант 1.1 блюпринта (`docs/ARCHITECTURE.md`) требует: защита — на уровне
// самого бинарника, а не на уровне скрипта.
//
// Как устроено. Lock-файл `state/engine.lock` держит JSON-слепок текущих
// запусков: массив `{pid, filter, started_at}`. На старте:
//
//  1. Читаем файл. Для каждой записи проверяем, что процесс с таким `pid`
//     ЕЩЁ ЖИВ (на Windows — `OpenProcess`, на не-Windows — `syscall.Kill(pid, 0)`).
//     Мёртвые записи выбрасываем — предыдущий процесс умер нештатно.
//  2. Если среди живых есть запись с конфликтующим фильтром, Acquire
//     отказывает с внятным сообщением (`уже запущен pid %d на фильтре %s`).
//     «Конфликтующий» = в точности совпадающий, либо тот, что ловит хотя бы
//     один общий пакет (это упрощение: продуктовый и песочный фильтры у
//     автопилота — разные по порту и не конфликтуют, остальные — считаем
//     конфликтом).
//  3. Если конфликта нет, добавляем свою запись и переписываем файл.
//
// На корректной остановке Release убирает свою запись. На аварийной остановке
// (крэш) запись остаётся, но проверка живости следующим процессом её
// выбросит.
//
// Намеренно НЕ используется OS-level advisory lock (`LockFileEx`/`flock`): они
// не позволяют нескольким легитимным экземплярам (продуктив + песочница у
// `--auto`), и их семантика на Windows не ровно та, что нужна. PID-подход
// гибче и работает одинаково на всех платформах, которых достаточно для
// тестов.
