//go:build !windows

package control

// transientIO на не-Windows всегда ложно: временных неудач этого рода здесь не
// бывает.
//
// Переименование на Unix заменяет файл независимо от того, читает ли его
// кто-то, а открытый файл остаётся доступным читателю по дескриптору даже
// после замены. Поэтому столкновения писателя и читателя состояния, из-за
// которого на Windows нужны повторы, здесь не существует как явления.
//
// Возвращать истину «на всякий случай» нельзя: тогда настоящая неполадка
// (нет каталога, нет прав, диск заполнен) молча повторялась бы пять раз
// вместо того, чтобы сразу назвать причину.
func transientIO(error) bool { return false }
