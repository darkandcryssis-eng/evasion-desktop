package control

import (
	"errors"
	"fmt"
	"time"
)

// Config задаёт параметры контура управления.
//
// Здесь ровно одно число, и это сделано нарочно. Все пороги, по которым
// решается «лучше ли» и «можно ли верить», принадлежат scoring и берутся из
// его конфигурации (10.1); продублировать их здесь значило бы завести второй
// набор, который рано или поздно разойдётся с первым. Контуру управления
// нужна лишь одна величина, которой у scoring нет и быть не может, —
// минимальное время жизни применённой стратегии.
type Config struct {
	// MinDwell — сколько держать применённую стратегию, прежде чем её можно
	// будет сменить на претендента.
	//
	// Зачем нужна, если есть порог превосходства. Порог превосходства
	// защищает от шума в оценке: претендент должен быть заметно лучше. Но две
	// стратегии могут быть по-настоящему близки и по-настоящему чередоваться
	// — тогда порог проходится то в одну, то в другую сторону, и автопилот
	// начинает дёргать снимок. Выдержка ограничивает частоту смен по времени,
	// а не по величине, и этим закрывает случай, который порогу недоступен.
	//
	// На срыв стратегии выдержка не распространяется: см. doc.go.
	MinDwell time.Duration

	// TrialPermille — доля реальных соединений, отдаваемая проверяемой
	// стратегии, в промилле (50 = 5%, значение из 5.7).
	//
	// Ноль означает «проверок на живом трафике нет»: законная настройка для
	// того, кто не хочет рисковать вовсе, но тогда ступень testing недостижима
	// и обучение идёт только с проб.
	TrialPermille int

	// BlackoutTrialPermille — доля проверки при полном обвале портфеля (5.8).
	//
	// Задание разрешает поднять долю эксперимента, когда не работает ничего:
	// риск эксперимента в этом состоянии уже ничего не ухудшает, потому что
	// ухудшать нечего. Это единственный разрешённый способ превысить жёсткий
	// потолок из 5.7, и действует он только пока обвал продолжается.
	BlackoutTrialPermille int
}

// trialPermilleCeiling — жёсткий потолок доли проверки в обычной работе.
//
// Задание называет 5% именно потолком, а не значением по умолчанию («потолок
// жёсткий», 5.7), поэтому проверка запрещает настроить больше, а не только
// подставляет 50 по умолчанию. Цена: владелец, пожелавший рискнуть десятью
// процентами в обычной работе, не сможет сделать это настройкой — и это
// сознательно, потому что ровно так доля проверки и расползается. Повышение
// разрешено только при обвале портфеля (5.8).
const trialPermilleCeiling = 50

// DefaultConfig возвращает значения по умолчанию.
//
// Четверть часа — осознанный компромисс: достаточно долго, чтобы смена
// стратегии успела отразиться в наблюдениях, и достаточно коротко, чтобы
// пользователь не сидел с неудачным выбором полдня. Величина принадлежит
// конфигурации, и подбирать её придётся по работе движка, а не выводить из
// рассуждений.
func DefaultConfig() Config {
	return Config{
		MinDwell:      15 * time.Minute,
		TrialPermille: trialPermilleCeiling,
		// Четверть трафика при обвале (5.8): когда не работает ничего,
		// эксперимент не ухудшает положения, но и отдавать ему всё незачем.
		//
		// Почему не больше — проверено живым прогоном, а не рассуждением.
		// Доля 90% давала рабочий обход на старте, но ЗАГРЯЗНЯЛА измерение
		// песочницы: DPI держит состояние по IP источника (5.4), и когда десинк
		// применён к большей части трафика, цель переходит в «расслабленный»
		// режим, а базовая проба без десинка едет на нём и показывает ложный
		// успех (в прогоне baseline youtube доходил до 56% при заблокированной
		// цели). Загрязнённая базовая линия закрывает повышение: ни один
		// кандидат её не превосходит, порог растёт до потолка, и движок
		// застревает в обвале, не переходя в active. Вдобавок поток десинка в
		// таком объёме, похоже, делает DPI агрессивнее (успех кандидатов падал
		// 6/6 → 4/6). Остальные три четверти прозрачны — по ним измеряется
		// честная базовая линия и видно, что сеть жива.
		//
		// Цена низкой доли: пока кандидат не дошёл до active, страница с
		// множеством запросов (youtube: ytimg.com, googlevideo.com) на четверти
		// соединений грузится неполно. Это окно прогрева, а не постоянный
		// режим: на чистом измерении кандидат добирает порог и переходит на
		// весь трафик. Для мгновенного полного обхода есть фиксированная
		// стратегия (run без --auto). Величина — в конфиге.
		BlackoutTrialPermille: 250,
	}
}

// validate проверяет согласованность параметров.
//
// Нулевая выдержка не запрещена ошибкой компиляции, но запрещена здесь:
// формально она означает «меняй когда угодно», а фактически — что защиты от
// дребезга нет вовсе. Такую настройку надо задавать явно малым числом, а не
// незаполненным полем, иначе забытый Config выглядел бы как осознанный выбор.
func (c Config) validate() error {
	switch {
	case c.MinDwell <= 0:
		return errors.New("control: минимальная выдержка должна быть положительной")
	case c.TrialPermille < 0:
		return fmt.Errorf("control: доля проверки %d промилле отрицательна", c.TrialPermille)
	case c.TrialPermille > trialPermilleCeiling:
		return fmt.Errorf("control: доля проверки %d промилле выше жёсткого потолка %d (5.7)",
			c.TrialPermille, trialPermilleCeiling)
	case c.BlackoutTrialPermille < c.TrialPermille:
		return fmt.Errorf("control: доля проверки при обвале %d промилле меньше обычной %d",
			c.BlackoutTrialPermille, c.TrialPermille)
	case c.BlackoutTrialPermille > 1000:
		return fmt.Errorf("control: доля проверки при обвале %d промилле больше 1000",
			c.BlackoutTrialPermille)
	}
	return nil
}
