// Пакет control — контур управления: когда менять стратегию и на какую.
//
// Зачем существует. Оценивать стратегии умеет scoring, применять — policy, но
// между «эта стратегия лучше» и «меняем прямо сейчас» лежит отдельное
// решение, и оно не статистическое. Переключение стоит денег: соединения,
// открытые в этот момент, доигрывают по прежнему снимку, а исход переключения
// станет известен не раньше, чем наберутся наблюдения. Поэтому менять надо
// редко, по доказанному поводу и с объяснимой причиной.
//
// Что знает: какие цели входят в радиус, что применено сейчас и с какого
// времени, что говорят оценки, что закреплено человеком вручную.
//
// Чего знать не должен: как считается оценка (scoring), как устроено
// сопоставление имён (policy), как измеряется исход (probe), где лежит архив
// (store). Решение «пора» здесь, арифметика «лучше» — в scoring.
//
// # Этот файл описывает только чистую половину
//
// Пакет делается в два приёма, и сейчас готов первый: Decider — решение без
// горутин, каналов и часов. Время приходит входным параметром, таблица оценок
// передаётся явно, результат — значение. Такое решение проверяется
// детерминированно и целиком, без сети и без ожиданий.
//
// Это сделано не ради красоты. Положительного сигнала у движка сейчас нет
// вовсе: без сторонних средств у владельца заблокировано почти всё, и
// проверить автопилот на живом сигнале будет нечем до этапа 1. Значит
// единственный способ отвечать за эту логику — вынести её туда, где её можно
// проверить подставленными оценками и поддельным временем.
//
// Вторым приёмом придёт горутина-владелец: тикер, канал команд, приём
// наблюдений, публикация снимка через policy.Table.Install. Там появятся
// вопросы, которых здесь нет намеренно, — расписание проб и поведение при
// переполнении очереди наблюдений.
//
// # Лестница допуска, и почему прыгать по ней нельзя
//
// Задание задаёт ступени (5.1), и каждая открывается своим условием:
//
//	candidate   только соединения, которые движок инициирует сам.
//	            Риск для пользователя нулевой.
//	testing     доля реальных соединений (по умолчанию 5%). Открывается
//	            порогом 5.5: объём наблюдений и нижняя граница доли успехов.
//	active      весь трафик цели. Открывается превосходством над действующей
//	            стратегией плюс тем же порогом доверия.
//	benched     не применяется, оценка продолжает затухать. Это резерв, из
//	            которого берут замену (5.8).
//
// Прыжок candidate → active запрещён, и это не формальность: порог 5.5
// открывает долю трафика, а не весь трафик. Проскочив ступень проверки,
// стратегия попала бы на весь трафик по доказательствам, собранным пробами, —
// то есть по измерениям, сделанным не в тех условиях, в которых ей предстоит
// работать. Ровно от этого ступенчатое допущение и защищает.
//
// Обратная дорога есть только у degraded, и только через долю: сорвавшаяся
// стратегия возвращается проверкой на малой доле с повышенным порогом объёма.
// Без обратной дороги портфель истощался бы с каждым сбоем сети, а задание
// требует удерживать доступ именно в таких случаях (1.1).
//
// Побочный вред (4.5) запрещает обе ступени сразу, а не только active. Задание
// требует мгновенного откатa по побочному вреду (5.1), а «мгновенный откат» и
// «продолжаем проверять на пяти процентах» — противоположные вещи. Снимает
// запрет только явное разрешение владельца; закрепление стратегии считается
// таким разрешением, потому что это и есть его осознанная команда.
//
// # Полный обвал портфеля
//
// Если в радиусе не осталось ни одной действующей стратегии, план помечается
// признаком обвала (5.8): трафик идёт прозрачным пропуском, а доля проверки
// повышается — когда не работает ничего, риск эксперимента уже ничего не
// ухудшает. Признак отдаётся данными, а не записью в лог, потому что на него
// обязаны реагировать и status, и тревога, а не только человек, читающий
// журнал.
//
// Свежий движок, у которого ещё нет доказанных стратегий, под определение
// обвала тоже попадает. Это намеренно: действия в обоих случаях одни и те же,
// а состояние «движок сейчас не применяет ничего» в status обязано быть видно
// и там, и там.
//
// # Порядок правил, и почему он именно такой
//
// Правила проверяются в фиксированном порядке, и порядок — это решение, а не
// следствие записи:
//
//  1. Закрепление. Человек сказал «применяй вот это» — применяем, не спрашивая
//     статистику.
//  2. Срыв действующей стратегии. Реагируем немедленно, даже если выдержка не
//     истекла.
//  3. Выдержка. Применённую стратегию держим не меньше MinDwell.
//  4. Претендент и порог доверия. Меняем только на проверенную и достаточно
//     лучшую.
//
// Срыв стоит выше выдержки сознательно. Выдержка защищает от дребезга, но
// дребезг — неприятность, а сорвавшаяся стратегия означает, что пользователь
// сидит без доступа прямо сейчас. Ждать истечения выдержки в этом случае
// значило бы предпочесть опрятность графика переключений работоспособности
// (5.7: быстрый контур реакции отдельно от затухания).
//
// # Непроверенная стратегия на живой трафик не попадает
//
// Претендент допускается к пользовательскому трафику только через
// scoring.EvaluatePromotion, то есть по объёму наблюдений и нижней границе
// доли успехов (5.1, 5.5). Данные для этого набираются пробами, а не
// пользователем: исследование — дело probe, а не чужих соединений.
//
// Цена этого правила высока и видна уже сейчас. Пока положительного сигнала
// нет, ни один претендент порог не пройдёт, и автопилот честно не применит
// ничего. Именно для этого случая существует закрепление: оно обходит пороги
// и позволяет работать по стратегии, выбранной человеком, пока движок не
// набрал собственных доказательств.
//
// # Базовая проба: с чем сравнивается успех
//
// Контур просит пробы не только о стратегиях, но и о каждой цели БЕЗ стратегии
// (ProbeItems выдаёт по одной записи с признаком Baseline на цель, всегда — в
// том числе при пустом портфеле). Без этой записи положительный исход
// двусмыслен: движок не отличает «стратегия обошла DPI» от «цель и так не
// блокировалась», и порог повышения открывался бы на доступных целях сам
// собой. Правило сравнения принадлежит scoring, здесь — только добыча данных
// для него.
//
// Следствие, которое надо знать при чтении решений: на цели, доступной без
// стратегии, автопилот не применит ничего и назовёт причиной not_promotable с
// разбором no_baseline_advantage внутри. Это правильный итог, а не застой.
// Закрепление по-прежнему выше этого правила, как и выше всех прочих: базовая
// линия ограничивает автопилот, а не человека.
//
// # Каждая цель радиуса получает ровно одну запись
//
// План всегда описывает радиус целиком: у цели либо стратегия, либо запись-
// исключение. Пропускать цель, которой нечего применять, нельзя — тогда на
// неё подействовала бы запись более общего домена из того же радиуса, и
// «выключено» молча означало бы «применено что-то другое». Это прямое
// следствие того, что policy выбирает более точную запись.
