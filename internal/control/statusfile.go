package control

import (
	"bytes"
	"encoding/json"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"time"
)

// bytesReader — короткая обёртка, чтобы строгий разбор читал из памяти.
func bytesReader(data []byte) io.Reader { return bytes.NewReader(data) }

// Повторы обращения к файлу состояния при временной неудаче.
//
// Зачем они нужны — свойство Windows, которого нет на Unix. Там переименование
// заменяет файл независимо от того, читает ли его кто-то; в Windows открытый
// файл замену блокирует, а открытие файла в момент замены даёт ошибку
// «процесс не может получить доступ к файлу, так как он занят другим
// процессом». Страдают обе стороны: писатель теряет обновление состояния,
// читатель (команда status) получает невнятную ошибку вместо состояния.
//
// Вероятность столкновения стала заметной после того, как состояние начали
// выкладывать по таймеру раз в две секунды, а не раз в минуту при пересчёте:
// окно расширилось примерно в тридцать раз, и прогон на машине владельца
// поймал столкновение с первого же запуска.
//
// Значения: пять попыток по 20 мс дают четверть секунды терпения при записи
// файла, занимающей единицы миллисекунд. Этого с большим запасом хватает,
// чтобы переждать чужое обращение, и при этом команда status не выглядит
// подвисшей, если дело в чём-то другом.
const (
	statusAttempts   = 5
	statusRetryDelay = 20 * time.Millisecond
)

// retryTransient повторяет обращение к файлу, пока неудача выглядит временной.
//
// Предикат передаётся параметром, а не берётся из пакета, по двум причинам:
// распознавание временных ошибок зависит от платформы (см. transientIO), а
// сама логика повторов — нет, и проверяться она обязана на любой машине. Тот
// же приём, что с pickMinRTT и parseServiceQuery.
//
// Возвращается последняя ошибка: пересказывать историю попыток незачем, а вот
// подменять настоящую причину словами «не удалось за 5 попыток» нельзя —
// потребителю нужна именно причина.
func retryTransient(attempts int, delay time.Duration, transient func(error) bool, op func() error) error {
	var err error
	for i := range attempts {
		err = op()
		if err == nil || !transient(err) {
			return err
		}
		// После последней попытки спать незачем.
		if i < attempts-1 {
			time.Sleep(delay)
		}
	}
	return err
}

// WriteStatusFile записывает состояние движка в файл.
//
// Зачем файл. Команда status обязана показывать состояние РАБОТАЮЩЕГО движка
// (2.3), а запускается она отдельным процессом. Полноценный канал управления
// (именованный канал или локальный порт) — это отдельная поверхность со своей
// безопасностью и своим жизненным циклом; на этапе 0 она не нужна, а файл даёт
// то же самое ценой одной записи на пересчёт.
//
// Цена, и её надо знать. Состояние в файле свежо настолько, насколько свеж
// последний пересчёт: это снимок, а не запрос к движку. Поэтому в нём есть
// PlannedAt, и потребитель всегда может увидеть, насколько данные устарели,
// вместо того чтобы догадываться. Запросы «прямо сейчас» появятся вместе с
// каналом управления, когда он понадобится.
//
// Запись атомарна: сначала во временный файл рядом, затем переименование.
// Иначе читатель однажды увидел бы половину JSON и решил, что движок сломан.
func WriteStatusFile(path string, st Status) error {
	data, err := json.MarshalIndent(st, "", "  ")
	if err != nil {
		return fmt.Errorf("control: сериализация состояния: %w", err)
	}
	data = append(data, '\n')

	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return fmt.Errorf("control: каталог состояния %s: %w", dir, err)
	}

	// Временный файл создаётся в том же каталоге: переименование атомарно
	// только внутри одной файловой системы.
	tmp, err := os.CreateTemp(dir, ".status-*")
	if err != nil {
		return fmt.Errorf("control: временный файл состояния: %w", err)
	}
	tmpName := tmp.Name()
	defer os.Remove(tmpName) // при успехе файла уже нет, ошибка здесь не важна

	if _, err := tmp.Write(data); err != nil {
		tmp.Close()
		return fmt.Errorf("control: запись состояния: %w", err)
	}
	if err := tmp.Close(); err != nil {
		return fmt.Errorf("control: закрытие состояния: %w", err)
	}
	// Windows не заменяет существующий файл переименованием молча, поэтому
	// os.Rename здесь делает именно замену (Go использует MoveFileEx с флагом
	// замены). На Unix переименование заменяет файл по умолчанию.
	//
	// Повторы нужны только Windows: там читатель, держащий файл открытым,
	// блокирует замену. Без них обновление состояния терялось бы каждый раз,
	// когда человек запустил status в неудачный момент, — и терялось бы
	// молча, если не считать записи в журнале.
	err = retryTransient(statusAttempts, statusRetryDelay, transientIO, func() error {
		return os.Rename(tmpName, path)
	})
	if err != nil {
		return fmt.Errorf("control: замена файла состояния: %w", err)
	}
	return nil
}

// ReadStatusFile читает состояние движка из файла.
//
// Нужен командам status и portfolio. Разбор строгий: неизвестное поле —
// ошибка, потому что иначе CLI, собранный из другой версии, показывал бы
// неполное состояние как полное.
func ReadStatusFile(path string) (Status, error) {
	// Повторы нужны только Windows: открытие файла в тот самый миг, когда
	// движок его заменяет, даёт ошибку совместного доступа. Без них команда
	// status время от времени отвечала бы «процесс не может получить доступ к
	// файлу» вместо состояния, то есть выглядела бы поломкой движка там, где
	// надо было подождать миллисекунду.
	//
	// Открывать файл с флагом FILE_SHARE_DELETE, чтобы не мешать замене, было
	// **попробовано и не сработало**: прогон на машине владельца показал, что
	// MoveFileEx с заменой отказывает (код 5, «отказано в доступе»), пока файл
	// открыт, независимо от флагов совместного доступа у читателя. Код с
	// опровергнутым обоснованием убран; остались повторы, которые работают.
	//
	// «Файла нет» временной ошибкой не считается и повторяться не будет:
	// движок не запущен — это полноценный ответ, и ждать его бессмысленно.
	var data []byte
	err := retryTransient(statusAttempts, statusRetryDelay, transientIO, func() error {
		var rerr error
		data, rerr = os.ReadFile(path)
		return rerr
	})
	if err != nil {
		return Status{}, fmt.Errorf("control: чтение состояния %s: %w", path, err)
	}
	var st Status
	dec := json.NewDecoder(bytesReader(data))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&st); err != nil {
		return Status{}, fmt.Errorf("control: разбор состояния %s: %w", path, err)
	}
	return st, nil
}
