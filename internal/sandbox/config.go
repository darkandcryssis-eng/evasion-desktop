package sandbox

import (
	"fmt"
	"runtime"
	"strconv"
	"time"
)

// Config задаёт параметры контура песочницы. Значения принадлежат конфигурации
// движка (10.1); здесь — их проверка и значения по умолчанию.
type Config struct {
	// PortLo, PortHi — выделенный диапазон локальных портов (включительно).
	//
	// Берётся вне динамического диапазона Windows (49152–65535), который ОС
	// раздаёт исходящим соединениям автоматически: так проба песочницы не
	// столкнётся с портом, который ОС выдала пользовательскому соединению, и
	// разделение по порту остаётся честным. Абсолютной гарантии нет —
	// приложение вправе явно занять любой порт, — но автоматические коллизии
	// исключены.
	PortLo uint16
	PortHi uint16

	// Workers — глобальный предел одновременных проб (5.4). За некоторым
	// пределом параллельность портит измерение, а не ускоряет его: много
	// одновременных соединений к одной цели — необычный рисунок трафика.
	Workers int

	// PerTarget — сколько проб к одной цели идёт одновременно (5.4). Больше
	// двух коррелирует результаты, если DPI держит состояние по IP источника:
	// вместо N независимых наблюдений выходит одно, размазанное на N.
	PerTarget int

	// Jitter — верхняя граница случайной задержки перед каждой пробой (5.4,
	// джиттер обязателен). Ноль означает «без джиттера»: законно для тестов,
	// где пробы запускаются поштучно, но в бою нежелательно.
	Jitter time.Duration

	// Round — пауза между полными обходами портфеля. Задаёт частоту фонового
	// A/B: песочница гоняет кандидатов кругами, Round — пауза между кругами.
	// Нулю не равна (см. validate): обходы вплотную жгли бы сеть и отдавали бы
	// DPI данные о поведении машины (5.8).
	Round time.Duration
}

const (
	// defaultPortLo, defaultPortHi — диапазон по умолчанию: 128 портов вне
	// эфемерного диапазона Windows.
	defaultPortLo uint16 = 40000
	defaultPortHi uint16 = 40127
	// workersCeiling — жёсткий верхний предел воркеров (5.4).
	workersCeiling = 16
	// defaultPerTarget — одновременных проб на цель (5.4).
	defaultPerTarget = 2
	// defaultJitter — верхняя граница джиттера перед пробой.
	defaultJitter = 300 * time.Millisecond
	// defaultRound — пауза между обходами портфеля.
	//
	// Короткая намеренно: на этапе прогрева (пока нет действующей стратегии)
	// песочнице надо быстро набрать порог наблюдений (5.5), а это выделенные
	// соединения, трафик пользователя они не трогают. Известный недостаток:
	// в установившемся режиме такой темп проб чаще, чем интервал 5.7 (12 мин),
	// и даёт DPI лишние данные о поведении машины — поэтому следующим шагом
	// песочницу надо переводить на перебор по ProbeItems с замедлением, когда
	// портфель устоялся. Пока портфель мал (7 кандидатов), цена терпима.
	defaultRound = 4 * time.Second
)

// DefaultConfig возвращает значения по умолчанию.
//
// Воркеров — min(8, NumCPU), но не больше потолка 16 (5.4): столько проб идут
// одновременно глобально. Диапазон портов и прочие величины — из констант выше.
func DefaultConfig() Config {
	w := runtime.NumCPU()
	if w > 8 {
		w = 8
	}
	return Config{
		PortLo:    defaultPortLo,
		PortHi:    defaultPortHi,
		Workers:   w,
		PerTarget: defaultPerTarget,
		Jitter:    defaultJitter,
		Round:     defaultRound,
	}
}

// validate проверяет согласованность параметров.
func (c Config) validate() error {
	switch {
	case c.PortLo == 0 || c.PortHi == 0:
		return fmt.Errorf("sandbox: диапазон портов не задан")
	case c.PortHi < c.PortLo:
		return fmt.Errorf("sandbox: верх диапазона портов %d меньше низа %d", c.PortHi, c.PortLo)
	case c.Workers <= 0:
		return fmt.Errorf("sandbox: число воркеров %d неположительно", c.Workers)
	case c.Workers > workersCeiling:
		return fmt.Errorf("sandbox: число воркеров %d выше жёсткого потолка %d (5.4)", c.Workers, workersCeiling)
	case c.PerTarget <= 0:
		return fmt.Errorf("sandbox: предел проб на цель %d неположителен", c.PerTarget)
	case c.PerTarget > c.Workers:
		// Больше, чем глобальных воркеров: предел на цель тогда недостижим —
		// это ошибка настройки, а не рабочий режим.
		return fmt.Errorf("sandbox: предел на цель %d больше числа воркеров %d", c.PerTarget, c.Workers)
	case c.Jitter < 0:
		return fmt.Errorf("sandbox: джиттер %v отрицателен", c.Jitter)
	case c.Round <= 0:
		return fmt.Errorf("sandbox: пауза между обходами %v неположительна", c.Round)
	}
	return nil
}

// ports сообщает число портов диапазона — для журнала и проверок.
func (c Config) ports() int { return int(c.PortHi-c.PortLo) + 1 }

// PortPredicates возвращает предикаты фильтра WinDivert по исходному порту для
// двух дескрипторов: продуктовый (порт вне диапазона песочницы) и песочный
// (порт внутри). Склеиваются с базовым фильтром командой запуска через "and".
//
// Непересекаемость — по построению: один берёт SrcPort строго вне [lo, hi],
// другой строго внутри, поэтому ни один пакет не матчит оба дескриптора. Это и
// есть разделение песочницы и продуктового пути на уровне захвата (5.2): два
// дескриптора на непересекающихся множествах пакетов не накладывают десинк
// дважды, в отличие от двух дескрипторов на одном трафике.
func (c Config) PortPredicates() (product, sandbox string) {
	lo := strconv.Itoa(int(c.PortLo))
	hi := strconv.Itoa(int(c.PortHi))
	product = "(tcp.SrcPort < " + lo + " or tcp.SrcPort > " + hi + ")"
	sandbox = "(tcp.SrcPort >= " + lo + " and tcp.SrcPort <= " + hi + ")"
	return product, sandbox
}
