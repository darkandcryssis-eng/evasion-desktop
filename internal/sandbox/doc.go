// Пакет sandbox ведёт подбор стратегий обхода на выделенных соединениях,
// не касаясь пользовательского трафика (5.2, M7).
//
// Зачем он есть. Автопилот первой версии подбирал стратегию, переключая
// активную на единственном контуре перехвата: во время подбора
// пользовательские соединения на миг получали проверяемого кандидата.
// Песочница снимает этот изъян — пробы инициирует сам движок с выделенного
// диапазона локальных портов, отдельный фильтр WinDivert отделяет их от
// трафика пользователя уже на захвате, и подбор идёт постоянным фоновым A/B,
// а не рывком на старте и при срыве.
//
// Что пакет знает и чего не знает. Знает: диапазон портов, привязку
// «порт → кандидат», как заказать пробу и куда отдать исход. Не знает: как
// применяется стратегия (packetexec), откуда берутся пакеты (capture), как
// считается оценка и кто становится active (scoring, control). Отбор ведёт
// контур управления по исходам, которые поставляет песочница, а сама она лишь
// измеряет. Граница узкая сознательно: песочница — граница безопасности (4.1),
// и ей положено быть явной, а не растворённой в policy.
//
// Изоляция. Контур перехвата песочницы — отдельный дескриптор WinDivert по
// своему диапазону портов и отдельная таблица потоков: кандидат из песочницы
// не попадает в продуктовую таблицу, а сбой поиска не роняет основной путь
// (5.2). Эти части собираются в команде запуска; сам пакет их не импортирует,
// чтобы оставаться проверяемым без сети и Windows — через инъекцию Prober и
// Reporter.
