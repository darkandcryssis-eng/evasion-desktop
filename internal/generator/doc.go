// Пакет generator ведёт генетический поиск стратегий обхода: порождает
// случайные деревья примитивов, мутирует их и скрещивает (M7, 4.3).
//
// Что знает и чего не знает. Знает только представление стратегии
// (strategy.Strategy) и реестр примитивов: виды узлов (strategy.Kinds), поля
// (strategy.Fields), точки разреза (core.CutKinds). О пакетах, сокетах и сети
// не знает вовсе — поэтому проверяется без них. Захардкоженного списка действий
// в генераторе нет: пространство поиска он берёт из реестра strategy и
// пересекает с возможностями исполнителя (4.7, 10.3). Добавление примитива в
// реестр расширяет поиск само, без правок здесь.
//
// Граница безопасности. Генетический алгоритм работает ТОЛЬКО в песочнице
// (1.4 п. 6): к реальному трафику его мутанты не допускаются. Генератор лишь
// порождает кандидатов; проверяет их песочница на выделенных соединениях, а в
// рабочий портфель они попадают только через статистический порог (5.5). Сам
// пакет generator ничего не исполняет и ни к какому трафику не прикасается.
//
// Исполнимость по построению. Всё, что порождает генератор, валидно
// (strategy.Validate) и требует лишь тех возможностей, что объявил исполнитель
// (RequiredCapabilities ⊆ Caps). Невыполнимое не порождается — иначе кандидат
// был бы оценён как нерабочий, хотя просто не применялся (тот же класс порчи
// измерений, что утечка по IPv6 или молчаливый пропуск непосильного примитива).
//
// Этот слайс — чистое ядро (порождение, мутация, скрещивание). Популяция и
// цикл поиска, а также стык с песочницей — отдельными слайсами.
