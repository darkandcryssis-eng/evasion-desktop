// Пакет rtctrack ведёт статистику живучести голосовых и демонстрационных
// RTC-соединений Discord: по паре (SNI, порт) собирает сколько сессий начато,
// сколько прожило дольше порога, сколько упало по RST, и ранжирует пары от
// лучшей к худшей.
//
// Для чего. Движок сейчас лечит TCP-рукопожатие голоса одинаково на всех
// RTC-портах (443/2053/2083/2087/2096/8443). Но живучесть РАЗНЫХ пар
// (сервер × порт) неодинакова: часть серверов на 2096 держит звонок дольше,
// другие на 443 падают через минуту. Знать эту карту = уметь предлагать
// Discord'у «попробуй сервер X, порт Y» или блокировать плохие пары на
// файрволе. То, что в блюпринте называется автопилотом v3 RTC-aware.
//
// Что внутри. Tracker — потокобезопасный агрегатор событий. Четыре входных
// метода:
//
//   - Observe(sni, port): замечено новое соединение (отправлен ClientHello).
//   - Settled(sni, port): соединение прошло рукопожатие и начало обмен
//     шифрованным трафиком. Пассивный признак успеха.
//   - Reset(sni, port): соединение разорвано сервером (RST). Пассивный
//     признак провала.
//   - Elapsed(sni, port, dur): соединение прожило dur и завершилось.
//     Включается при корректном закрытии; обновляет среднее dwell.
//
// Два выходных: Snapshot даёт карту текущего состояния по парам; Rank
// возвращает лучшие k пар по эмпирическому индексу живучести (успех × dwell).
//
// Чем это НЕ является. Не хранит PCAP, не держит открытых соединений, не
// общается с сетью. Чистый агрегатор. Привязка к живым сокетам WinDivert —
// работа вызывающего (cmd/evasion/intercept.go в будущей итерации).
