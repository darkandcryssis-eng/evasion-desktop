package tlsparse

import "errors"

// Ошибки разбора.
//
// Главное различие — между «данных пока мало» и «данные противоречивы». Первое
// требует подождать следующий сегмент, второе — прекратить разбор. Если их
// спутать, движок либо зависнет в ожидании байт, которых не будет, либо
// отбросит соединение, которое всего лишь пришло по частям.
var (
	// ErrIncomplete — структура корректна, но буфер пока короче объявленной
	// длины. Надо дождаться следующих байт потока.
	ErrIncomplete = errors.New("tlsparse: данных пока недостаточно")
	// ErrNotTLS — байты не похожи на запись TLS (неизвестный тип содержимого
	// или неподдерживаемая версия слоя записей).
	ErrNotTLS = errors.New("tlsparse: не запись TLS")
	// ErrNotHandshake — запись не относится к рукопожатию.
	ErrNotHandshake = errors.New("tlsparse: запись не является рукопожатием")
	// ErrNotClientHello — сообщение рукопожатия имеет другой тип.
	ErrNotClientHello = errors.New("tlsparse: сообщение не ClientHello")
	// ErrMalformed — объявленные внутри сообщения длины противоречат друг
	// другу или выходят за границы охватывающей структуры.
	ErrMalformed = errors.New("tlsparse: противоречивая структура сообщения")
	// ErrFragmentedHandshake — сообщение рукопожатия не умещается в одну
	// запись TLS и продолжается в следующей.
	//
	// Первая версия такой случай не собирает, но и не игнорирует: ошибка
	// возвращается явно. Молчаливый разбор первой половины дал бы неверный SNI,
	// а значит неверное решение о стратегии — тот же класс порчи измерений, что
	// утечка по IPv6 (3.2).
	ErrFragmentedHandshake = errors.New("tlsparse: рукопожатие разбито на несколько записей")
	// ErrNoSNI — в ClientHello нет расширения server_name либо в нём нет имени
	// типа host_name.
	ErrNoSNI = errors.New("tlsparse: расширение server_name отсутствует")
)
