// Пакет tlsparse разбирает записи TLS, сообщение ClientHello, извлекает имя
// сервера (SNI) и вычисляет структурные точки разреза записи.
//
// Зачем существует: ClientHello — единственное место потока, которое интересует
// движок. Именно по нему выбирается стратегия (решение принимается на каждое
// соединение, 1.4 п. 4), и именно его разрезают и дублируют примитивы десинка.
// Отдельный пакет нужен, чтобы этот разбор можно было фаззить изолированно: как
// и packet, он обрабатывает данные из сети, то есть заведомо враждебные.
//
// Что знает: раскладку слоя записей TLS, формат сообщения рукопожатия
// ClientHello, формат расширений и расширения server_name, а также где в этих
// структурах проходят границы, по которым осмысленно резать.
//
// Чего знать не должен: ничего о стратегиях и о том, какую точку разреза
// выбрать, — пакет отдаёт все структурные границы как данные, а выбор делает
// desync. Ничего о пакетах IP и TCP: на вход подаётся поток байт тела
// соединения, собранный вызывающим кодом.
//
// # Принципы реализации
//
// Разбор без копирования: результат — смещения и длины в исходном буфере.
// Строк не создаётся, память не выделяется (бюджеты 8.1).
//
// Неполнота и порча различаются строго. Если байт просто не хватает, это
// ErrIncomplete и вызывающий код должен дождаться следующего сегмента; если
// структура противоречива — это ошибка разбора. Смешивать их нельзя: в первом
// случае надо ждать, во втором — перестать разбирать.
