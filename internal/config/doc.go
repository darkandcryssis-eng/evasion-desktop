// Пакет config — конфигурация движка: формат файла, значения по умолчанию,
// проверка и сборка производных структур (множество доменов групп, стратегия
// режима прокси).
//
// Зачем существует: все числа, названные в задании «по умолчанию», живут здесь, а
// не в коде потребителей (10.1). Потребители получают уже проверенные значения и
// сами ничего не разбирают.
//
// Формат — JSON. Разбор строгий: неизвестный ключ — ошибка, а не тихий пропуск.
// Опечатка в имени параметра иначе выглядела бы как «параметр не работает».
// Конфиг считается недоверенным вводом (10.2): размер файла ограничен, стратегия
// внутри проходит полную валидацию пакета strategy.
//
// Что знает: схему конфига и правила её проверки, нормализацию доменных имён.
//
// Чего знать не должен: как параметры применяются. Конфиг не запускает прокси и
// не выбирает стратегии, он только отдаёт проверенные данные.
//
// Состав растёт вместе с пакетами: раздел появляется тогда, когда у него есть
// потребитель. Пустых разделов «на будущее» нет. Иначе пользователь задал бы
// параметр, который ничего не делает.
