// Пакет packetexec — исполнитель стратегии этапа 1: воплощает её
// переписыванием пакетов (4.7).
//
// Не новый контур. Вся логика исполнения — проверка возможностей, построение
// плана, проведение операций — уже в executor.Base. packetexec добавляет лишь
// две вещи: реализацию executor.Conn, которая строит и отправляет пакеты через
// capture.PacketSink, и набор объявляемых возможностей. Поэтому пакеты
// strategy, scoring, generator и control при переходе на этап 1 не меняются
// (4.7 п. 4) — это выполняется по построению, а не проверкой.
//
// # Что умеет слайс 1
//
// Точную сегментацию TCP и паузы (возможности CapFragmentTCP, CapDelay). В
// отличие от socketexec, где ОС вправе склеить подряд идущие записи в один
// сегмент даже при TCP_NODELAY, здесь границы сегментов задаются точно: каждый
// кусок нагрузки уходит отдельным пакетом с нужным номером последовательности.
//
// Фейки (SendFake с правками TamperParams), IP-фрагментация и обратный порядок
// придут слайсом 2 — это механика, которая и ломает DPI. Объявлять их
// возможности до реализации нельзя: исполнитель, принявший непосильную
// стратегию, оценился бы как нерабочий, хотя исполнялся бы не так, как описан
// (4.7 п. 2). Поэтому непосильные операции сейчас возвращают явную ошибку, а
// соответствующие возможности не объявлены.
//
// # Сборка пакета
//
// Из шаблона — перехваченного пакета ClientHello — копируются заголовки,
// подставляется новая нагрузка, правятся длины сетевого слоя и номер
// последовательности TCP, затем пересчитываются контрольные суммы. Пересчёт
// обязателен: Windows отвергает инъекцию пакетов с неверной суммой даже при
// offloading (см. capture/doc.go).
//
// Номер последовательности сейчас отсчитывается по порядку отправки. Это верно,
// пока нет обратного порядка (CapReorder не объявлен): при прямом порядке
// порядок отправки совпадает с положением куска в нагрузке. Слайс 2, добавляя
// реордер, перейдёт на вычисление смещения по положению среза в исходной
// нагрузке — иначе отправленный первым «второй» кусок получил бы чужой номер.
//
// # Границы
//
// packetexec только отправляет пакеты через sink. Откуда пакеты берутся и куда
// уходят — дело capture; какую стратегию применять — дело policy; когда
// освобождать поток — дело flow. Контур исполнения (executor.Run) про субстрат
// не знает.
