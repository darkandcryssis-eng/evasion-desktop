// Пакет store — хранение наблюдений: интерфейс, доменные типы и приём записи.
//
// Зачем существует. Оценка стратегии не является её свойством: она свойство
// четвёрки «стратегия × цель × точка наблюдения × время» (6.1). Такой ключ не
// вместить в счётчики — множество стратегий и целей меняется на ходу, а
// история нужна, чтобы оценки затухали со временем и чтобы их можно было
// пересчитать по другой формуле, не потеряв исходные данные.
//
// Что знает: какой вид имеет наблюдение, как принять его не мешая горячему
// пути и как спросить готовый срез для решений.
//
// Чего знать не должен: как исходы взвешиваются (scoring), какие решения по
// ним принимаются (control), как проводятся измерения (probe).
//
// # Три слоя по характеру доступа (6.3)
//
//	горячий путь ──► структуры в памяти, БД не трогается НИКОГДА
//	                      ▲
//	                      │ асинхронно
//	приём ──► журнал наблюдений (только добавление)
//	                      │
//	                      ▼
//	            материализованные срезы ──► аналитика и решения
//
// Горячий путь к хранилищу не обращается вовсе. Между ним и хранилищем стоит
// Writer: он принимает наблюдения без блокировки и пишет их пачками в своей
// горутине. Это не оптимизация, а требование — решение по ClientHello обязано
// укладываться в 10 мкс (8.1), и запись на диск туда не вмещается ни при каком
// устройстве хранилища.
//
// # Почему реализация на SQLite лежит в подпакете
//
// Интерфейс Store объявлен здесь, а реализация — в store/sqlite. Это
// не формальность: pure-Go SQLite тянет 26 модулей переведённого из C кода, и
// если бы реализация лежала здесь, эта зависимость попала бы в граф импорта
// всем, кому нужен только интерфейс — scoring, control, policy. При разделении
// её импортирует лишь cmd/evasion, который собирает движок целиком.
//
// Заодно это выполняет требование 10.4: новое хранилище добавляется через
// интерфейс, без зависимости от особенностей SQLite.
//
// # Что получает строку, а что счётчик (6.4)
//
// Отдельная строка пишется ТОЛЬКО для:
//
//   - соединений, к которым применялась стратегия;
//   - соединений с обнаруженной аномалией (повторный ClientHello, сброс);
//   - результатов активных проб;
//   - событий жизненного цикла стратегий и переключений.
//
// Всё остальное — агрегированные счётчики в telemetry. Строка на каждое
// соединение машины не пишется никогда: на активной машине их десятки тысяч в
// сутки, и объём данных стал бы неуправляемым. При этом правиле выходит до
// нескольких тысяч строк в сутки.
//
// # Схема рассчитана на переход
//
// События пишутся без обновлений, время хранится явным полем, и ничего из
// особенностей SQLite не используется. Это сделано ради перехода на колоночную
// СУБД при распределённом сборе (6.5) — не потому, что он близок, а потому что
// задним числом такую схему не переделать без потери истории.
