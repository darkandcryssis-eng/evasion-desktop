// Пакет sqlite — реализация хранилища наблюдений на SQLite.
//
// Лежит подпакетом намеренно. Pure-Go SQLite тянет около двадцати шести модулей
// переведённого из C кода, и если бы реализация жила в store, эта зависимость
// попала бы в граф импорта всем, кому нужен только интерфейс: scoring, control,
// policy. При таком разделении её импортирует лишь cmd/evasion, который
// собирает движок целиком. Заодно выполняется требование 10.4: новое хранилище
// добавляется через интерфейс, без зависимости от особенностей SQLite.
//
// # Почему вообще SQLite, если зависимостей велено держать минимум
//
// Требования задания здесь сталкиваются: 6.5 называет SQLite, 3.1 запрещает
// CGO и требует минимума зависимостей. Обычный драйвер SQLite — обёртка над
// библиотекой на C и без CGO не работает, поэтому первые два пункта совместимы
// только через чистую реализацию на Go, а она и тянет транслятор.
//
// Выбор сделан в пользу SQLite: хранилище — именно та вещь, которую не пишут
// сами. Устойчивость к сбою посреди записи, пакетные вставки, выборки с
// группировкой и удаление по сроку достаются готовыми и обкатанными. Своя
// реализация променяла бы чужой проверенный код на непроверенный свой в самом
// неудачном для ошибок месте.
//
// Цена названа и принята: около двадцати шести модулей в графе зависимостей и
// рост бинарника примерно на четыре мегабайта.
//
// # Схема рассчитана на переход
//
// События пишутся только добавлением, без обновлений. Время хранится целым
// числом миллисекунд, а не типом даты SQLite. Перечисления хранятся ТЕКСТОВЫМИ
// обозначениями, а не числами: числа привязали бы архив к текущему порядку
// констант в коде, и перестановка значения молча испортила бы всю прошлую
// историю. Текст самодокументируем и переносится в колоночную СУБД без
// преобразования (6.5).
//
// Явный столбец дня служит временным разделом: по нему идёт удаление по сроку,
// и он же станет ключом раздела при переходе на колоночное хранилище.
