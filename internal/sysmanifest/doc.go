// Пакет sysmanifest ведёт журнал системных изменений, которые делает движок,
// чтобы их можно было откатить после любого способа завершения — штатного или
// краха.
//
// Зачем существует. Движок правит системные настройки Windows: добавляет
// правила файрвола (netsh advfirewall), записи в hosts, в будущем — другие
// глобальные настройки. Эти правки живут вне процесса движка: если движок
// умирает нештатно (паника, kill -9, падение драйвера WinDivert, отключение
// электричества), правки остаются до перезагрузки или ручной очистки.
//
// Инвариант движка: каждое системное
// изменение атомарное и обратимое, причём отмена возможна с диска, а не из
// памяти процесса, который этих изменений мог уже не помнить.
//
// Как устроено. На каждое применённое изменение в журнал (`state/system.json`)
// добавляется запись: вид изменения (`firewall_rule`, `hosts_entry`), стабильный
// идентификатор в пределах вида, время применения, данные для отмены в
// формате, который понимает соответствующий исполнитель отмены (хранится как
// `json.RawMessage` — пакет про него ничего не знает). Запись в файл идёт через
// tmp + atomic rename, чтобы прерывание посреди записи не оставляло
// полуфайл.
//
// Что НЕ делает. Не выполняет сами изменения и не выполняет сами отмены —
// это дело пакетов `internal/hosts`, лаунчера файрвольных правил и будущих
// исполнителей. Задача пакета — хранить достаточно сведений, чтобы отмена
// могла воспроизвестись из любого состояния процесса, включая отсутствующий
// процесс.
//
// Что в journal'е НЕТ:
//
//   - Содержимого системных файлов целиком. Мы храним только то, что ПРИМЕНИЛИ,
//     и как это ПРИМЕНИЛИ отменить. Снятие резервной копии hosts целиком — это
//     задача пакета `internal/hosts`, не наша.
//   - Самого факта «изменение сработало». Запись в журнал идёт ПОСЛЕ успешного
//     применения; если применение не удалось, записи нет, отменять нечего.
//     Это ровно то, что делает ранее принятая `writer.closeOnce` в store: ОНА
//     гарантирует, что мы не напишем результат, которого нет.
