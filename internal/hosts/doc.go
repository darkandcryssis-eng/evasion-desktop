// Package hosts читает и правит системный hosts-файл, добавляя или удаляя
// именованный «управляемый» блок между маркерами.
//
// Зачем это движку. У владельца проекта провайдер режет SYN до реального
// диапазона Discord Cloudflare (`162.159.*`) на TCP:443, но тот же Cloudflare
// на других IP (например `23.227.38.74`) доступен и маршрутизирует к Discord
// по SNI (any-IP routing для HTTP). Задание 1.3 запрещает туннели и прокси —
// но hosts-подмена маршрут не меняет (пакет уходит из той же машины), а лишь
// просит клиента связываться с другим IP Cloudflare. Это промежуточный слой
// между DPI-десинком (наш профиль) и настоящим VPN (из области исключено).
//
// Границы пакета. Он только РАЗБИРАЕТ и ПРАВИТ содержимое: все операции
// работают над срезом байт. Чтение и запись файла, права, бэкап и восстановление
// — забота вызывающего (команды cmd/evasion). Это тот же приём разделения,
// что в `tlsparse` (знает про формат TLS, но не про сеть) и `interception`
// (знает про имена, но не останавливает процессы).
//
// Формат управляемого блока. Пара маркеров-комментариев, окружающая строки:
//
//	# >>> evasion:{id} begin >>>
//	# ... тело блока ...
//	# <<< evasion:{id} end <<<
//
// ID — короткий токен (ASCII, без пробелов) для различения блоков разных
// задач. Это позволяет движку держать несколько управляемых блоков рядом
// (например, cloudflare-fallback для HTTP и, в будущем, dnsoverride для DoH-меток),
// не мешая один другому и не трогая чужое содержимое hosts.
//
// Границы с внешними инструментами. Zapret 2 GUI оставляет в hosts блок с теми
// же маркерами собственного формата (`# >>> zapretgui:hosts managed begin >>>`).
// Пакет его НЕ трогает — у них свой префикс, у нас свой (`evasion:`), и
// пересекаться они по дизайну не могут. Удаление чужих блоков — задача
// отдельного скрипта (scripts/clean-zapret-hosts.ps1).
