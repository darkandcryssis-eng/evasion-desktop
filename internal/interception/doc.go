// Пакет interception обнаруживает сторонние средства перехвата трафика.
//
// Зачем существует. У движка два разных потребителя этого знания, и оба
// обязаны пользоваться одним набором правил:
//
//   - команда doctor (5.9) сообщает о конфликтах: при работающем zapret или
//     GoodbyeDPI измерения движка недостоверны, а на этапе 1 два перехватчика
//     WinDivert на одном трафике дают непредсказуемое поведение;
//   - библиотека прогонов глушит перехватчики на время измерения и возвращает
//     их обратно, иначе измеряется сумма двух воздействий.
//
// Прежде правила обнаружения жили только в прогонах (tests/harness). Двух
// наборов быть не должно: разойдясь, они дали бы движку и прогонам разные
// ответы на один вопрос, и расхождение заметили бы в самый неподходящий
// момент — при разборе непонятного измерения.
//
// Что знает: как спросить у операционной системы, запущены ли известные
// средства перехвата, и как называется команда их запуска.
//
// Чего знать не должен: что с этим знанием делать. Пакет **только находит**.
// Останавливать чужие процессы — действие прогона, а не продукта: движок не
// вправе выключать то, чем пользуется человек, и такой возможности здесь
// нет вовсе. Остановка и возврат живут в tests/harness, который этот пакет
// потребляет.
//
// # Почему по именам, а не по признаку «использует WinDivert»
//
// Перехватчик опознаётся надёжно только по имени. Признак «любой процесс,
// открывший WinDivert» выглядит общее, но требует перебора открытых
// устройств и прав, которых на этапе 0 нет, а главное — ошибается в
// опасную сторону: назвать чужой процесс перехватчиком хуже, чем не узнать
// свой. Для прогонов это означало бы остановку постороннего процесса, для
// doctor — ложное обвинение.
//
// Цена названа прямо: список имён неполон и будет устаревать. Поэтому
// отсутствие находок означает «известных средств не обнаружено», а не
// «перехвата точно нет», и формулировки в выводе обязаны это различать.
//
// # Платформа
//
// Средства, из-за которых измерение становится суммой двух воздействий
// (zapret, GoodbyeDPI, byedpi), существуют под Windows, как и сам движок
// (3.1). На прочих платформах поиск ничего не находит — не умалчивает, а
// честно возвращает пустой список с признаком того, что поиск не
// применим.
