package interception

import "strings"

// Kind — чем является обнаруженное средство перехвата.
//
// Обозначения машинные и английские, а не человеческие подписи. Прежде в
// прогонах вид хранился строками «служба» и «процесс», и по ним же шло
// ветвление — то есть человекочитаемый текст работал машинным значением.
// Задание это запрещает прямо: движок возвращает данные, а не представление
// (2.2), и подписи принадлежат потребителю.
type Kind string

const (
	// KindProcess — обычный процесс.
	KindProcess Kind = "process"
	// KindService — служба Windows.
	KindService Kind = "service"
)

// Tool — обнаруженное средство перехвата.
//
// Нулевое значение негодно: средство без имени не обнаружено.
type Tool struct {
	// Kind — вид: процесс или служба.
	Kind Kind `json:"kind"`
	// Name — имя процесса или службы.
	Name string `json:"name"`
	// Command — команда запуска процесса, если её удалось узнать.
	//
	// Нужна прогонам: остановленный процесс надо вернуть, а мёртвый процесс о
	// себе уже ничего не расскажет. Пусто означает «узнать не удалось», и
	// потребитель обязан это различать: вернуть такое средство автоматически
	// нельзя, и человек должен об этом узнать, а не обнаружить тихо
	// выключенный обход.
	Command string `json:"command,omitempty"`
}

// Result — что дал поиск.
//
// Отдельный тип, а не просто срез: пустой срез сам по себе двусмыслен —
// «ничего не нашли» и «искать не умеем на этой платформе» выглядели бы
// одинаково. То же правило, на котором проект стоит с самого начала: нулевое
// значение не подменяет отсутствие данных.
type Result struct {
	// Tools — что обнаружено.
	Tools []Tool `json:"tools"`
	// Supported — поиск применим на этой платформе.
	//
	// Ложь означает, что ответ «ничего не найдено» получен не измерением, и
	// выводов из него делать нельзя.
	Supported bool `json:"supported"`
	// Partial — поиск прошёл не полностью.
	//
	// Так бывает, когда системная команда недоступна или отказала в правах:
	// часть средств могла остаться незамеченной. Признак нужен затем, чтобы
	// doctor не выдавал неполный обзор за полный.
	Partial bool `json:"partial"`
	// Notes — машинно-читаемые пометки о том, что именно не удалось.
	Notes []string `json:"notes,omitempty"`
}

// Found сообщает, обнаружено ли хоть одно средство перехвата.
func (r Result) Found() bool { return len(r.Tools) > 0 }

// Clean сообщает, что обстановка заведомо чистая.
//
// Истина только тогда, когда поиск применим, прошёл полностью и ничего не
// нашёл. Во всех прочих случаях ложь, потому что «не нашли» и «не искали» —
// разные ответы, и выдавать второе за первое значило бы объявить измерение
// чистым без оснований.
func (r Result) Clean() bool { return r.Supported && !r.Partial && len(r.Tools) == 0 }

// Names возвращает имена обнаруженных средств — для краткой строки отчёта.
func (r Result) Names() []string {
	out := make([]string, 0, len(r.Tools))
	for _, t := range r.Tools {
		out = append(out, t.Name)
	}
	return out
}

// KnownProcesses возвращает имена процессов, которые пакет умеет узнавать.
//
// Экспортируется для doctor: на вопрос «что именно проверялось» обязан быть
// ответ. Без него «конфликтов не обнаружено» — утверждение без границ, а
// список имён заведомо неполон и будет устаревать.
func KnownProcesses() []string { return append([]string(nil), interceptProcesses...) }

// KnownServices возвращает имена служб, которые пакет умеет узнавать.
func KnownServices() []string { return append([]string(nil), interceptServices...) }

// Известные средства перехвата, искажающие измерения.
//
// Список имён, а не признак «любой процесс с WinDivert»: обоснование и цена —
// в doc.go. Имена сравниваются без учёта регистра: в Windows регистр имён
// процессов и служб не значим.
var (
	// interceptProcesses — имена процессов средств перехвата.
	interceptProcesses = []string{
		"winws.exe",      // zapret (второе поколение)
		"zapret.exe",     // zapret
		"goodbyedpi.exe", // GoodbyeDPI
		"ciadpi.exe",     // byedpi
		"byedpi.exe",     // byedpi
	}
	// interceptServices — имена служб средств перехвата.
	//
	// WinDivert в списке намеренно: сам драйвер не является средством обхода,
	// но его загруженность означает, что перехватчик либо работает, либо
	// работал недавно. На этапе 1 это прямой конфликт — два перехватчика
	// WinDivert на одном трафике дают непредсказуемое поведение. Потребитель
	// обязан различать драйвер и процесс: загруженный драйвер без процесса не
	// повод останавливать измерение.
	interceptServices = []string{
		"zapret",
		"winws",
		"goodbyedpi",
		"WinDivert",
		"WinDivert14",
	}
)

// IsDriver сообщает, что средство — драйвер перехвата, а не средство обхода.
//
// Нужно потребителям, которые относятся к драйверу иначе: прогоны не
// останавливают измерение из-за загруженного драйвера без процесса, а doctor
// на этапе 0 сообщает о нём как о сведении, а не как о конфликте.
func (t Tool) IsDriver() bool {
	return t.Kind == KindService && strings.HasPrefix(strings.ToLower(t.Name), "windivert")
}
