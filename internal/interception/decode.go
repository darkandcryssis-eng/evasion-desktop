// oemToUTF8 переводит вывод консоли Windows в UTF-8.
//
// Знаки ниже 0x80 совпадают с ASCII и переносятся как есть; остальные берутся
// из таблицы. Если вывод оказался уже в UTF-8 (так бывает, когда кодовая
// страница консоли переключена), перевод его испортил бы, поэтому годная
// последовательность UTF-8 остаётся нетронутой.
//
// Зачем вообще нужно: системные команды Windows (sc, tasklist, taskkill) пишут
// по-русски в кодовой странице консоли, а не в UTF-8, и без перевода сообщение
// об ошибке попадало в отчёт кашей вида «�� 㤠���� ����� 䠩�».
// Владелец такую строку и увидел, когда возврат zapret не сработал, — то есть
// диагностика оказалась нечитаемой в самый неподходящий момент.
//
// Функция живёт в файле без ограничения по платформе намеренно: она нужна
// только Windows, но проверяться обязана на любой машине. Тот же приём, что с
// pickMinRTT и perDecision — дефект, воспроизводимый лишь на одной платформе,
// выносится в чистую функцию.
func oemToUTF8(b []byte) string {
	if utf8.Valid(b) {
		return string(b)
	}
	table := []rune(oemCP866)
	var sb strings.Builder
	sb.Grow(len(b) * 2)
	for _, c := range b {
		if c < 0x80 {
			sb.WriteByte(c)
			continue
		}
		sb.WriteRune(table[int(c)-0x80])
	}
	return sb.String()
}

// DecodeConsole переводит вывод консоли Windows в UTF-8.
//
// Экспортируется для потребителей, которые сами выполняют системные команды:
// библиотека прогонов останавливает и возвращает перехватчики через sc и
// taskkill, и их сообщения об ошибках приходят в той же кодовой странице.
// Держать вторую копию таблицы нельзя — разойдясь, копии дали бы разную
// читаемость одной и той же ошибки, а именно нечитаемость диагностики здесь
// уже один раз подвела.
func DecodeConsole(b []byte) string { return oemToUTF8(b) }

// FirstLine возвращает первую непустую строку вывода.
//
// Экспортируется по той же причине, что DecodeConsole: сообщения системных
// команд многострочны, и потребителю нужна та же выжимка, что и здесь.
func FirstLine(s string) string { return firstLine(s) }

// firstLine возвращает первую непустую строку вывода.
func firstLine(s string) string {
	for _, line := range strings.Split(s, "\n") {
		if line = strings.TrimSpace(line); line != "" {
			return line
		}
	}
	return ""
}

// containsFold сообщает, встречается ли подстрока без учёта регистра.
//
// Регистр не учитывается потому, что имена процессов и служб в Windows его не
// различают, а системные команды печатают их как им угодно.
func containsFold(s, sub string) bool {
	return strings.Contains(strings.ToLower(s), strings.ToLower(sub))
}

// parseServiceQuery разбирает вывод `sc query <имя>`.
//
// Вынесено в чистую функцию и живёт вне windows-файла намеренно: это самая
// непрозрачная часть обнаружения, и проверяться она обязана на любой машине, а
// не только там, где воспроизводится. Тот же приём, что с pickMinRTT и
// perDecision.
//
// Что здесь неочевидно, по порядку:
//
//   - Состояние печатается строкой вида «STATE : 4 RUNNING», и слово RUNNING
//     переведено на язык системы. Поэтому опора на код 4, а слово — лишь
//     подстраховка для случая, когда формат вывода отличается.
//   - Код 1060 означает «указанная служба не установлена». Это полноценный
//     ответ «не запущена», а не неудача опроса, и различать их обязательно:
//     sc отдаёт ненулевой код возврата и при отсутствии службы, и при отказе
//     в правах. Приняв отказ в правах за отсутствие службы, обнаружение
//     объявило бы обстановку чистой именно тогда, когда проверить её не
//     смогло.
func parseServiceQuery(out string) (running, notInstalled bool) {
	if containsFold(out, "1060") {
		return false, true
	}
	// Двоеточие с кодом 4 — признак работающей службы. Проверяется именно
	// «: 4», а не просто «4»: цифра встречается и в номере типа службы, и в
	// контрольных точках, и в названиях вроде WinDivert14.
	if strings.Contains(out, ": 4") || containsFold(out, "RUNNING") {
		return true, false
	}
	return false, false
}
