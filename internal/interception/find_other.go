//go:build !windows

package interception

// Find на не-Windows ничего не ищет.
//
// Средства, из-за которых измерение становится суммой двух воздействий
// (zapret, GoodbyeDPI, byedpi), существуют под Windows, как и сам движок
// (3.1).
//
// Результат помечается как неприменимый (Supported = false), а не как «чисто».
// Разница принципиальна и ровно та же, что с базовой линией цели: «не нашли» и
// «не искали» — разные ответы. Пометив отсутствие находок чистотой, пакет
// выдал бы отсутствие проверки за её успешное прохождение, и doctor сообщил бы
// «конфликтов нет» там, где конфликтов просто не искали.
func Find() Result {
	return Result{
		Supported: false,
		Notes:     []string{"поиск средств перехвата реализован только для Windows"},
	}
}
