package core

// StrategyID — устойчивый идентификатор стратегии.
//
// Значение выводится из канонической формы дерева стратегии (хеш содержимого,
// см. пакет strategy). Поэтому две текстуально разные записи одной и той же
// стратегии дают один идентификатор, а любая мутация дерева — новый. Это нужно
// генератору для бесплатной дедупликации повторно выведенных мутантов и
// хранилищу — для стабильных ключей между запусками.
//
// Цена такого выбора: идентификатор нельзя задать «красивым» вручную и он
// меняется при любой правке дерева, поэтому родословную стратегии (от каких
// родителей произошла) приходится хранить отдельным полем, а не выводить из ID.
type StrategyID string

// String возвращает идентификатор как строку. Метод существует, чтобы
// StrategyID удовлетворял fmt.Stringer и единообразно выводился в логах.
func (id StrategyID) String() string { return string(id) }
