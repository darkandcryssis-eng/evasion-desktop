// Пакет executor задаёт интерфейс исполнителя стратегии и объявление
// возможностей.
//
// Зачем существует: это одна из двух независимых осей абстракции (4.7).
// Executor выбирает, КАК стратегия воплощается — через сокеты (socketexec,
// этап 0) или через перехват пакетов (packetexec, этап 1). Вторая ось,
// PacketSource/Sink (откуда берутся пакеты), — деталь уже пакетного
// исполнителя, здесь её нет.
//
// Что знает: как по возможностям исполнителя отказать неисполнимой стратегии
// явной ошибкой (а не молча), и как провести готовый план desync через
// абстрактное соединение. Семантику примитивов знает desync, субстрат (сокет
// или пакет) — конкретные реализации Conn.
//
// Чего знать не должен: как устроен сокет или пакет (это socketexec/packetexec
// и их Conn), как выбирается стратегия (policy), как собирается телеметрия.
//
// # Разделение исполнителя и субстрата
//
// Логика исполнения одинакова для обоих этапов: проверить возможности,
// построить план, провести операции. Поэтому она собрана в Base, а всё
// различие субстратов вынесено в реализацию Conn. Это и есть граница, за
// которой переход на этап 1 не меняет контур управления: добавляется новая
// реализация Conn и новое объявление возможностей, а не новый контур.
package executor
