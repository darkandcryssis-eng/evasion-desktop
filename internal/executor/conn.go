package executor

import (
	"context"

	"github.com/fitting-1c/evasion/internal/desync"
)

// Conn — соединение, через которое исполняется стратегия, в терминах двух
// операций плана desync.
//
// Это и есть граница между общей логикой исполнения и субстратом. Реализация в
// режиме прокси (socketexec) отправляет реальные данные через сокет ОС, а
// фейки — raw-сокетом; реализация перехвата (packetexec) обе операции выполняет
// переписыванием пакетов. Общая логика (Base) про это различие не знает.
//
// Все реализации обязаны учитывать отмену контекста: исполнение стратегии
// происходит в контуре соединения, которое может быть закрыто в любой момент.
type Conn interface {
	// Input возвращает событие, по которому строится план: нагрузку,
	// направление, порядковый номер и признак ClientHello. Вызывается один
	// раз в начале исполнения.
	Input() desync.Input

	// SendReal отправляет операцию с куском реальной нагрузки. Куски,
	// отправленные подряд, составляют исходную нагрузку. Операция передаётся
	// целиком, а не отдельными полями: пакетному исполнителю нужно смещение в
	// потоке (Op.StreamOffset) для номера последовательности — при дублировании
	// и обратном порядке порядок отправки не равен положению в потоке. Op.Frame
	// сообщает обрамление; реализация, не умеющая запрошенного, обязана вернуть
	// ошибку, а не отправить иначе.
	SendReal(ctx context.Context, op desync.Op) error

	// SendFake отправляет фейковый пакет с правками полей заголовка. Фейк
	// должен быть замечен DPI, но отвергнут сервером; за это отвечают правки
	// (низкий TTL, порча суммы, неверный номер последовательности).
	SendFake(ctx context.Context, op desync.Op) error
}
