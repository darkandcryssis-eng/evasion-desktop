// Пакет strategy определяет представление стратегии обхода как двоичного дерева
// примитивов, его валидацию, каноническую форму, сериализацию и реестр видов
// примитивов.
//
// Зачем существует: это единственный тип данных, который мутирует генетический
// поиск (generator), поэтому его форма зафиксирована заданием (4.3) и вынесена в
// отдельный пакет. Представление намеренно отделено от исполнения: strategy
// ничего не знает о пакетах, сокетах и сети, поэтому генератор, работающий
// только с представлением, тестируется без Windows и без сети.
//
// Что знает: как устроено дерево действий, какие бывают виды примитивов и поля
// заголовков, что считать корректной стратегией, как привести дерево к
// однозначной форме и сосчитать по нему идентификатор и набор требуемых
// возможностей.
//
// Чего знать не должен: семантику исполнения примитивов (это desync), устройство
// пакетов (это packet), способ перехвата (это capture/executor). Любое знание о
// «как это выполнить в сети» здесь — ошибка слоя.
//
// Внешнее описание стратегии (из конфига или портфеля) считается НЕДОВЕРЕННЫМ и
// проходит полную валидацию до любого использования (требование 10.2).
