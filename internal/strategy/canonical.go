package strategy

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"

	"github.com/fitting-1c/evasion/internal/core"
)

// idBytes — сколько байт хеша берём в идентификатор. 16 байт (128 бит) дают
// 32 шестнадцатеричных знака: достаточно против случайных коллизий портфеля,
// компактно для ключей и логов.
const idBytes = 16

// canonicalBytes возвращает каноническую байтовую форму стратегии —
// детерминированную сериализацию её правил без идентификатора.
//
// Детерминизм обеспечивается тем, что все структуры сериализуются с
// фиксированным порядком полей (теги, объявленный порядок), а карты в форме не
// участвуют. Поэтому одинаковые по смыслу деревья дают одинаковые байты, а
// значит и одинаковый идентификатор.
func canonicalBytes(s *Strategy) ([]byte, error) {
	// Идентификатор не входит в каноническую форму: он из неё выводится, и его
	// включение сделало бы вычисление рекурсивным.
	return json.Marshal(s.Rules)
}

// ComputeID вычисляет идентификатор стратегии из её канонической формы.
//
// Идентификатор — префикс SHA-256 от канонических байт. Содержимое дерева
// однозначно определяет идентификатор: любая мутация меняет его, одинаковые
// деревья совпадают. Это даёт генератору дедупликацию, а хранилищу — стабильные
// ключи между запусками.
func ComputeID(s *Strategy) (core.StrategyID, error) {
	raw, err := canonicalBytes(s)
	if err != nil {
		return "", err
	}
	sum := sha256.Sum256(raw)
	return core.StrategyID(hex.EncodeToString(sum[:idBytes])), nil
}
