package strategy

// checkEncodedShape отсекает патологическое сериализованное описание до того,
// как его увидит декодер JSON.
//
// Зачем нужен отдельный проход. Разбор дерева стоит квадратично от глубины
// вложенности: каждый уровень Action.UnmarshalJSON делимитирует байты своего
// поддерева, то есть байты пересканируются столько раз, какова глубина. На
// недоверенном вводе (описание стратегии приходит из файла, 10.2) это выливается
// в секунды процессорного времени: замер показал 3.3 с на глубине 4000 против
// 3.2 мс на глубине 100. Линейная проверка перед разбором снимает это целиком,
// потому что законные стратегии неглубоки (предел MaxDepth — 16 уровней).
//
// Проверка намеренно НЕ является разбором: она не проверяет корректность JSON и
// не пытается сообщить о несбалансированных скобках — это работа декодера,
// который сделает это точнее. Здесь только два грубых предела: размер и
// вложенность.
func checkEncodedShape(data []byte, limits Limits) error {
	if limits.MaxInputBytes > 0 && len(data) > limits.MaxInputBytes {
		return verr(ErrInputTooLarge, "", "описание %d байт превышает предел %d",
			len(data), limits.MaxInputBytes)
	}
	if limits.MaxEncodedNesting <= 0 {
		return nil
	}

	depth := 0
	// inString: находимся внутри строкового литерала JSON. Скобки внутри строк
	// считать нельзя — значение вида "{{{{" иначе дало бы ложное срабатывание.
	inString := false
	// escaped: предыдущий байт был обратной косой чертой, поэтому текущий байт
	// экранирован и не может закрыть строку (случай "\"" ).
	escaped := false

	for i := 0; i < len(data); i++ {
		c := data[i]

		if inString {
			switch {
			case escaped:
				// Экранированный байт съедаем без разбора: для подсчёта скобок
				// важно лишь то, что он не закрывает строку. Многобайтовые
				// последовательности \uXXXX тоже безопасны — их байты не
				// содержат кавычки и обратной косой черты.
				escaped = false
			case c == '\\':
				escaped = true
			case c == '"':
				inString = false
			}
			continue
		}

		switch c {
		case '"':
			inString = true
		case '{', '[':
			depth++
			if depth > limits.MaxEncodedNesting {
				return verr(ErrInputTooDeep, "", "вложенность описания превышает предел %d",
					limits.MaxEncodedNesting)
			}
		case '}', ']':
			depth--
			if depth < 0 {
				// Закрывающих скобок больше, чем открывающих: ввод заведомо
				// некорректен. Дальше считать бессмысленно — отдаём декодеру,
				// он выдаст внятную синтаксическую ошибку с позицией.
				return nil
			}
		}
	}
	return nil
}
