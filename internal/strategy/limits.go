package strategy

// Limits — границы размера и формы стратегии, применяемые при валидации.
//
// Это защитные пределы (не тюнинг): они останавливают патологические деревья из
// недоверенного ввода и фаззинга и ограничивают дерево, которое строит
// генератор. Значения по умолчанию заданы в DefaultLimits, но вынесены в тип,
// чтобы потребитель (конфиг, тесты, генератор) мог их переопределить — магических
// чисел в коде валидации нет (требование 10.1).
type Limits struct {
	// MaxRules — наибольшее число правил в стратегии.
	MaxRules int
	// MaxDepth — наибольшая глубина дерева действий (корень = глубина 1).
	MaxDepth int
	// MaxNodes — наибольшее число узлов во всех деревьях одной стратегии.
	MaxNodes int
	// MaxFakePayload — наибольшая длина фейковых байт при подмене тела.
	MaxFakePayload int
	// MaxFragmentOffset — наибольшее смещение разреза при фрагментации.
	MaxFragmentOffset int
	// MaxFragmentDelayMs — наибольшая пауза между частями разреза, в
	// миллисекундах.
	//
	// Предел защитный, а не вкусовой: пауза задерживает установку соединения
	// ровно на своё значение, и мутант с паузой в минуту превратил бы
	// соединение в зависшее. Для DPI с окном пересборки осмысленны единицы
	// сотен миллисекунд.
	MaxFragmentDelayMs int

	// MaxInputBytes — наибольший размер сериализованного описания одной
	// стратегии.
	MaxInputBytes int
	// MaxEncodedNesting — наибольшая вложенность скобок в сериализованном
	// описании.
	//
	// Это предохранитель разбора, а не смысловой предел: смысловую глубину
	// дерева проверяет MaxDepth уже после разбора. Нужен отдельный предел
	// потому, что разбор вложенного описания стоит квадратично от глубины
	// (каждый уровень пересканирует байты своего поддерева), и без отсечки
	// глубокое описание из недоверенного файла сжигает процессор ещё до того,
	// как до него доберётся валидация. Замер: глубина 4000 — 3.3 с, глубина
	// 100 — 3.2 мс.
	MaxEncodedNesting int
}

// DefaultLimits возвращает разумные пределы по умолчанию.
//
// Числа подобраны с запасом: реальные стратегии малы (единицы правил, десятки
// узлов), а большие значения в основном защищают от разрастания при мутациях и
// от недоверенного ввода. Фрагментация ограничена ~64 КиБ — потолком размера
// IP-пакета; фейк тела — типичным размером ClientHello.
func DefaultLimits() Limits {
	return Limits{
		MaxRules:          32,
		MaxDepth:          16,
		MaxNodes:          256,
		MaxFakePayload:    4096,
		MaxFragmentOffset: 65535,
		// Две секунды: заметно больше вероятного окна пересборки и при этом
		// терпимо для пользователя, если стратегия окажется в работе.
		MaxFragmentDelayMs: 2000,

		// Оценка сверху: MaxNodes узлов по ~80 байт сериализованной формы —
		// около 20 КБ. 32 КиБ дают полуторный запас и при этом вдвое снижают
		// худшую стоимость разбора по сравнению с 64 КиБ.
		MaxInputBytes: 32 << 10,
		// Выводится из MaxDepth, а не задаётся отдельно: предохранитель не
		// должен отсекать то, что валидация считает законным.
		MaxEncodedNesting: 16 + encodedNestingOverhead,
	}
}

// encodedNestingOverhead — сколько уровней скобок добавляет обрамление сверх
// глубины самого дерева действий.
//
// Разбор: объект документа (1), массив правил (2), объект правила (3), объект
// действия каждого уровня (+1 на уровень), объект параметров внутри узла (+1).
// Итого обрамление — четыре уровня; берём с небольшим запасом, чтобы изменение
// формы документа не потребовало пересчёта.
const encodedNestingOverhead = 8

// normalized возвращает пределы, согласованные между собой.
//
// Нужно потому, что MaxEncodedNesting — предохранитель разбора, а MaxDepth —
// смысловой предел. Если в конфиге поднять MaxDepth, забыв про предохранитель,
// законные глубокие стратегии стали бы отвергаться на разборе с неочевидной
// причиной. Поэтому предохранитель поднимается до нужного минимума
// автоматически; опустить его ниже законного предела конфигом нельзя.
func (l Limits) normalized() Limits {
	if need := l.MaxDepth + encodedNestingOverhead; l.MaxEncodedNesting < need {
		l.MaxEncodedNesting = need
	}
	return l
}
