// Package quic извлекает имя сервера (SNI) из QUIC-пакета Initial.
//
// Зачем это движку. QUIC идёт по UDP, и TCP-десинк на него не влияет (3.3).
// Поэтому в первой версии трафик QUIC к отслеживаемым группам блокируется,
// чтобы приложение откатилось на TCP, где десинк уже работает. Чтобы блокировать
// ТОЛЬКО отслеживаемые группы, а не весь UDP/443 на машине, нужно знать имя
// сервера — и берётся оно там же, где у TCP: из ClientHello. В QUIC ClientHello
// лежит внутри зашифрованного пакета Initial, но Initial шифруется ключами,
// выводимыми из открытого Destination Connection ID по фиксированной соли (RFC
// 9001, раздел 5.2), так что расшифровать и прочитать SNI может кто угодно на
// пути — этим и пользуемся.
//
// Границы пакета намеренно узкие: только разбор и расшифровка клиентского
// Initial ради SNI. Пакет не строит QUIC-пакеты, не ведёт соединений и не
// расшифровывает ничего, кроме клиентского Initial QUIC v1. Любой разбор, по
// которому имя достать не удалось (не Initial, не v1, фрагментированный
// ClientHello, сбой расшифровки), — это honest «не знаю»: ExtractSNI возвращает
// ok == false, и вызывающий НЕ блокирует. Переблокировать вслепую хуже, чем
// пропустить (1.6): пропуск стоит отката приложения на TCP, а ложная блокировка
// рвёт связность.
