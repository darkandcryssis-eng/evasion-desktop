// Package discordvoice опознаёт начало голосового соединения Discord по форме
// первого UDP-пакета.
//
// Зачем это движку. Текст, картинки и вход в Discord идут по HTTPS/TCP:443 —
// их обходит основной контур. Голосовые каналы идут отдельно, по UDP к
// медиа-серверам Discord, без TLS и без имени сервера (SNI), и цензор режет их
// отдельно. Значит TCP-десинк на голос не влияет вовсе, а опознать голосовой
// поток «как все» — по имени — нельзя: имени в UDP нет.
//
// Ключевое наблюдение, на котором держится пакет: голосовое соединение Discord
// начинается с пакета обнаружения внешнего IP (IP discovery) строго
// определённой формы — 74 байта, тип 0x0001, поле длины 70 (Discord требует
// именно 74-байтный пакет с 15 марта 2023; 70-байтный вариант ответа больше не
// получает). Эта форма достаточно характерна, чтобы опознавать начало
// голосового потока ПО САМОМУ ПАКЕТУ, не ведя список IP-адресов Discord. Так
// обход голоса получается самонастраивающимся: ни диапазонов IP в конфиге, ни
// их устаревания.
//
// Границы намеренно узкие. Пакет только ОПОЗНАЁТ начало голоса по форме
// первого пакета. Он не строит пакеты, не ведёт соединений, не знает про
// WinDivert и про стратегии десинка — это дело вызывающего (как tlsparse не
// знает про перехват). Честный отказ — основа безопасности (1.6): на всём, что
// не распознано точно, функции возвращают false, и вызывающий голос не трогает;
// ложно принять чужой UDP за голос Discord хуже, чем пропустить (можно задеть
// посторонний трафик).
//
// Источник формата пакета — официальная документация Discord и её разбор в
// сообществе; взята только структура пакета (общедоступный факт протокола), а
// не чьи-либо подобранные параметры обхода.
