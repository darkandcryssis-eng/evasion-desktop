// Пакет capture — источник и приёмник пакетов сетевого уровня (2.5).
//
// Зачем существует и почему с первого коммита. Логику десинка нужно
// проверять без сети и без Windows, а контур управления (flow, packetexec)
// строить поверх устойчивого шва. Задание требует объявить этот шов
// интерфейсами сразу (2.5): если оставить его на потом, пакетный путь
// прирастёт к конкретной реализации, и офлайн-воспроизведение с синтетикой
// прикрутить будет уже некуда.
//
// # Две оси, которые легко спутать (4.7)
//
//   - Executor выбирает, КАК стратегия воплощается: socketexec (этап 0) или
//     packetexec (этап 1).
//   - PacketSource/PacketSink выбирают, ОТКУДА берутся пакеты, и это деталь
//     пакетного исполнителя, а не альтернатива ему. Источник живёт только
//     внутри packetexec.
//
// Реализации по возрастанию риска: synthetic (тесты, здесь), pcap
// (офлайн-воспроизведение, команда replay), windivert (живой режим, только
// Windows, подключается отдельным шагом на машине с драйвером).
//
// # Владение буфером Packet.Data
//
// Data действителен только до следующего Recv того же источника. Зрелые
// backend переиспользуют буфер приёма (так устроен и WinDivert: один буфер на
// handle), поэтому потребитель, удерживающий пакет дольше одного оборота
// (например таблица потоков), ОБЯЗАН скопировать Data. Контракт задан по
// строжайшему backend нарочно: иначе потребители, написанные против безопасной
// синтетики, молча ломались бы на живом перехвате — тот же класс порчи, что
// подмена одного признака готовности другим.
//
// # Контрольные суммы при инъекции
//
// Windows требует у инъектируемых пакетов верных контрольных сумм даже при
// включённом offloading на сетевой карте (basil00/WinDivert, issue #134).
// Поэтому приёмник windivert обязан пересчитать суммы перед отправкой
// (packet.RecomputeChecksums). Записано здесь, в контракте шва, чтобы это не
// всплыло дефектом «реинъекция молча отбрасывается» при реализации windivert.
// Синтетического приёмника это не касается: он никуда не шлёт.
//
// # Границы
//
// Пакет только переносит пакеты. Что с ними делать (разрез, фейк, отбрасывание)
// — дело desync и packetexec; killswitch и автооткат при потере связности
// (1.6) — дело control и packetexec. Здесь ни того, ни другого нет.
