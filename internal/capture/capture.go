package capture

import "github.com/fitting-1c/evasion/internal/core"

// Packet — один пакет сетевого уровня, прошедший через источник.
//
// Несёт сырые байты, направление и непрозрачные данные повторной инъекции.
// Разбор байт — дело пакета packet (Dissect и далее); capture в содержимое
// не заглядывает, он только переносит.
type Packet struct {
	// Data — сырой пакет начиная с IP-заголовка.
	//
	// Владение: действителен только до следующего Recv того же источника
	// (см. doc.go). Удерживающий дольше обязан скопировать.
	Data []byte

	// Dir — направление пакета. Переиспользуем core.Direction: та же сущность
	// «к серверу / от сервера», и второй параллельный enum только разошёлся бы
	// с первым.
	Dir core.Direction

	// Reinject — непрозрачные данные, которые источник приложил к пакету для
	// его последующей отправки.
	//
	// Толкует их ТОЛЬКО парный приёмник того же backend: windivert кладёт сюда
	// свой адрес (направление, интерфейс, флаги), без которого WinDivertSend
	// не знает, куда вернуть пакет. У synthetic и pcap поле nil. Смешивать
	// пакеты одного backend с приёмником другого — ошибка программиста, а не
	// случай, который обязан обрабатываться в бою: источник и приёмник живого
	// режима создаются парой.
	Reinject any
}

// PacketSource — откуда приходят пакеты (2.5).
//
// Recv возвращает очередной пакет. Живой источник блокирует до прихода пакета
// или ошибки; синтетический и файловый по исчерпании возвращают io.EOF.
type PacketSource interface {
	Recv() (Packet, error)
}

// PacketSink — куда уходят пакеты (2.5).
//
// Send отправляет пакет. Для живого приёмника это повторная инъекция в стек, и
// он опирается на Packet.Reinject; для него же обязательны верные контрольные
// суммы (см. doc.go).
type PacketSink interface {
	Send(Packet) error
}
