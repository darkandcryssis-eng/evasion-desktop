package desync

import (
	"fmt"
	"time"

	"github.com/fitting-1c/evasion/internal/strategy"
)

// OpKind — вид операции плана.
//
// Деление ровно на две операции отражает единственное различие субстратов,
// которое невозможно скрыть: реальные данные соединения в режиме прокси уходят
// через сокет ОС (их заголовком не управляешь), а фейки вбрасываются отдельно с
// полным контролем над заголовком. Исполнитель перехвата реализует обе операции
// переписыванием пакетов, но различать их всё равно обязан: реальные данные
// нельзя повредить, фейки — наоборот, должны быть отвергнуты сервером.
type OpKind uint8

const (
	// OpSendReal — отправить кусок реальной полезной нагрузки соединения.
	// Куски, отправленные подряд, вместе составляют исходную нагрузку
	// (возможно, разрезанную на части). Правок заголовка не несёт.
	OpSendReal OpKind = iota
	// OpSendFake — отправить фейковый пакет: он должен быть замечен DPI, но
	// отвергнут сервером (низкий TTL, порча контрольной суммы, неверный номер
	// последовательности). Несёт правки заголовка, которые и делают его
	// фейком.
	OpSendFake
)

// String возвращает метку вида операции для золотых тестов и логов.
func (k OpKind) String() string {
	switch k {
	case OpSendReal:
		return "send_real"
	case OpSendFake:
		return "send_fake"
	default:
		return fmt.Sprintf("OpKind(%d)", uint8(k))
	}
}

// Framing — как исполнитель должен оформить кусок на проводе.
//
// Это единственное свойство разреза, которое невозможно восстановить из одних
// только байтов: разрез на уровне TCP и на уровне IP дают разные пакеты.
// socketexec реализует только FrameSegment и отвергает FrameIPFragment по
// возможностям (IP-фрагментация требует контроля над пакетами, 1.5.1);
// packetexec реализует оба. Поле введено сразу, чтобы форма плана не менялась
// при появлении packetexec.
type Framing uint8

const (
	// FrameSegment — обычный кусок потока: целый неразрезанный либо часть после
	// разреза на уровне TCP. Отправляется как самостоятельные данные/сегмент.
	FrameSegment Framing = iota
	// FrameIPFragment — IP-фрагмент одной датаграммы. Соседние такие куски
	// исполнитель собирает в один фрагментированный на уровне IP пакет
	// (группировку выполняет packetexec).
	FrameIPFragment
)

// String возвращает метку обрамления для золотых тестов и логов.
func (f Framing) String() string {
	switch f {
	case FrameSegment:
		return "segment"
	case FrameIPFragment:
		return "ip_fragment"
	default:
		return fmt.Sprintf("Framing(%d)", uint8(f))
	}
}

// Op — одна операция плана.
type Op struct {
	// Kind — вид операции.
	Kind OpKind
	// Payload — байты для отправки. Для OpSendReal это срез исходной нагрузки
	// (без копирования). Для OpSendFake это итоговое содержимое фейка:
	// правки тела (подмена фейковыми байтами) уже применены здесь, а правки
	// полей заголовка — ещё нет, они в Edits.
	Payload []byte
	// Edits — правки полей заголовка, которые исполнитель должен применить к
	// сформированному пакету фейка. Пусто у OpSendReal. Содержит только правки
	// полей заголовка; правка тела здесь не фигурирует, так как уже отражена в
	// Payload.
	Edits []strategy.TamperParams
	// InsertMD5Sig — вставить в этот фейк опцию TCP MD5 Signature (RFC 2385) с
	// заведомо неверной подписью (ActionMD5Sig). Делает пакет фейком так же,
	// как правки Edits: исполнитель перехвата вставляет опцию и двигает
	// смещение данных TCP. Пусто у OpSendReal и у фейков без md5sig. Сокетный
	// исполнитель поле игнорирует (возможности CapMD5Sig у него нет, шлюз
	// отвергнёт стратегию раньше).
	InsertMD5Sig bool
	// InsertIPv6HopByHop — вставить в этот фейк заголовок расширения IPv6
	// Hop-by-Hop (ActionIPv6Ext). Как и InsertMD5Sig, делает пакет фейком.
	// Применимо только к IPv6; на IPv4 исполнитель вернёт ошибку
	// недоступности, и движок пропустит оригинал сырьём.
	InsertIPv6HopByHop bool
	// Frame — как оформить кусок на проводе.
	Frame Framing
	// StreamOffset — смещение байт этой операции от начала нагрузки события.
	//
	// Нужно пакетному исполнителю: номер последовательности TCP зависит от
	// ПОЛОЖЕНИЯ куска в потоке, а не от порядка отправки. Дублирование ставит
	// фейк на ту же позицию, что и реальные данные, а обратный порядок меняет
	// порядок отправки — в обоих случаях порядок отправки не равен положению, и
	// без этого поля сегмент получил бы чужой номер последовательности.
	// Сокетный исполнитель поле игнорирует: он пишет байты по порядку.
	StreamOffset int
	// DelayBefore — пауза перед этой операцией.
	//
	// Хранится у операции, а не отдельным видом операции, потому что пауза —
	// свойство момента отправки, а не самостоятельное действие: отдельный вид
	// заставил бы исполнителя различать операции, которые ничего не отправляют,
	// и усложнил бы золотые тесты без пользы.
	//
	// Паузы вложенных разрезов складываются: внешний разрез добавляет свою
	// паузу к той, что уже назначил внутренний.
	DelayBefore time.Duration
}

// Plan — упорядоченная последовательность операций, в которую разворачивается
// стратегия для одного исходящего события.
//
// Порядок операций значим: он задаёт порядок отправки. Обратный порядок
// фрагментов (FragReverse) выражается именно порядком операций в плане, а не
// отдельным флагом, — так исполнителю не нужно знать о «реверсе», он просто
// отправляет операции подряд.
//
// Требуемые возможности по плану НЕ вычисляются: план не хранит сведений о
// фрагментации, обратном порядке и дублировании — они растворены в содержимом и
// порядке операций. Поэтому проверку исполнимости ведёт исполнитель по самой
// стратегии (strategy.RequiredCapabilities), до построения плана.
type Plan struct {
	Ops []Op
}
