// Пакет desync задаёт семантику примитивов обхода и строит из стратегии план
// исходящих операций.
//
// Зачем существует: это общий слой толкования дерева стратегии, которым
// пользуются оба исполнителя (socketexec на этапе прокси, packetexec на этапе
// перехвата). Разделение «поиск отдельно, исполнение одной стратегии отдельно»
// повторяет устройство Geneva (4.1): generator работает с представлением
// (strategy), desync — с семантикой, executor — с субстратом.
//
// Главное свойство: план не привязан к субстрату. Один и тот же обход дерева
// даёт одинаковый план и для сокета, и для перехвата пакетов, поэтому два
// исполнителя не могут разойтись в толковании одной стратегии — расходиться
// нечему. Исполнитель лишь реализует операции плана доступными ему средствами и
// отвергает те, что не умеет, по механизму возможностей (пакет executor).
//
// Что знает: что означают примитивы Send, Drop, Duplicate, Tamper, Fragment;
// как из дерева получается упорядоченная последовательность отправок; как
// отличается реальная отправка от фейка.
//
// Чего знать не должен: как операция превращается в байты сокета или пакета
// (это executor и его реализации), как перехватывается трафик (это capture),
// как выбирается стратегия (это policy). Пакет чист: не делает ввода-вывода,
// не обращается к сети, детерминирован и целиком тестируется офлайн — что и
// требует порядок работ 8.3 (золотые тесты до интеграции).
