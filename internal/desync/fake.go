package desync

// synthFakePayload формирует тело фейка заданной длины.
//
// Содержимое фейка почти не влияет на обход DPI: фейк всё равно отбраковывается
// сервером (низкий TTL, порча), а инспекции обычно важны длина и положение в
// потоке, а не байты. Но содержимое обязано быть ДЕТЕРМИНИРОВАННЫМ: от этого
// зависят золотые тесты и воспроизведение записи (replay). Поэтому байты не
// случайны, а циклически копируются из исходной нагрузки — так фейк внешне
// похож на реальные данные (та же «фактура»), но полностью предсказуем.
//
// Это осознанно простой выбор v1. Если позже понадобится фейк, неотличимый от
// настоящего ClientHello по содержимому, здесь появится отдельная стратегия
// формирования; на форму плана это не повлияет.
func synthFakePayload(src []byte, n int) []byte {
	if n <= 0 {
		return nil
	}
	out := make([]byte, n)
	if len(src) == 0 {
		// Исходных байт нет — заполняем нулями, лишь бы детерминированно.
		return out
	}
	for i := range out {
		out[i] = src[i%len(src)]
	}
	return out
}
