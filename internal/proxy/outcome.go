// Типы записей TLS, которые различимы по первому байту ответа сервера.
//
// Больше от разбора ответа здесь и не требуется: нужно отличить «сервер начал
// рукопожатие» от «сервер отказал предупреждением». Полный разбор ответа — не
// дело прокси, он перекладывает поток, а не толкует его.
const (
	tlsRecordAlert     = 0x15
	tlsRecordHandshake = 0x16
)

// ConnOutcome — исход одного соединения в виде данных.
//
// Зачем существует. Контур управления учится на живом трафике (1.4 п. 4), но
// узнать исход он может только от того, кто этот трафик вёл. Журнал для этого
// не годится: он текст для человека, а решения принимаются по числам.
//
// Это данные, а не представление (2.2): ни готовых формулировок, ни оценок —
// только то, что наблюдалось.
type ConnOutcome struct {
	// Target — цель радиуса, к которой отнести наблюдение.
	//
	// Берётся из выбора (Selection.Target), а не из имени соединения, и это
	// принципиально: оценки ключуются целью радиуса («youtube.com»), а
	// соединение пришло к её поддомену («www.youtube.com»). Записав имя
	// соединения, наблюдение попало бы в оценку другой четвёрки (6.1) и
	// решения по цели его никогда бы не увидели.
	Target string
	// Host, SNI — имена соединения, как их видел прокси. Для журнала и разбора
	// спорных случаев.
	Host string
	SNI  string

	// StrategyID — применённая стратегия; пусто, если не применялась ничего.
	StrategyID core.StrategyID
	// Trial — соединение шло по проверяемой ступени (5.1).
	Trial bool
	// StrategyApplied — стратегия действительно применилась.
	//
	// Отдельный признак, а не вывод из непустого StrategyID: стратегия могла
	// быть выбрана и не примениться (режим наблюдения, начало потока не
	// ClientHello, недоступная точка разреза). Без этого признака такие
	// соединения выглядели бы проверкой стратегии, не будучи ею, — та же порча
	// измерений, что при утечке по IPv6 (3.2, 4.7 п. 2).
	StrategyApplied bool

	// Outcome, Reason — исход и его причина в словаре core.
	Outcome core.Outcome
	Reason  core.Reason

	// At — когда соединение завершилось.
	At time.Time
	// BytesUp, BytesDown — сколько переложено в каждую сторону.
	BytesUp, BytesDown int64
	// FirstByte — через сколько пришёл первый байт ответа сервера.
	FirstByte time.Duration
	// Connect — сколько заняла установка соединения с сервером.
	//
	// Ближайшее к RTT, что известно о пользовательском соединении: сам RTT
	// движок на этом пути не измеряет, а время установки TCP им определяется.
	Connect time.Duration
	// ConnectMeasured — удалось ли измерить Connect. Признак обязателен по той
	// же причине, что и у FirstByte: нулевая длительность законна.
	ConnectMeasured bool
	// FirstByteMeasured — удалось ли измерить FirstByte. Нулевая задержка
	// законна (ответ быстрее разрешения часов), поэтому ноль без признака
	// читался бы как «мгновенно», а не как «не измерено». Правило уже стоило
	// проекту трёх дефектов.
	FirstByteMeasured bool
}

// OutcomeSink принимает исходы соединений.
//
// Интерфейс объявлен здесь, а реализуется снаружи: прокси знает, что он
// наблюдал, но не знает, кому и зачем это нужно. Так контур управления не
// попадает в зависимости прокси, а прокси — в зависимости контура, и переход
// на этап 1 не требует менять ни того, ни другого (4.7 п. 4).
//
// Реализация обязана быть быстрой и не блокировать: её зовёт горутина
// соединения. Контур для этого кладёт наблюдение в очередь и отбрасывает при
// переполнении (control.Engine.Observe).
type OutcomeSink interface {
	// ConnOutcome сообщает исход завершившегося соединения.
	ConnOutcome(ConnOutcome)
}

// relayResult — чем кончилось перекладывание потока.
type relayResult struct {
	// up, down — переложено байт в каждую сторону.
	up, down int64
	// gotDown — сервер прислал хоть один байт.
	gotDown bool
	// firstDownByte — первый байт ответа сервера; значим при gotDown.
	firstDownByte byte
	// firstDownAfter — через сколько пришёл первый байт; значим при
	// firstDownMeasured.
	firstDownAfter    time.Duration
	firstDownMeasured bool
	// serverEndedFirst — поток от сервера кончился раньше, чем поток от
	// клиента.
	//
	// Это ключевой признак для различения «нас оборвали» и «пользователь
	// ушёл»: без него закрытие клиентом выглядело бы провалом стратегии.
	serverEndedFirst bool
	// downErr — чем кончилось чтение от сервера.
	downErr error
}

// classifyConn выводит исход соединения из того, что наблюдалось.
//
// Чистая функция намеренно: это главное суждение прокси о стратегии, и
// проверяться оно обязано на всех ветвях сразу, без сети и соединений.
//
// Правила и почему они такие:
//
//  1. Стратегия не применилась — исход «не определено», независимо от причины.
//     Главное правило классификации всего проекта: вес такого наблюдения
//     нулевой (5.7), и ошибиться в эту сторону безопаснее, чем приписать
//     стратегии чужую неудачу.
//  2. Сервер ответил предупреждением TLS — «не определено», а не провал: до
//     сервера дошли, DPI обманут, а чем недоволен сервер — не про стратегию.
//  3. Сервер ответил рукопожатием — успех.
//  4. Ответа нет, но первым ушёл клиент — «не определено»: пользователь закрыл
//     вкладку, и винить в этом стратегию нельзя.
//  5. Ответа нет, и первым кончился поток от сервера — провал. Сброс и тихое
//     закрытие не различаются: с точки зрения стратегии это одно и то же —
//     ClientHello ушёл, ответа не было.
//
// Чего эта классификация НЕ умеет и почему. Замедление (throttled) здесь не
// определяется: для него нужен замер полосы за окно (5.3), а на
// пользовательском трафике окно портит сам пользователь — он может
// остановиться в любой момент. Замедление остаётся за медленным уровнем проб.
// Молчаливое отбрасывание, которое пользователь переждал и закрыл сам, тоже
// попадёт в «не определено»: из прокси оно неотличимо от потери интереса.
// Именно этот пробел закрывает пассивный сигнал по ретрансмиссиям (5.10).
func classifyConn(applied bool, r relayResult) (core.Outcome, core.Reason) {
	if !applied {
		return core.OutcomeInconclusive, core.ReasonStrategyNotApplied
	}
	if r.gotDown {
		if r.firstDownByte == tlsRecordAlert {
			return core.OutcomeInconclusive, core.ReasonTLSRejected
		}
		return core.OutcomeOK, core.ReasonHandshakeDone
	}
	if !r.serverEndedFirst {
		return core.OutcomeInconclusive, core.ReasonCanceled
	}
	switch {
	case isTimeout(r.downErr):
		return core.OutcomeFail, core.ReasonTimeout
	default:
		return core.OutcomeFail, core.ReasonReset
	}
}

// isReset сообщает, что соединение было сброшено другой стороной.
//
// Отличать сброс от тихого закрытия нужно не классификации (для неё это одно и
// то же), а журналу: сброс сразу после ClientHello — характерная подпись
// вмешательства, и видеть её в записях полезно.
func isReset(err error) bool {
	if err == nil || errors.Is(err, io.EOF) {
		return false
	}
	return errors.Is(err, syscall.ECONNRESET) || errors.Is(err, net.ErrClosed)
}

// downstreamWatcher — обёртка над чтением от сервера, запоминающая первый байт
// ответа и время его прихода.
//
// Нужна потому, что исход соединения определяется именно первым ответом: по
// нему видно, обманулся ли DPI. Обёртка выделяется одна на соединение и к
// бюджету решения по ClientHello (8.1) отношения не имеет — тот бюджет про
// выбор стратегии, а это уже перекладывание потока.
type downstreamWatcher struct {
	r     io.Reader
	start time.Time

	got       bool
	firstByte byte
	after     time.Duration
	measured  bool
}

// Read читает от сервера, попутно запоминая первый полученный байт.
func (w *downstreamWatcher) Read(p []byte) (int, error) {
	n, err := w.r.Read(p)
	if n > 0 && !w.got {
		w.got = true
		w.firstByte = p[0]
		w.after = time.Since(w.start)
		// Признак измерения ставится всегда, когда замер состоялся, даже если
		// он дал ноль: ноль здесь означает «быстрее разрешения часов», а не
		// «не измеряли».
		w.measured = true
	}
	return n, err
}
