// Пакет proxy — локальный SOCKS5-сервер режима прокси (этап 0).
//
// Зачем существует: это способ применить десинк к трафику приложения, не
// трогая систему. Приложение (браузер, curl) настраивается на этот прокси; для
// каждого соединения прокси перехватывает начало — ClientHello, — исполняет
// выбранную стратегию через socketexec и дальше просто перекладывает поток в обе
// стороны. SOCKS5 — не средство обхода и не туннель: трафик никуда не уходит на
// внешние серверы, IP не меняется (1.3). Это именно локальный инструмент
// применения стратегии.
//
// Что знает: протокол SOCKS5 (метод без аутентификации, команда CONNECT), как
// вычленить ClientHello из начала потока, как применить стратегию к нему и
// перекладывать остальной поток.
//
// Чего знать не должен: как выбирается стратегия (это StrategyProvider, который
// на M6 реализует policy), как устроен десинк (это desync/socketexec), как
// собирается телеметрия сверх событий жизненного цикла соединения.
//
// Граница этапа: прокси действует только на приложения, настроенные на него.
// Системного охвата здесь нет — он появляется на этапе 1 (перехват). QUIC идёт
// по UDP мимо TCP-прокси и здесь не обрабатывается; его блокировка (3.3) —
// забота режима перехвата.
