// Пакет policy — горячая таблица: какому соединению какая стратегия.
//
// Зачем существует. Решение принимается на каждом соединении в самом горячем
// его месте — между разбором ClientHello и первой отправкой байт. Любая
// задержка здесь оплачивается пользователем напрямую, на каждом открытии
// соединения, поэтому бюджет жёсткий: не более 10 мкс на решение и ноль
// аллокаций (8.1). Отсюда устройство: таблица читается как неизменяемый
// снимок, без блокировок и без карт под мьютексом (4.2, правило 1).
//
// Что знает: как сопоставить имя соединения (host из SOCKS и SNI из
// ClientHello) с записью радиуса поражения и вернуть готовый выбор —
// стратегию вместе с её идентификатором.
//
// Чего знать не должен: откуда взялась стратегия и почему она считается
// лучшей (это scoring), когда подменять снимок и по каким командам (это
// control), как стратегия исполняется (desync, socketexec), как измеряется
// исход (probe). Пакет отвечает только на вопрос «что применить к этому
// соединению прямо сейчас».
//
// # Снимок неизменяем, подмена атомарна
//
// Snapshot после создания не меняется никогда. Вся работа — нормализация
// имён, вычисление идентификаторов стратегий, построение карты — сделана в
// NewSnapshot, то есть вне горячего пути. Table держит указатель на текущий
// снимок и подменяет его атомарно (Install). Читатели видят либо старый
// снимок целиком, либо новый целиком; промежуточного состояния не существует,
// и соединение, начатое до подмены, доигрывает по снимку, который оно
// прочитало.
//
// Цена: на время подмены в памяти живут два снимка, и наблюдения, собранные
// по старому, относятся к старому решению. Это и требовалось: исход
// соединения должен приписываться той стратегии, которая к нему реально
// применилась.
//
// # Почему карта с обходом меток, а не перебор доменов
//
// Радиус задан суффиксами доменов, и наивная проверка — перебрать все домены
// и для каждого сравнить суффикс. Это O(N) от размера таблицы, а таблицу
// наполняет автопилот, так что её размер нам неподвластен.
//
// Здесь сделано наоборот: карта нормализованных имён, а по имени соединения
// идёт обход его суффиксов по границам метк. Для "a.b.youtube.com" это
// "a.b.youtube.com", "b.youtube.com", "youtube.com", "com" — не больше
// поиска на метку, то есть O(числа метк) независимо от размера таблицы.
//
// Побочная выгода: обход идёт от самого длинного имени к самому короткому,
// поэтому более точная запись выигрывает у более общей бесплатно. Если в
// таблице есть и "youtube.com", и "www.youtube.com", к "www.youtube.com"
// применится вторая. Без этого свойства итог зависел бы от порядка, в котором
// control перечислил записи, а это не то, чем можно управлять осмысленно.
//
// # Ноль аллокаций: где они могли бы возникнуть
//
// Три места, каждое закрыто намеренно:
//
//  1. Сравнение суффикса. Привычное strings.HasSuffix(host, "."+d) выделяет
//     строку на каждое сравнение. Обход по меткам не склеивает ничего.
//  2. Приведение регистра. strings.ToLower выделяет строку, когда в имени
//     есть заглавные буквы. Имя приводится к нижнему регистру в массив на
//     стеке, а поиск в карте идёт выражением m[string(buf)] — такой поиск
//     компилятор выполняет без копии ключа.
//  3. Отрезание порта. net.SplitHostPort для имени без порта выделяет
//     ошибку — на горячем пути этого нельзя. Порт здесь и не нужен: proxy
//     отдаёт host и port раздельно, а SNI порта не содержит.
//
// Регистр приводится только для ASCII — так и определена
// регистронезависимость DNS. Из этого следует требование к записям: домен
// обязан быть в ASCII, то есть IDN записывается в punycode. Иначе запись
// молча не совпадала бы с именем из ClientHello, где punycode приходит всегда
// (RFC 6066). NewSnapshot такую запись отвергает с внятной ошибкой, а не
// принимает бесполезной.
//
// # Две ступени допуска в одной записи
//
// Задание требует ступенчатого допущения к трафику (5.1): проверяемая
// стратегия получает долю реальных соединений (по умолчанию 5%), а остальные
// идут по действующей. Поэтому запись несёт две стратегии, и выбор между ними
// делается жребием на каждое соединение.
//
// Жребий, а не детерминированное разделение по имени. Доля должна быть долей
// СОЕДИНЕНИЙ, а не долей хостов: разделение по хешу имени отправило бы весь
// хост в одну ветвь, и сравнение мерило бы разницу между хостами, а не между
// стратегиями. Цена жребия — невоспроизводимость: по журналу нельзя заранее
// сказать, какому соединению что досталось. Поэтому применённая ветвь
// отмечается в самом выборе (proxy.Selection.Trial) и доходит до наблюдения
// вместе с исходом.
//
// Чего policy про ступени не знает: какой доле трафика рисковать (это
// конфигурация, 5.7), какая стратегия в каком статусе (это портфель в
// control) и когда проверку прекращать. Снимок переносит уже принятое
// решение. Мгновенный откат по побочному вреду (5.1) выражается подменой
// снимка без проверяемой ветви — то есть обычным Install, а не особым путём.
//
// # Что считается попаданием
//
// Имён у соединения два, и они могут не совпадать: host из запроса SOCKS и
// SNI из ClientHello. Сначала проверяется SNI, и только затем host. Причина в
// том, кого мы обманываем: DPI классифицирует соединение по имени в
// ClientHello, значит стратегию нужно выбирать по тому же имени. Цена: если
// обе записи есть и они разные, запись по host не сработает — её перекроет
// запись по SNI.
//
// По IP-адресам сопоставление не делается вовсе: радиус задан доменами, а
// совпадение адреса с доменным суффиксом было бы случайностью. Так же
// поступает config.DomainSet. Запрет держится при построении снимка — запись,
// похожая на адрес, отвергается, — и этого достаточно: всякий суффикс IPv4
// состоит из цифр и точек, а IPv6 содержит двоеточие, поэтому совпасть с
// записью они не могут. Горячий путь на адреса не тратится вовсе.
//
// # Деградация всегда в прозрачный пропуск
//
// Пустая таблица, неустановленный снимок, неизвестное имя, имя длиннее
// допустимого — всё это даёт пустой выбор, то есть соединение проходит без
// изменений. Ошибок наружу пакет на горячем пути не отдаёт: своя ошибка
// выбора не повод рвать пользовательское соединение (1.6). Отсутствие записи
// и запись с nil-стратегией различаются вторым результатом Lookup, а не видом
// выбора, — нулевое значение не подменяет отсутствие данных.
