package policy

import (
	"sync/atomic"

	"github.com/fitting-1c/evasion/internal/proxy"
)

// Table — горячая таблица решений, которую читают горутины соединений.
//
// Состоит из одного указателя на текущий снимок. Чтение — одна атомарная
// загрузка, запись — одна атомарная подмена. Мьютекса здесь нет намеренно: он
// поставил бы горутины соединений в очередь за правом прочитать таблицу, а
// читают её все и в самый неудобный момент — на открытии соединения.
//
// Владелец у таблицы один: горутина control. Только она вызывает Install
// (4.2, правило 2). Горутины соединений вызывают Select и больше ничего.
// Table не содержит ни scoring.Table, ни хранилища: пересчёт делает control в
// стороне, а сюда кладёт уже готовый результат.
//
// Копировать Table нельзя — внутри атомарный указатель; поэтому все методы на
// указателе, а go vet поймает попытку копирования.
type Table struct {
	cur atomic.Pointer[Snapshot]
}

// Убеждаемся на этапе компиляции, что таблица годится прокси как провайдер
// стратегий: proxy.StrategyProvider — это и есть шов, ради которого пакет
// существует, и сам proxy при подмене StaticProvider на policy не меняется.
var _ proxy.StrategyProvider = (*Table)(nil)

// NewTable создаёт таблицу без снимка.
//
// Пустая таблица применима сразу: до первого Install она пропускает весь
// трафик без изменений. Это нужное поведение, а не заглушка — прокси может
// начать принимать соединения раньше, чем control посчитает первый снимок, и
// до этого момента правильно ничего не делать.
func NewTable() *Table { return &Table{} }

// Install публикует новый снимок. Вызывает только горутина-владелец.
//
// Подмена атомарна: соединение видит либо прежний снимок целиком, либо новый
// целиком. Уже начатые соединения доигрывают по тому снимку, который успели
// прочитать, — иначе исход приписался бы стратегии, которая к соединению не
// применялась.
//
// Install(nil) переводит таблицу в прозрачный режим. Это законная команда
// («выключить автопилот»), а не признак ошибки, поэтому и не ошибка.
func (t *Table) Install(s *Snapshot) { t.cur.Store(s) }

// Current возвращает живой снимок; nil, если снимок ещё не установлен.
// Снимок неизменяем, поэтому отдавать его наружу безопасно: изменить его
// через возвращённый указатель нельзя.
func (t *Table) Current() *Snapshot { return t.cur.Load() }

// Rev возвращает номер живого снимка; 0 означает, что снимка нет.
func (t *Table) Rev() uint64 { return t.cur.Load().Rev() }

// Select выбирает стратегию для соединения — реализация
// proxy.StrategyProvider.
//
// Горячий путь целиком: атомарная загрузка, приведение имени в буфер на стеке,
// несколько поисков в карте. Ни блокировок, ни аллокаций, ни ошибок наружу:
// при любом сомнении возвращается пустой выбор, и соединение проходит
// прозрачно (1.6).
//
// Признак meta.IsClientHello здесь не проверяется сознательно. Решение «в
// начале потока не ClientHello, применять нечего» уже принимает proxy, и
// принимает оно его по собственному разбору, а не по нашему мнению.
// Дублировать это условие значило бы завести второе место, где оно может
// разойтись с первым.
func (t *Table) Select(meta proxy.ConnMeta) proxy.Selection {
	sel, _ := t.cur.Load().Lookup(meta.Host, meta.SNI)
	return sel
}
