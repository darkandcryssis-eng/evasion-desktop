package policy

import (
	"math/rand/v2"

	"github.com/fitting-1c/evasion/internal/proxy"
)

// permilleScale — знаменатель доли трафика. Промилле, а не проценты: доля по
// умолчанию 5% (5.7), и при шаге в процент её нельзя было бы уточнить, не
// меняя единицу измерения.
const permilleScale = 1000

// record — запись снимка: что применять к имени.
//
// Две ступени допуска живут в одной записи, потому что выбор между ними
// делается на соединение (1.4 п. 4) и обязан быть одним решением: сначала
// найти запись, затем выбрать ветвь. Разнести их по двум таблицам значило бы
// искать дважды.
type record struct {
	// target — имя записи, то есть цель радиуса.
	//
	// Хранится здесь, чтобы выбор мог её назвать: исход соединения относится к
	// цели радиуса, а не к имени соединения. Без этого наблюдение по
	// "www.youtube.com" попало бы в оценку другой четвёрки (6.1), и решения по
	// "youtube.com" его бы не увидели.
	target string
	// main — действующая стратегия (статус active). Пустой выбор означает
	// прозрачный пропуск.
	main proxy.Selection
	// trial — проверяемая стратегия (статус testing). Пустой выбор означает,
	// что проверять на этой цели нечего.
	trial proxy.Selection
	// permille — доля соединений, отдаваемая trial. Ноль означает «проверки
	// нет»; при непустом trial ноль запрещён построением снимка, иначе
	// проверка выглядела бы настроенной, не происходя ни разу.
	permille uint32
}

// pick выбирает ступень допуска для одного соединения.
//
// Жребий бросается на каждое соединение независимо — это и есть живой A/B из
// 1.4 п. 4: доля 5% означает пять процентов соединений, а не пять процентов
// хостов. Детерминированное разделение (например, по хешу имени) дало бы
// второе: весь хост попадал бы в одну ветвь, и сравнение считало бы разницу
// между хостами, а не между стратегиями.
//
// Цена: последовательность решений невоспроизводима, и по журналу нельзя
// заранее сказать, какому соединению что досталось. Поэтому применённая ветвь
// отмечается в самом выборе (proxy.Selection.Trial) и доходит до наблюдения
// вместе с исходом.
func (r record) pick() proxy.Selection {
	sel := r.main
	if r.permille != 0 && drawPermille() < r.permille {
		sel = r.trial
	}
	// Цель проставляется и пустому выбору: «к этой цели не применялось ничего»
	// — тоже наблюдение, и отнести его надо к цели, а не потерять.
	sel.Target = r.target
	return sel
}

// drawPermille бросает жребий в диапазоне [0, 1000).
//
// math/rand/v2 выбран намеренно: его глобальный источник держит состояние на
// каждый поток исполнения, поэтому обходится без блокировки и без аллокаций —
// оба запрещены на горячем пути (4.2, правило 1). Проверено
// testing.AllocsPerRun вместе с остальным решением.
//
// Качество случайности здесь не криптографическое, и это достаточно: жребий
// делит трафик, а не защищает секреты. Предсказуемость последовательности
// ничего не открывает наблюдателю, который и так видит сами соединения.
func drawPermille() uint32 {
	return rand.Uint32N(permilleScale)
}
