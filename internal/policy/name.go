package policy

import (
	"errors"
	"fmt"
	"strings"
)

// maxNameLen — предельная длина имени, с которым пакет работает.
//
// 253 знака — максимум для доменного имени в представлении с точками. Имя
// длиннее не может быть именем из DNS, поэтому и записью радиуса быть не
// может: запись отвергается при построении снимка, а имя соединения такой
// длины просто не совпадает ни с чем (прозрачный пропуск). Заодно это даёт
// горячему пути право держать буфер приведения регистра на стеке: размер
// известен заранее и не зависит от входа.
const maxNameLen = 253

// errEmptyName и прочие — ошибки проверки записи. Неэкспортируемые: на них
// никто не разветвляется, они доходят до человека текстом через NewSnapshot.
var (
	errEmptyName    = errors.New("пустой домен")
	errNameTooLong  = errors.New("домен длиннее 253 знаков")
	errEmptyLabel   = errors.New("пустая метка в домене")
	errNameNotASCII = errors.New("домен записан не в ASCII: имя в ClientHello приходит в punycode (RFC 6066), запишите домен так же")
	errNameWildcard = errors.New("звёздочка в домене не нужна: запись и так покрывает все поддомены")
	errNameIsIP     = errors.New("домен похож на IP-адрес, а радиус задаётся именами")
)

// canonicalDomain приводит домен записи к той же форме, в которой горячий путь
// видит имя соединения, и отвергает запись, которая не смогла бы совпасть ни с
// чем.
//
// Строгость здесь намеренная: принять запись, которая никогда не сработает, —
// худший исход, чем ошибка при построении. Молча бесполезная запись выглядит
// как настроенный радиус и прячет настоящую причину, по которой стратегия не
// применяется (тот же довод, что у desync.ErrCutUnavailable: операция не
// должна оказываться пустой, выглядя выполненной).
//
// Вызывается только при построении снимка, поэтому аллокации здесь допустимы.
func canonicalDomain(d string) (string, error) {
	d = strings.TrimSpace(d)
	// Ведущую и завершающую точки считаем одной и той же записью:
	// ".youtube.com", "youtube.com." и "youtube.com" — одно и то же
	// (так же поступает config.normalizeDomain).
	d = strings.Trim(d, ".")
	if d == "" {
		return "", errEmptyName
	}
	if len(d) > maxNameLen {
		return "", errNameTooLong
	}
	if strings.Contains(d, "..") {
		return "", errEmptyLabel
	}
	for i := 0; i < len(d); i++ {
		c := d[i]
		switch {
		case c >= 0x80:
			return "", errNameNotASCII
		case c == '*':
			return "", errNameWildcard
		case c >= 'a' && c <= 'z', c >= 'A' && c <= 'Z', c >= '0' && c <= '9':
		case c == '-' || c == '_' || c == '.':
		default:
			// Сюда попадают "youtube.com:443", "https://youtube.com" и прочие
			// формы, в которых домен перепутан с адресом или ссылкой.
			return "", fmt.Errorf("недопустимый знак %q в домене", string(c))
		}
	}
	// Знаки уже проверены на ASCII, поэтому ToLower здесь делает ровно то же,
	// что foldName на горячем пути. Соответствие этих двух путей —
	// предусловие работы таблицы, оно закреплено тестом.
	d = strings.ToLower(d)
	if looksLikeAddress([]byte(d)) {
		return "", errNameIsIP
	}
	return d, nil
}

// foldName переписывает имя соединения в dst в канонической форме: без
// обрамляющих пробелов, без завершающих точек, в нижнем регистре ASCII.
// Возвращает длину записанного и признак пригодности имени.
//
// Работает без аллокаций: отрезание делается срезами, а копия ложится в
// переданный буфер — на горячем пути это массив на стеке. Непригодное имя
// (пустое или длиннее буфера) не ошибка, а отказ от сопоставления: такому
// соединению стратегия не назначается, и оно проходит прозрачно.
func foldName(dst []byte, name string) (int, bool) {
	for len(name) > 0 && (name[0] == ' ' || name[0] == '\t') {
		name = name[1:]
	}
	for len(name) > 0 {
		c := name[len(name)-1]
		if c != ' ' && c != '\t' && c != '.' {
			break
		}
		name = name[:len(name)-1]
	}
	if name == "" || len(name) > len(dst) {
		return 0, false
	}
	for i := 0; i < len(name); i++ {
		c := name[i]
		// Регистр приводится только для ASCII: именно так определена
		// регистронезависимость DNS. Байты вне ASCII переносятся как есть —
		// они всё равно не совпадут с записью, которая обязана быть ASCII.
		if c >= 'A' && c <= 'Z' {
			c += 'a' - 'A'
		}
		dst[i] = c
	}
	return len(name), true
}

// looksLikeAddress сообщает, что имя выглядит IP-адресом, а не доменом.
//
// Вызывается только при построении снимка: отвергнув запись-адрес один раз,
// мы избавляем горячий путь от этой проверки навсегда (см. Snapshot.match).
//
// Проверка намеренно грубая: двоеточие означает IPv6 (в домене оно и так
// запрещено), имя из одних цифр и точек — IPv4. Доменное имя из одних цифр
// невозможно: числовых доменов верхнего уровня не существует, поэтому ложных
// отказов проверка не даёт. net.ParseIP не используется: он разбирает адрес,
// а нам нужно лишь отличить его от имени, причём и для неполных записей вида
// "250.185.78", которые ParseIP адресом не считает.
func looksLikeAddress(name []byte) bool {
	for i := 0; i < len(name); i++ {
		if name[i] == ':' {
			return true
		}
	}
	for i := 0; i < len(name); i++ {
		c := name[i]
		if (c < '0' || c > '9') && c != '.' {
			return false
		}
	}
	return len(name) > 0
}
