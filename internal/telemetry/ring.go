package telemetry

import (
	"log/slog"
	"sync"
	"time"
)

// DefaultRingCapacity — число событий, хранимых в кольцевом буфере по
// умолчанию (блок 7). Настраивается: значение принадлежит конфигурации (10.1),
// здесь задана подстановка, чтобы пакет был пригоден без неё.
const DefaultRingCapacity = 10000

// Field — одно поле события.
//
// Значение хранится как есть, а не приводится к строке: движок отдаёт данные, а
// не представление (2.2), и потребитель сам решит, как их показать. Приведение
// к строке здесь потеряло бы тип — число стало бы неотличимо от строки с
// цифрами, и машинная обработка усложнилась бы.
type Field struct {
	Key   string
	Value any
}

// Event — событие в кольцевом буфере.
type Event struct {
	// Time — момент события.
	Time time.Time
	// Level — уровень важности.
	Level slog.Level
	// Message — сообщение.
	Message string
	// Fields — поля события.
	Fields []Field
}

// Ring — кольцевой буфер последних событий в памяти.
//
// Зачем нужен: чтобы после сбоя увидеть, что происходило прямо перед ним, не
// включая отладку заранее. Подробный журнал включают, когда сбой уже случился,
// а он к тому времени уже произошёл — буфер решает именно эту задачу.
//
// Защищён мьютексом, и это осознанно. В буфер идут события жизненного цикла
// соединения — единицы на соединение, а не на пакет, и на таком потоке мьютекс
// не заметен. Вариант без блокировок (захват слота атомарным сложением)
// быстрее, но чтение снимка при одновременной записи возвращало бы смесь
// старых и новых записей — именно в момент разбора сбоя это вредно. Задание
// прямо требует: везде, кроме горячего пути, прямолинейный скучный код (8.1).
type Ring struct {
	mu sync.Mutex
	// buf — хранилище фиксированного размера. Выделяется один раз: буфер
	// существует всё время работы, и перевыделение только добавило бы мусора.
	buf []Event
	// next — куда писать следующее событие.
	next int
	// filled — сколько слотов заполнено; перестаёт расти по достижении
	// ёмкости. Отдельно от next, потому что по одному next нельзя отличить
	// пустой буфер от полного.
	filled int
	// total — сколько событий прошло через буфер всего, включая вытесненные.
	// Нужно, чтобы потребитель знал, сколько записей потеряно.
	total int64
}

// NewRing создаёт буфер заданной ёмкости. Неположительная ёмкость заменяется
// значением по умолчанию.
func NewRing(capacity int) *Ring {
	if capacity <= 0 {
		capacity = DefaultRingCapacity
	}
	return &Ring{buf: make([]Event, capacity)}
}

// Append добавляет событие, вытесняя самое старое при заполнении.
func (r *Ring) Append(e Event) {
	r.mu.Lock()
	defer r.mu.Unlock()

	r.buf[r.next] = e
	r.next = (r.next + 1) % len(r.buf)
	if r.filled < len(r.buf) {
		r.filled++
	}
	r.total++
}

// Snapshot возвращает события от самого старого к самому новому.
//
// Отдаётся копия: потребитель получает согласованный срез, который не изменится
// под ним при следующей записи. Для буфера на десять тысяч записей копия стоит
// доли миллисекунды и делается только при разборе сбоя или по запросу status.
func (r *Ring) Snapshot() []Event {
	r.mu.Lock()
	defer r.mu.Unlock()

	out := make([]Event, 0, r.filled)
	if r.filled == 0 {
		return out
	}
	// Начало — самое старое событие. При неполном буфере это нулевой слот,
	// при полном — тот, куда будет записано следующее.
	start := 0
	if r.filled == len(r.buf) {
		start = r.next
	}
	for i := 0; i < r.filled; i++ {
		out = append(out, r.buf[(start+i)%len(r.buf)])
	}
	return out
}

// Stats возвращает состояние буфера.
//
// Число потерянных событий сообщается отдельно: без него снимок выглядел бы
// полной картиной, тогда как при переполнении он лишь хвост. Разбирая сбой,
// важно знать, что начало событий утрачено.
func (r *Ring) Stats() (held int, capacity int, total int64, dropped int64) {
	r.mu.Lock()
	defer r.mu.Unlock()

	dropped = r.total - int64(r.filled)
	if dropped < 0 {
		dropped = 0
	}
	return r.filled, len(r.buf), r.total, dropped
}
