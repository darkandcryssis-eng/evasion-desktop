// Пакет telemetry — счётчики, кольцевой буфер событий и обработчик журнала.
//
// Зачем существует. Наивное «логировать каждый отправленный пакет» убило бы
// движок: на горячем пути десятки тысяч событий в секунду, и форматирование
// строк там дороже самой обработки. Поэтому наблюдаемость разделена на три
// слоя с разной стоимостью (блок 7):
//
//	всегда включено   счётчики                  атомарные инкременты
//	всегда включено   жизненный цикл соединения единицы событий на соединение
//	по включению      подробности по пакетам    только отладка, с ограничением частоты
//
// Что знает: как дёшево считать, как хранить последние события в памяти и как
// отдать журнал в машинно-читаемом виде.
//
// Чего знать не должен: что означают события и как по ним принимаются решения.
// Пакет даёт измерительные приборы, а не выводы.
//
// # Почему счётчики перечислены, а не названы строками
//
// Счётчик на горячем пути обязан быть атомарным инкрементом без аллокаций
// (4.2, правило 1). Карта «имя → счётчик» потребовала бы либо блокировки, либо
// sync.Map с выделением памяти при первой записи — и то и другое на горячем
// пути недопустимо. Поэтому набор счётчиков задан перечислением и лежит в
// массиве: инкремент — это индексация и атомарное сложение.
//
// Цена: добавление счётчика требует правки перечисления, а не только места
// вызова. Это осознанный обмен — зато измерение не искажает измеряемое.
//
// Разрезы по стратегиям и целям здесь НЕ ведутся: их множество меняется на
// ходу, и ключом служит четвёрка «стратегия × цель × точка наблюдения × время»
// (6.1). Такие наблюдения принадлежат store, который для этого и устроен.
//
// # Почему кольцевой буфер под мьютексом, а не без блокировок
//
// Буфер нужен, чтобы после сбоя увидеть, что происходило прямо перед ним, не
// включая отладку заранее. Записываются в него события жизненного цикла
// соединения — единицы на соединение, а не на пакет. На таком потоке мьютекс
// не заметен, а снимок буфера получается согласованным.
//
// Вариант без блокировок (захват слота атомарным сложением) быстрее, но чтение
// снимка при одновременной записи возвращало бы смесь старых и новых записей, и
// именно в момент разбора сбоя это вредно. Задание прямо требует: везде, кроме
// горячего пути, — прямолинейный скучный код (8.1).
