// Package warp регистрирует устройство в сети Cloudflare WARP через их
// публичный HTTP API — без браузера, без логина, без установки клиента
// Cloudflare. На выходе — комплект ключей и адреса пира, из которого
// собирается WireGuard-конфигурация для нашего встроенного туннеля (Phase 2.2).
//
// Зачем это движку. Задание 1.3 первоначально запрещало туннели. Решение
// владельца (сессия от 2026-11-01) переписало его: ISP режет SYN до
// Cloudflare Spectrum (`162.159.*.235`), где живут voice-гейтвеи Discord, и
// на TLS-уровне это непробиваемо. Единственный способ — туннель к точке, до
// которой провайдер пропускает трафик. WARP годится по трём причинам:
//
//   - endpoint 162.159.192.1 (`engage.cloudflareclient.com`) открыт у ISP,
//     проверено живым прогоном;
//   - бесплатен и анонимен (регистрация анонимная, никаких емейлов);
//   - WireGuard-протокол — стандартный, никакого vendor-lock-in: если
//     Cloudflare прикроет лавочку, тот же код peer-ится с собственным VPS по
//     одному WireGuard-конфигу.
//
// Границы пакета. Он только РЕГИСТРИРУЕТ и ОТДАЁТ account. Открытие туннеля,
// маршрутизация, прокси-слой — все следующие фазы (2.2–2.5), в этом пакете
// их нет. Так же как tlsparse знает про TLS, но не про сеть.
//
// Чего пакет НЕ делает по дизайну:
//
//   - не записывает account на диск сам: это задача вызывающего (команда CLI),
//     чтобы пакет был чистый и проверялся на синтетике;
//   - не ходит в сеть при запуске тестов: HTTP-клиент инъектируется, тесты
//     работают против `httptest.Server`;
//   - не апгрейдит в WARP+ (платный): для voice-гейтвеев Discord хватает
//     бесплатного тарифа.
//
// Протокол. Открытый спек API есть у `wgcf` (MIT) — обратно-инженерный клиент
// WARP на Go. Код пакета написан самостоятельно, но форматы запросов и
// ответов (имена полей, пути, заголовки) сверены с их реализацией. При
// изменении API Cloudflare константы в `api.go` обновляются одной правкой.
