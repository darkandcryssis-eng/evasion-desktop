package packet

// Арифметика контрольных сумм по RFC 1071 (сумма 16-битных слов в дополнении до
// единицы) и инкрементальный пересчёт по RFC 1624.
//
// Это самый непрозрачный код пакета, поэтому пояснения здесь густые: ошибка в
// контрольной сумме не проявляется как сбой программы — пакет просто молча
// отбрасывается сетью, и выглядит это как «стратегия не работает».

// onesComplementSum накапливает сумму 16-битных слов буфера в сетевом порядке
// байт, добавляя её к initial.
//
// Сумма возвращается несвёрнутой (до 32 бит), чтобы несколько участков можно
// было сложить без потери переносов и свернуть один раз в конце.
func onesComplementSum(data []byte, initial uint32) uint32 {
	sum := initial
	i := 0
	// Идём парами байт: слово = старший байт слева (big-endian, сетевой
	// порядок). Условие i+1 < len гарантирует, что оба обращения в границах.
	for ; i+1 < len(data); i += 2 {
		sum += uint32(data[i])<<8 | uint32(data[i+1])
	}
	// Непарный последний байт участвует как старший байт слова, младший — ноль.
	// Это предписано RFC 1071 и не является дополнением буфера нулём: сам
	// буфер не меняется.
	if i < len(data) {
		sum += uint32(data[i]) << 8
	}
	return sum
}

// fold сворачивает 32-битную накопленную сумму в 16 бит, не инвертируя.
//
// Отдельно от foldChecksum, потому что инкрементальный пересчёт складывает уже
// инвертированные слагаемые и инвертирует результат ровно один раз.
func fold(sum uint32) uint16 {
	// Переносы из старшей половины прибавляем к младшей, пока они не кончатся.
	// Цикл нужен потому, что само прибавление может породить новый перенос.
	for sum>>16 != 0 {
		sum = sum&0xffff + sum>>16
	}
	return uint16(sum)
}

// foldChecksum сворачивает сумму и инвертирует, давая готовое значение поля
// контрольной суммы.
func foldChecksum(sum uint32) uint16 {
	return ^fold(sum)
}

// IPv4HeaderChecksum считает контрольную сумму заголовка IPv4 по его байтам.
//
// Поле суммы (байты 10–11) в подсчёте участвовать не должно: оно само является
// результатом, и старое значение исказило бы его. Поэтому участок байт
// пропускается при суммировании — буфер при этом не изменяется, что важно,
// поскольку представления здесь работают поверх чужой памяти.
//
// Возвращает 0 при слишком коротком буфере: это не контрольная сумма, а признак
// того, что считать нечего; вызывающий код обязан проверять длину заголовка до
// вызова (так делает Dissect).
func IPv4HeaderChecksum(header []byte) uint16 {
	if len(header) < ipv4MinHeaderLen {
		return 0
	}
	sum := onesComplementSum(header[:ipv4ChecksumOff], 0)
	sum = onesComplementSum(header[ipv4ChecksumOff+2:], sum)
	return foldChecksum(sum)
}

// pseudoSumIPv4 считает сумму псевдозаголовка IPv4 для контрольных сумм TCP и
// UDP: адрес источника, адрес назначения, нулевой байт, номер протокола и длина
// данных протокола верхнего уровня.
//
// Псевдозаголовок нигде не передаётся — он существует только в арифметике суммы,
// чтобы подмена адресов не прошла незамеченной.
func pseudoSumIPv4(src, dst []byte, proto uint8, l4Len int) uint32 {
	var sum uint32
	sum = onesComplementSum(src, sum)
	sum = onesComplementSum(dst, sum)
	// Нулевой байт и номер протокола образуют одно 16-битное слово, поэтому
	// протокол попадает в младшую половину.
	sum += uint32(proto)
	sum += uint32(uint16(l4Len))
	return sum
}

// pseudoSumIPv6 считает сумму псевдозаголовка IPv6.
//
// Отличия от IPv4: длина данных верхнего уровня занимает 32 бита, а номер
// протокола («следующий заголовок») стоит после трёх нулевых байт. Нули на сумму
// не влияют, поэтому в арифметике они опущены — но длина складывается двумя
// словами, иначе старшая половина 32-битного поля потерялась бы.
func pseudoSumIPv6(src, dst []byte, nextHeader uint8, l4Len int) uint32 {
	var sum uint32
	sum = onesComplementSum(src, sum)
	sum = onesComplementSum(dst, sum)
	sum += uint32(uint32(l4Len) >> 16)
	sum += uint32(uint32(l4Len) & 0xffff)
	sum += uint32(nextHeader)
	return sum
}

// l4Checksum считает контрольную сумму протокола верхнего уровня: сумма
// псевдозаголовка плюс сумма байт самого протокола, в которой поле суммы
// пропущено (по той же причине, что и в IPv4HeaderChecksum).
//
// csumOff — смещение поля контрольной суммы внутри l4 (16 для TCP, 6 для UDP).
func l4Checksum(pseudo uint32, l4 []byte, csumOff int) uint16 {
	if csumOff+2 > len(l4) {
		return 0
	}
	sum := onesComplementSum(l4[:csumOff], pseudo)
	sum = onesComplementSum(l4[csumOff+2:], sum)
	return foldChecksum(sum)
}

// UpdateChecksum16 пересчитывает контрольную сумму после замены одного
// 16-битного слова, не пересуммируя весь пакет (RFC 1624, формула «HC' =
// ~(~HC + ~m + m'»).
//
// Зачем нужен инкрементальный путь: правка поля заголовка — основная операция
// десинка, и полный пересчёт суммы по всему пакету на каждую правку был бы
// лишней работой на горячем пути.
//
// Тонкость, из-за которой здесь используется именно формула RFC 1624, а не
// более ранняя из RFC 1141: наивная формула даёт неверный результат −0 (0xFFFF)
// в краевых случаях. Инвертирование слагаемых по модулю дополнения до единицы
// этого избегает.
func UpdateChecksum16(current, oldWord, newWord uint16) uint16 {
	// ~HC + ~m + m' в 32-битной арифметике; инверсии берём от 16-битных
	// значений, расширяя до 32 бит, чтобы переносы не потерялись.
	// Свёртка с инверсией результата и даёт внешнее «~(...)» формулы.
	sum := uint32(^current) + uint32(^oldWord) + uint32(newWord)
	return foldChecksum(sum)
}
