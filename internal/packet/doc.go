// Пакет packet разбирает и собирает заголовки IPv4, IPv6, TCP и UDP и считает
// контрольные суммы.
//
// Зачем существует: структурированный разбор вынесен отдельным слоем, чтобы
// логика десинка работала с полями, а не со смещениями байт. Это же даёт
// возможность фаззить разбор изолированно — самое выгодное место для фаззинга во
// всём проекте, поскольку здесь обрабатываются данные из сети.
//
// Что знает: раскладку байт перечисленных протоколов, арифметику контрольных
// сумм, устройство цепочки заголовков расширения IPv6 и опций TCP.
//
// Чего знать не должен: ничего о стратегиях, о выборе стратегии, о соединениях и
// об их состоянии, о способе перехвата. Пакет не принимает решений — он только
// читает и пишет байты.
//
// # Принципы реализации
//
// Разбор без копирования: результат разбора — смещения в исходном буфере, а не
// новые срезы и не новые структуры. Это даёт ноль аллокаций на горячем пути
// (бюджеты 8.1) и позволяет править пакет на месте.
//
// Данные из сети считаются враждебными всегда. Паник в этом пакете нет: каждое
// обращение к байтам предварено проверкой границ, а некорректный ввод порождает
// ошибку, а не аварию. Отсюда же отказ от panic в конструкторах представлений.
package packet
