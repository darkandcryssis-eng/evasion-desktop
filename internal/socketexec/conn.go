package socketexec

import (
	"context"
	"errors"
	"io"

	"github.com/fitting-1c/evasion/internal/desync"
)

// Ошибки реализации соединения.
var (
	// ErrFakeUnsupported — попытка отправить фейк в режиме прокси. В норме сюда
	// не доходит: стратегию с фейком отвергает шлюз возможностей до построения
	// плана. Это защитная сетка на случай рассогласования возможностей и
	// фактического поведения.
	ErrFakeUnsupported = errors.New("socketexec: фейки в режиме прокси недоступны")
	// ErrFrameUnsupported — запрошено обрамление, которого режим прокси не
	// умеет (IP-фрагментация). Тоже должно отсекаться возможностями раньше.
	ErrFrameUnsupported = errors.New("socketexec: обрамление недоступно в режиме прокси")
)

// Conn реализует executor.Conn поверх соединения с сервером.
//
// Отвечает только за отправку ClientHello (возможно, разрезанного): релеинг
// остального потока — задача пакета proxy. Апстрим задан как io.Writer, а не
// net.Conn, намеренно: так исполнитель тестируется офлайн на записывающем
// буфере, без сети и без Windows.
type Conn struct {
	in       desync.Input
	upstream io.Writer
	// wrote — была ли хотя бы попытка записи в апстрим.
	//
	// Нужно вызывающему, чтобы знать, можно ли безопасно откатиться к
	// прозрачному пропуску после ошибки. Если в сокет ещё ничего не уходило,
	// начало потока можно послать как есть и соединение уцелеет; если уходило —
	// поток уже необратимо начат.
	wrote bool
}

// NewConn создаёт соединение исполнителя поверх апстрима с заданным событием.
//
// in описывает исходящий ClientHello: нагрузку, направление, порядковый номер и
// признак ClientHello (его определяет вызывающий через tlsparse).
func NewConn(upstream io.Writer, in desync.Input) *Conn {
	return &Conn{in: in, upstream: upstream}
}

// Input возвращает событие, по которому строится план.
func (c *Conn) Input() desync.Input { return c.in }

// SendReal записывает кусок реальной нагрузки в апстрим.
//
// Каждый вызов — одна запись в сокет; последовательность вызовов и задаёт
// сегментацию (при включённом TCP_NODELAY, см. EnableSegmentation). Пустые
// куски сюда не попадают: desync их не порождает.
func (c *Conn) SendReal(ctx context.Context, op desync.Op) error {
	if op.Frame != desync.FrameSegment {
		return ErrFrameUnsupported
	}
	if err := ctx.Err(); err != nil {
		return err
	}
	// Смещение в потоке (op.StreamOffset) здесь не нужно: сокет пишет байты по
	// порядку, и номер последовательности назначает стек ОС. Поле существует
	// для пакетного исполнителя.
	//
	// Признак ставится ДО записи, а не после удачной: при ошибке часть байт
	// могла уже уйти в сеть, и считать, что поток не начат, было бы опасно —
	// вызывающий послал бы начало второй раз.
	c.wrote = true
	// io.Writer.Write обязан записать все байты или вернуть ошибку, поэтому
	// частичную запись отдельно не обрабатываем — это нарушение контракта
	// Writer, которое проявится ошибкой.
	_, err := c.upstream.Write(op.Payload)
	return err
}

// Wrote сообщает, была ли попытка записи в апстрим.
//
// По нему вызывающий решает, допустим ли откат к прозрачному пропуску после
// ошибки исполнения.
func (c *Conn) Wrote() bool { return c.wrote }

// SendFake в режиме прокси недоступен и всегда возвращает ошибку.
//
// Параметры игнорируются: до вызова дело не доходит в корректном сценарии, а
// если дошло — это ошибка согласования, и исполнять фейк, которого мы не умеем,
// нельзя (молчаливое игнорирование запрещено, 4.7 п. 2).
func (c *Conn) SendFake(_ context.Context, _ desync.Op) error {
	return ErrFakeUnsupported
}
