// Пакет socketexec исполняет стратегию в пользовательском пространстве через
// обычный TCP-сокет (этап 0, режим прокси).
//
// Зачем существует: это реализация executor.Executor и executor.Conn для этапа
// прокси. Реальные данные соединения уходят через сокет ОС, а исполнение
// стратегии сводится к тому, КАК именно эти данные записываются.
//
// # Граница возможностей на Windows
//
// На целевой платформе (Windows 10/11) из пользовательского пространства нельзя
// вбросить TCP-пакет: отправка TCP поверх raw-сокетов запрещена ОС начиная с
// Windows XP SP2 (документация Microsoft, «TCP/IP Raw Sockets»). Поэтому
// канонический фейк (отдельный пакет с низким TTL, который видит DPI, но не
// получает сервер) в чистом userspace невыразим — он обязан быть вне
// TCP-машины ОС, а это требует драйвера (WinDivert, этап 1).
//
// Отсюда набор возможностей v1 — только сегментация TCP (CapFragmentTCP):
// ClientHello разрезается на несколько записей в сокет, что разносит SNI по
// сегментам и обходит наивное сопоставление по SNI. Фейки, дублирование и
// порча — через механизм возможностей отвергаются до этапа 1 (executor
// возвращает CapabilityError). Это честное отражение возможностей платформы, а
// не искусственное ограничение: этап 0 обкатывает весь контур (оценка, бандит,
// генератор) на пространстве сегментации, а полная механика приходит с
// packetexec без изменения контура.
//
// Следствие: на этапе 0 права администратора не нужны вовсе — raw-сокетов нет.
//
// Чего знать не должен: про SOCKS-сервер и релеинг остального потока (это
// proxy), про выбор стратегии (policy), про телеметрию. socketexec только
// исполняет готовую стратегию для одного соединения.
