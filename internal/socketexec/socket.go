package socketexec

import (
	"net"

	"github.com/fitting-1c/evasion/internal/core"
	"github.com/fitting-1c/evasion/internal/executor"
)

// Capabilities возвращает возможности исполнителя этапа прокси.
//
// Только сегментация TCP. Обоснование границы — в документации пакета: вброс
// TCP-пакетов из пользовательского пространства на Windows запрещён ОС, поэтому
// фейки, дублирование реальных данных и порча контрольных сумм здесь
// невыразимы и отвергаются шлюзом возможностей (executor.EnsureExecutable).
//
// Возвращается функцией, а не экспортированной переменной: набор не должен
// случайно мутировать из другого пакета.
func Capabilities() core.PrimitiveSet {
	return core.PrimitiveSet(0).With(core.CapFragmentTCP).With(core.CapDelay)
}

// Executor — исполнитель стратегии через сокет. Встраивает executor.Base,
// добавляя лишь объявленный набор возможностей; вся логика исполнения
// (проверка возможностей, построение плана, проведение операций) — в Base.
type Executor struct {
	executor.Base
}

// New создаёт исполнитель этапа прокси.
func New() Executor {
	return Executor{Base: executor.Base{Caps: Capabilities()}}
}

// статическая проверка соответствия интерфейсу.
var _ executor.Executor = Executor{}

// EnableSegmentation включает на соединении с сервером режим, при котором
// отдельные записи с большей вероятностью уходят отдельными сегментами.
//
// Технически это выключение алгоритма Нейгла (TCP_NODELAY): иначе ОС склеивает
// подряд идущие записи в один сегмент, и разрез, задуманный стратегией,
// исчезает ещё до отправки.
//
// Оговорка, которую нельзя скрывать: на уровне сокета отправку отдельными
// сегментами гарантировать невозможно — это свойство стека ОС, и даже с
// TCP_NODELAY ядро вправе объединить данные. Полный контроль над границами
// сегментов даёт только этап 1 (перехват пакетов). Поэтому эффективность
// сегментации на этапе 0 проверяется живой сетью, а не этим кодом.
func EnableSegmentation(conn *net.TCPConn) error {
	return conn.SetNoDelay(true)
}
