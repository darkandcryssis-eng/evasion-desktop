// Package tunnel поднимает userspace-туннель WireGuard к Cloudflare WARP на
// базе зарегистрированного аккаунта (`internal/warp`). Через туннель
// предоставляется `net.Dialer`-подобный интерфейс: любое TCP-соединение,
// открытое через `(*Tunnel).DialContext`, идёт в сеть Cloudflare и дальше по
// их маршрутизации к настоящему адресу.
//
// Зачем это движку (решение владельца, 2026-11-01): ISP режет SYN до
// Cloudflare Spectrum (`162.159.*.235`), где живут voice-гейтвеи Discord.
// Пакет туда не выходит из сети провайдера, и TLS-десинк тут бесполезен —
// нет пакета, в который можно было бы влезть. Туннель к Cloudflare даёт тот
// самый «второй конец», до которого провайдер пропускает (endpoint
// `engage.cloudflareclient.com:2408` открыт), а дальше трафик уже внутри
// Cloudflare и до Spectrum дотягивается своим путём.
//
// Границы.
//
//   - Пакет НЕ меняет системную маршрутизацию. Пакеты через туннель идут,
//     только если вызывающий явно использовал `Tunnel.DialContext`. Весь
//     остальной трафик машины уходит прямым путём, как и был — это требование
//     владельца «основной трафик не трогаем».
//   - Пакет НЕ монтирует TUN-устройство в ОС. Всё userspace, через
//     `wireguard-go` + gVisor netstack. Админских прав для туннеля не нужно.
//     (hosts-подмена и WinDivert в соседних пакетах админа требуют по своим
//     причинам.)
//   - Пакет НЕ знает, кого именно резолвить и куда звонить. Он отдаёт
//     Dialer; маршрутизация «что через туннель» — забота SNI-прокси (Phase
//     2.3). Так пакет остаётся чистым и тестируется без Discord-специфики.
//
// Выход из тупика с размером бинарника: `wireguard-go` + `gvisor` добавляют
// ~15 МБ к бинарнику. Это сознательная цена: альтернативы (CGO к WireGuard,
// внешний клиент) противоречат правилам проекта (3.1: без CGO) или UX
// (пользователь что-то ставит отдельно). Остаточного вреда нет: туннель
// поднимается только когда владелец включил `transport_tunnel.enabled`.
