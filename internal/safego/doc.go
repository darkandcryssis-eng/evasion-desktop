// Пакет safego запускает фоновые горутины с восстановлением после паники.
//
// Зачем существует. Движок работает от администратора на Windows, держит
// открытый дескриптор WinDivert и правит системные настройки (файрвол, hosts).
// Паника в любой из его 20+ фоновых горутин роняет весь процесс и оставляет
// эти правки висеть до перезагрузки. Инвариант 1.3 блюпринта
// (`docs/ARCHITECTURE.md`) прямо запрещает такой исход: паника в фоне не должна
// быть смертью процесса.
//
// Что делает пакет. Предоставляет Group — набор горутин с общим жизненным
// циклом (как у errgroup, но без распространения ошибок) и обязательным
// `recover()` внутри каждой. При панике:
//
//  1. запись в журнал с именем горутины, значением паники и трассой;
//  2. вызов onPanic — коллбек верхнего уровня (у движка он поднимает прозрачный
//     режим killswitch);
//  3. горутина завершается, остальные продолжают работу;
//  4. процесс не умирает.
//
// Что НЕ делает. Не пытается перезапустить упавшую горутину: паника —
// сигнал о нарушении инварианта, повторный запуск с тем же состоянием даст
// тот же результат. Правильный ответ — остановиться безопасно и дать
// пользователю диагностировать.
//
// Чем это отличается от обычного `go func` с `defer recover()`. Общий счётчик
// и Wait позволяют верхнему уровню дождаться остановки всех фоновых работ
// при завершении — иначе `main` возвращал бы управление до того, как
// горутины успеют корректно закрыть ресурсы.
