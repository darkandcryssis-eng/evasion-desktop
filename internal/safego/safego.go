package safego

import (
	"fmt"
	"log/slog"
	"runtime/debug"
	"sync"
)

// OnPanic — коллбек, вызываемый при панике внутри горутины группы.
//
// Получает имя горутины, значение паники и байты трассы (как возвращает
// runtime/debug.Stack). Не должен сам паниковать и не должен блокироваться
// надолго: вызывается синхронно, пока панику ещё обрабатывает defer, и
// длинная работа задержит очистку стека горутины.
//
// В реальном движке onPanic поднимает прозрачный режим killswitch: один упавший
// фоновой приёмник не должен молча оставить машину с частично применённым
// десинком. Прозрачный режим пропускает трафик как есть, пока оператор не
// разберётся с причиной.
type OnPanic func(name string, value any, stack []byte)

// Group — набор горутин с общим жизненным циклом и восстановлением после
// паники.
//
// Нулевое значение (`var g Group`) допустимо и работает как группа без
// журнала и без onPanic — паника восстанавливается, но нигде не фиксируется.
// Для реальной работы заводить через NewGroup.
type Group struct {
	wg       sync.WaitGroup
	logger   *slog.Logger
	onPanic  OnPanic
	mu       sync.Mutex
	panicked bool
	count    int
}

// NewGroup создаёт группу с заданным журналом и коллбеком паники.
//
// logger == nil — паники восстанавливаются молча (пригодно для тестов).
// onPanic == nil — паники восстанавливаются без побочных действий (пригодно,
// когда группа защищает ресурсы, но нет killswitch'а поверх).
func NewGroup(logger *slog.Logger, onPanic OnPanic) *Group {
	return &Group{logger: logger, onPanic: onPanic}
}

// Go запускает fn в новой горутине, зарегистрированной в группе.
//
// Если fn паникует, Group её восстанавливает: запись в журнал, вызов onPanic,
// пометка Panicked() = true. Процесс при этом не умирает, другие горутины
// группы продолжают работу.
//
// Возвращает немедленно. Чтобы дождаться завершения всех зарегистрированных
// горутин, вызывать Wait.
//
// Имя (name) используется только для диагностики — попадает в журнал и в
// коллбек onPanic. Два разных имени у двух горутин ничем не отличаются от
// одного и того же, кроме читаемости лога.
func (g *Group) Go(name string, fn func()) {
	g.wg.Add(1)
	g.mu.Lock()
	g.count++
	g.mu.Unlock()
	go func() {
		defer g.wg.Done()
		defer g.recoverPanic(name)
		fn()
	}()
}

// recoverPanic — тело defer, вынесенное отдельно, чтобы оба путя (с паникой и
// без) были одинаково коротки. Выделено ради симметрии и ради читаемости stack
// trace в тестах: trace кончается здесь, а не внутри goroutine-клозуры.
func (g *Group) recoverPanic(name string) {
	r := recover()
	if r == nil {
		return
	}
	stack := debug.Stack()
	g.mu.Lock()
	g.panicked = true
	g.mu.Unlock()
	if g.logger != nil {
		g.logger.Error("паника горутины",
			"name", name,
			"panic", fmt.Sprint(r),
			"stack", string(stack))
	}
	if g.onPanic != nil {
		// Коллбек может сам паниковать (ошибка писателя onPanic — не наша). В
		// этом случае её гасим: иначе горутина осталась бы с незакрытым Done
		// и Wait висел бы вечно, что хуже исходной паники.
		defer func() { _ = recover() }()
		g.onPanic(name, r, stack)
	}
}

// Wait блокирует, пока все зарегистрированные горутины не завершатся.
//
// Безопасно вызывать повторно: вторая Wait возвращает сразу (sync.WaitGroup
// допускает несколько Wait поверх одного набора завершений, если Add не
// идёт параллельно).
func (g *Group) Wait() {
	g.wg.Wait()
}

// Panicked сообщает, восстанавливалась ли хоть одна паника внутри группы.
//
// Нужно для верхнего уровня: `main` на выходе проверяет, был ли фатальный
// отказ, и выставляет код возврата по этому признаку.
func (g *Group) Panicked() bool {
	g.mu.Lock()
	defer g.mu.Unlock()
	return g.panicked
}

// Count — сколько горутин было запущено через Go, суммарно за всё время
// жизни группы. Используется в тестах; в проде нужен редко, но стоит дёшево
// и помогает отладке.
func (g *Group) Count() int {
	g.mu.Lock()
	defer g.mu.Unlock()
	return g.count
}
