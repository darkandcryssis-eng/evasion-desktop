package flow

import "time"

// HelloDetector распознаёт ClientHello в полезной нагрузке.
//
// Инъектируется, чтобы ядро таблицы не зависело от tlsparse и проверялось без
// него. Возвращает: собранный ClientHello, признак того, что имя сервера в
// нагрузке уже целиком видно (десинк применим), и признак того, что нагрузка
// вообще похожа на TLS-рукопожатие. Вызывается как на одном сегменте, так и на
// склейке нескольких (таблица передаёт накопленный буфер — детектор разницы не
// видит). Не-TLS сегмент десинку не подвергается — поток уходит с пути без
// изменений.
type HelloDetector func(payload []byte) (hello []byte, complete bool, isTLS bool)

// phase — стадия жизни потока в таблице.
type phase uint8

const (
	// awaiting — ждём первый сегмент с данными, на котором примем решение.
	awaiting phase = iota
	// assembling — в первом сегменте распознан TLS, но имя сервера ещё не
	// видно (крупный ClientHello с переставленными расширениями, где
	// server_name уехал в следующий сегмент). Сегменты УДЕРЖИВАЮТСЯ (не идут в
	// сеть), а копятся, пока склейка не покажет имя. Удержание нужно, чтобы
	// десинк мог начаться с того сегмента, в котором имя НАЧИНАЕТСЯ: если бы
	// ранние сегменты уже ушли сырыми, а имя оказалось расщеплено на границе,
	// до его начала было бы не дотянуться.
	assembling
	// settled — решение принято (десинк применён, либо поток признан
	// неинтересным). Все дальнейшие пакеты проходят без разбора. Уход с пути.
	settled
)

const (
	// maxAssemblySegments — предел числа сегментов в склейке при поиске SNI
	// многосегментного ClientHello. Имя лежит в начале рукопожатия; если за
	// столько сегментов оно не встретилось, это не тот случай, ради которого
	// стоит держать поток, — сдаёмся, удержанное отдаём сырым.
	//
	// 48 (повышено с 32): живой прогон у владельца показал ~50% «пропущено»
	// на 32 сегментах — YouTube Chromium hello с ECH outer-record + post-
	// quantum key_share + GREASE + расширенным cipher_suites вылазит за 32.
	// 48 сегментов × 2 КиБ = 96 КиБ — покрывает практический потолок с
	// запасом.
	maxAssemblySegments = 48
	// maxAssemblyBytes — предел суммарного размера склейки. 96 КиБ в паре
	// с 48 сегментами удерживает бюджет памяти (~24 МиБ максимум на 256
	// одновременных assembling, большинство потоков в awaiting/settled без
	// буфера).
	maxAssemblyBytes = 96 * 1024
	// maxAssemblyStalls — сколько повторов УЖЕ удержанных байт (ретрансмиссий)
	// терпим, не продвинувшись по склейке, прежде чем сдаться.
	//
	// Зачем терпеть вообще. Удерживая первый сегмент (Buffering), мы не даём
	// ему уйти к серверу — значит сервер его не подтверждает, и клиент по RTO
	// шлёт тот же сегмент заново (тот же seq). Прежний строгий тест
	// непрерывности принимал такой повтор за «разрыв» и сдавался, отдавая
	// настоящий ClientHello сырьём: TSPU видел открытый SNI и рвал соединение
	// (картинки cdn.discordapp.com, net_error -101). Это мы сами и провоцировали
	// удержанием. Теперь повтор удержанных байт — не повод сдаваться: дубликат
	// гасится (в сеть не уходит), ждём недостающий сегмент.
	//
	// Зачем предел. Если недостающий сегмент так и не приходит (настоящая
	// потеря), висеть на потоке вечно нельзя — после стольких холостых повторов
	// сдаёмся и досылаем удержанное сырьём. В нормальном случае второй сегмент
	// приходит в том же флайте (микросекунды), до любого RTO, и ни одного
	// холостого повтора не случается — предел затрагивает лишь уже
	// деградировавший поток.
	maxAssemblyStalls = 8
)

// entry — состояние одного потока. В фазах awaiting/settled намеренно крошечно:
// вся суть 4.2 в том, что состояния мало. Буфер и границы появляются только у
// потока в фазе assembling и освобождаются, как только решение принято.
type entry struct {
	phase phase
	// seen — время последнего пакета потока; по нему идёт истечение.
	seen time.Time
	// buf — накопленные полезные нагрузки удержанных сегментов в фазе
	// assembling. Это копия: байты капчи действительны лишь до следующего Recv,
	// а решение принимается на более позднем сегменте. Непуст только при
	// assembling.
	buf []byte
	// segLens — длины отдельных сегментов в buf, по порядку. Нужны вызывающему,
	// чтобы отдать удержанные сегменты в сеть по исходным границам (не склеивая
	// их в один пакет сверх MTU).
	segLens []int
	// baseSeq — номер последовательности TCP первого удержанного сегмента.
	// По нему проверяется непрерывность склейки и восстанавливаются seq частей.
	baseSeq uint32
	// stalls — сколько раз подряд приходили УЖЕ удержанные байты (повтор
	// ретрансмиссии), не продвинув склейку. Сбрасывается в ноль при любом
	// реальном продвижении; по достижении maxAssemblyStalls сборка сдаётся.
	// Осмыслен только при assembling.
	stalls int

	// helloSeq — seq сегмента, на котором распознан ClientHello. По нему
	// опознаётся его повторная отправка: TCP пересылает несдоставленный сегмент
	// с тем же номером. Осмыслен только при watchRetransmit.
	helloSeq uint32
	// watchRetransmit — поток нёс ClientHello и ещё не дал повтора. Пока
	// истинно, пакет с тем же helloSeq поднимает пассивный признак срыва (5.10).
	// Гасится после первого же повтора: одно сорванное соединение — одно
	// наблюдение, а не по числу ретрансмиссий, которых TCP делает несколько.
	watchRetransmit bool
}

// Disposition — что вызывающий должен сделать с текущим пакетом.
type Disposition uint8

const (
	// Pass — пропустить оригинал без изменений (если не поднят Buffering).
	Pass Disposition = iota
	// Apply — обнаружен ClientHello с видимым именем: применить стратегию и
	// оригинал не пропускать. Поля Hello/BaseSeq/SegLens описывают, к чему
	// применять десинк.
	Apply
)

// Action — итог обработки одного пакета.
type Action struct {
	// Disposition — что делать с оригиналом.
	Disposition Disposition

	// Hello — байты для разбора и применения десинка (при Apply) либо
	// удержанные сегменты для досылки сырьём (при Incomplete).
	//
	// При одиночном ClientHello (имя в первом же сегменте) это нагрузка одного
	// сегмента, SegLens пуст. При собранном из нескольких — вся склейка
	// (нагрузки всех удержанных сегментов подряд), а SegLens несёт их границы.
	Hello []byte
	// BaseSeq — номер последовательности TCP первого байта Hello. По нему
	// вызывающий восстанавливает seq удержанных сегментов и десинкуемого куска.
	BaseSeq uint32
	// SegLens — длины сегментов внутри Hello по порядку. Пуст (или один элемент)
	// для одиночного ClientHello; при сборке несёт границы, по которым
	// вызывающий отделяет сегменты до имени (досылает сырьём) от сегмента, с
	// которого имя начинается (десинкует).
	SegLens []int

	// AtCapacity — поток не взят под наблюдение из-за переполнения таблицы и
	// пропущен прозрачно (4.4). Признак для тревоги на стороне вызывающего.
	AtCapacity bool
	// Buffering — сегмент удержан под сборку многосегментного ClientHello:
	// вызывающий НЕ должен слать его в сеть, байты уже скопированы в таблицу.
	// Поднимается вместе с Pass.
	Buffering bool
	// Incomplete — многосегментный ClientHello собрать не удалось (имя не
	// показалось в пределах склейки либо склейку оборвал разрыв нумерации).
	// Hello/BaseSeq/SegLens несут удержанные до этого сегменты: вызывающий
	// обязан дослать их в сеть сырьём (они ещё не отправлены), затем пропустить
	// текущий пакет. Поднимается вместе с Pass.
	Incomplete bool
	// Reason — почему сборка сдалась (осмыслен только при Incomplete).
	// Диагностика: по разбивке причин в журнале видно, ЧЕМ именно вызван
	// пропуск (разрыв вперёд, лимит сегментов/байт, холостые повторы, не-TLS),
	// а не просто сам факт пропуска.
	Reason GiveUpReason
	// Retransmit — на уже решённом (settled) потоке повторно отправлен
	// ClientHello (тот же seq): сильный признак, что первая попытка осталась
	// без ответа, то есть соединение было сорвано (5.10). Hello несёт байты
	// повторного ClientHello для разбора имени. Поднимается вместе с Pass:
	// детект наблюдательный, сам пакет проходит без изменений. Поднимается не
	// более раза на поток.
	Retransmit bool
}

// Table — таблица потоков. Не потокобезопасна: ею владеет одна горутина (4.2
// правило 2).
type Table struct {
	capacity int
	ttl      time.Duration
	detect   HelloDetector
	flows    map[Key]*entry
}

// NewTable создаёт таблицу на capacity потоков с истечением ttl и заданным
// детектором ClientHello.
func NewTable(capacity int, ttl time.Duration, detect HelloDetector) *Table {
	return &Table{
		capacity: capacity,
		ttl:      ttl,
		detect:   detect,
		flows:    make(map[Key]*entry),
	}
}

// Outbound обрабатывает исходящий пакет соединения key с номером
// последовательности seq и полезной нагрузкой payload (пустой у SYN/ACK).
// now — текущее время, для истечения.
//
// Решение принимается на первом сегменте с данными. Если в нём уже виден SNI
// (или сегмент несёт целый ClientHello), поток сразу уходит с пути с Apply.
// Если распознан TLS, но имени ещё не видно, поток переходит в сборку: сегмент
// удерживается (Buffering), а следующие копятся, пока склейка не покажет SNI.
// Как только решение принято — поток settled и больше не разбирается.
func (t *Table) Outbound(key Key, seq uint32, payload []byte, now time.Time) Action {
	e, ok := t.flows[key]
	if !ok {
		// Новый поток. При переполнении под наблюдение не берём: пропускаем
		// прозрачно, без вытеснения (4.4). Сломать соединение из-за нехватки
		// ёмкости недопустимо — прозрачный режим восстановим, обрыв нет.
		if len(t.flows) >= t.capacity {
			return Action{Disposition: Pass, AtCapacity: true}
		}
		e = &entry{phase: awaiting, seen: now}
		t.flows[key] = e
	}
	e.seen = now

	switch e.phase {
	case settled:
		// Решение уже принято — уходим с пути. Единственное, что ещё смотрим на
		// решённом потоке, — повтор ClientHello: тот же seq, что у исходного.
		// Это дешёвое сравнение чисел; разбор нагрузки на горячем пути не
		// запускаем, иначе каждый пакет потока шёл бы через детектор (нарушение
		// 4.2 правило 1). Повтор поднимает пассивный признак срыва ровно один
		// раз на поток, сам пакет при этом проходит без изменений.
		if e.watchRetransmit && len(payload) > 0 && seq == e.helloSeq {
			e.watchRetransmit = false
			return Action{Disposition: Pass, Retransmit: true, Hello: payload, BaseSeq: seq}
		}
		return Action{Disposition: Pass}
	case assembling:
		return t.assemble(e, seq, payload)
	}

	// awaiting. Пустой сегмент (SYN/ACK): данных нет, решать не на чем — ждём.
	if len(payload) == 0 {
		return Action{Disposition: Pass}
	}

	// Первый сегмент с данными.
	hello, complete, isTLS := t.detect(payload)
	switch {
	case isTLS && complete:
		// Имя видно (или целый ClientHello) — десинк применим сразу.
		// Запоминаем seq ClientHello: по нему опознаем его повторную отправку
		// как признак срыва (5.10).
		e.phase = settled
		e.helloSeq = seq
		e.watchRetransmit = true
		return Action{Disposition: Apply, Hello: hello, BaseSeq: seq}
	case isTLS:
		// TLS распознан, но имени ещё не видно: возможно, крупный ClientHello,
		// в котором server_name уехал в следующий сегмент. Начинаем сборку и
		// УДЕРЖИВАЕМ сегмент — он ещё может оказаться частью имени, если оно
		// расщеплено на границе.
		e.phase = assembling
		e.baseSeq = seq
		e.buf = append(e.buf, payload...)
		e.segLens = append(e.segLens, len(payload))
		return Action{Disposition: Pass, Buffering: true}
	default:
		// Не TLS — уходим с пути.
		e.phase = settled
		return Action{Disposition: Pass}
	}
}

// assemble докладывает сегмент к склейке и решает, собрался ли ClientHello.
//
// Вызывается для потока в фазе assembling. Пустые сегменты (чистые ACK) буфер не
// трогают и проходят в сеть. Сегмент, ровно продолжающий склейку, добавляется;
// повтор уже удержанных байт (ретрансмиссия) гасится и терпится до предела
// холостых повторов; коалесцированный повтор с новым хвостом добавляет только
// хвост. Как только склейка показывает SNI, возвращается Apply со всей склейкой
// и её границами; при исчерпании предела (сегментов, байт или холостых
// повторов), разрыве нумерации вперёд или потере признака TLS — Incomplete с
// удержанными сегментами на досылку.
func (t *Table) assemble(e *entry, seq uint32, payload []byte) Action {
	if len(payload) == 0 {
		// Чистый ACK посреди рукопожатия: данных нет, склейку не двигаем и не
		// удерживаем — пропускаем в сеть.
		return Action{Disposition: Pass}
	}

	// Непрерывность. Следующий сегмент обязан продолжать склейку ровно за уже
	// накопленным (seq == end). Отклонения разбираем по типу, а не сдаёмся на
	// любом, как раньше: главный враг на горячем пути — не разрыв, а повтор
	// удержанного сегмента (ретрансмиссия), который мы сами и провоцируем,
	// придерживая первый сегмент.
	end := e.baseSeq + uint32(len(e.buf))
	if seq != end {
		segEnd := seq + uint32(len(payload))
		switch {
		case seqLE(e.baseSeq, seq) && seqLE(seq, end) && seqLE(segEnd, end):
			// Все байты сегмента уже удержаны — чистый повтор ретрансмиссии.
			// Дубликат в сеть не шлём (оригинал придержан), склейку не трогаем,
			// ждём недостающий сегмент. Считаем холостой повтор: если он так и
			// не сменится продвижением — сдадимся по пределу.
			e.stalls++
			if e.stalls > maxAssemblyStalls {
				return t.giveUp(e, GiveUpStall)
			}
			return Action{Disposition: Pass, Buffering: true}
		case seqLE(e.baseSeq, seq) && seqLE(seq, end) && seqLT(end, segEnd):
			// Частичное перекрытие: передняя часть уже удержана, хвост новый
			// (коалесцированная ретрансмиссия, несущая и следующий сегмент).
			// Докладываем только новый хвост и идём обычным путём.
			payload = payload[end-seq:]
		default:
			// Разрыв вперёд (переупорядочение) или сегмент левее начала склейки:
			// склеить правильные байты без спекуляции нельзя — сдаёмся.
			return t.giveUp(e, GiveUpSeqGap)
		}
	}

	// Реальное продвижение по склейке: холостые повторы обнуляем.
	e.stalls = 0
	prefixLen := len(e.buf)
	e.buf = append(e.buf, payload...)
	e.segLens = append(e.segLens, len(payload))

	_, complete, isTLS := t.detect(e.buf)
	switch {
	case isTLS && complete:
		// Имя показалось — десинк применим. Отдаём всю склейку и её границы.
		// Повтор многосегментного ClientHello начнётся с baseSeq первого
		// сегмента — по нему и сторожим срыв (5.10).
		buf, segLens, base := e.buf, e.segLens, e.baseSeq
		e.phase = settled
		e.helloSeq = base
		e.watchRetransmit = true
		e.buf, e.segLens = nil, nil
		return Action{Disposition: Apply, Hello: buf, BaseSeq: base, SegLens: segLens}
	case isTLS && len(e.segLens) < maxAssemblySegments && len(e.buf) < maxAssemblyBytes:
		// Имени ещё не видно, предел не исчерпан — удерживаем и копим дальше.
		return Action{Disposition: Pass, Buffering: true}
	default:
		// Предел склейки исчерпан либо склейка перестала быть TLS. Снимаем
		// текущий сегмент со склейки (он уйдёт сырым как обычный пакет) и
		// сдаёмся с удержанным префиксом на досылку. Причину различаем для
		// диагностики: не-TLS, предел сегментов или предел байт.
		reason := GiveUpNotTLS
		if isTLS {
			if len(e.segLens) >= maxAssemblySegments {
				reason = GiveUpSegments
			} else {
				reason = GiveUpBytes
			}
		}
		e.buf = e.buf[:prefixLen]
		e.segLens = e.segLens[:len(e.segLens)-1]
		return t.giveUp(e, reason)
	}
}

// seqLE сообщает, что номер последовательности TCP a не позже b, с учётом
// кольцевой арифметики (RFC 1982, 32 бита): разность трактуется как знаковая,
// поэтому сравнение корректно и через точку переполнения uint32.
func seqLE(a, b uint32) bool { return int32(a-b) <= 0 }

// seqLT — строгий вариант seqLE: a строго раньше b в кольцевой арифметике.
func seqLT(a, b uint32) bool { return int32(a-b) < 0 }

// GiveUpReason — почему сборка многосегментного ClientHello была прервана.
// Расширяет Action.Incomplete деталью: нужно для диагностики, по частотам
// причин подбирается maxAssembly* в разумных значениях.
type GiveUpReason uint8

const (
	// GiveUpUnknown — причина не указана (поведение по умолчанию для старых
	// Action без явной постановки).
	GiveUpUnknown GiveUpReason = iota
	// GiveUpSegments — исчерпан предел числа сегментов.
	GiveUpSegments
	// GiveUpBytes — исчерпан предел суммарного размера.
	GiveUpBytes
	// GiveUpSeqGap — разрыв нумерации сегментов (TCP out-of-order или
	// переупорядочивание): дальше не склеить без спекуляции.
	GiveUpSeqGap
	// GiveUpNotTLS — после первой пробы поток перестал выглядеть TLS'ом.
	GiveUpNotTLS
	// GiveUpStall — недостающий сегмент так и не пришёл, шли лишь холостые
	// повторы удержанных байт, и исчерпан их предел (maxAssemblyStalls).
	GiveUpStall
)

// String — короткая текстовая метка для журнала.
func (r GiveUpReason) String() string {
	switch r {
	case GiveUpSegments:
		return "лимит_сегментов"
	case GiveUpBytes:
		return "лимит_байт"
	case GiveUpSeqGap:
		return "разрыв_seq"
	case GiveUpNotTLS:
		return "не_tls"
	case GiveUpStall:
		return "холостые_повторы"
	default:
		return "неизвестно"
	}
}

// giveUp прекращает сборку: поток settled, удержанные до этого сегменты (если
// есть) возвращаются в Action на досылку сырьём, буфер освобождается. reason
// объясняет, чем вызван отказ (диагностика в журнале).
func (t *Table) giveUp(e *entry, reason GiveUpReason) Action {
	buf, segLens, base := e.buf, e.segLens, e.baseSeq
	e.phase = settled
	e.buf, e.segLens = nil, nil
	return Action{Disposition: Pass, Incomplete: true, Hello: buf, BaseSeq: base, SegLens: segLens, Reason: reason}
}

// Forget убирает поток из таблицы. Вызывается при FIN/RST: соединение
// закрылось, держать запись (и её буфер сборки) незачем. Безвреден для
// неизвестного ключа.
func (t *Table) Forget(key Key) {
	delete(t.flows, key)
}

// Sweep убирает потоки, не обновлявшиеся дольше ttl, и возвращает их число.
//
// Нужен потому, что settled-записи живут до конца соединения, а FIN/RST можно
// не увидеть (мы ушли с пути). Истечение освобождает ёмкость под новые потоки и
// буферы незавершённой сборки. Вызывается периодически горутиной-владельцем.
func (t *Table) Sweep(now time.Time) int {
	removed := 0
	for k, e := range t.flows {
		if now.Sub(e.seen) > t.ttl {
			delete(t.flows, k)
			removed++
		}
	}
	return removed
}

// Len возвращает число отслеживаемых потоков. Для наблюдаемости и тестов.
func (t *Table) Len() int { return len(t.flows) }
