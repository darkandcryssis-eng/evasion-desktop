// Пакет flow — таблица потоков этапа 1 (4.2, 4.4).
//
// Зачем существует. Движку нужны только первые пакеты каждого TCP-соединения —
// те, что несут ClientHello. Таблица отслеживает соединение ровно до этого
// решения и уходит с пути: дальше пакеты соединения проходят без разбора. Это
// главный источник стабильности (4.2 правило 3) и свойство архитектурное, а не
// следствие аккуратного кода — горячий путь крошечный, состояния мало, радиус
// бага ограничен началом соединения.
//
// # Решение на первом сегменте, где виден SNI
//
// Поток держится от первого увиденного пакета до того, как станет ясно, где
// лежит имя сервера. В обычном случае это первый сегмент с данными: на нём
// принимается единственное решение (применять ли десинк), и поток помечается
// «решено» — все последующие его пакеты проходят без разбора.
//
// # Сборка многосегментного ClientHello
//
// Крупный ClientHello (постквантовый key_share ~1.2 КБ, переставленные
// расширения) не помещается в один TCP-сегмент, и server_name в части
// соединений уезжает во второй-третий сегмент. Чтобы такие цели не уходили мимо
// десинка с сырым SNI, таблица собирает ClientHello через несколько сегментов:
// если в первом сегменте распознан TLS, но имени ещё не видно, поток переходит
// в фазу сборки и сегменты УДЕРЖИВАЮТСЯ (в сеть не идут), пока склейка не
// покажет имя. Удержание, а не досылка сырьём на лету, нужно ради случая, когда
// имя расщеплено ровно на границе сегментов: десинк должен начаться с того
// сегмента, где имя НАЧИНАЕТСЯ, а если бы ранние сегменты уже ушли, до его
// начала было бы не дотянуться. Непрерывность склейки проверяется по номеру
// последовательности.
//
// На решении таблица отдаёт вызывающему всю склейку и границы сегментов. Тот
// досылает сырьём сегменты до имени (DPI по ним ничего не прочтёт — имени там
// нет), а сегмент, с которого имя начинается, и всё за ним десинкует. Для
// частого случая «имя целиком во втором сегменте» это в точности прежнее
// поведение (первый сегмент сырым, второй десинкуется), только первый досылается
// на решении, а не на приходе; на провод при этом выходят те же байты.
//
// Это не полная пересборка потока: буфер держат лишь потоки в фазе сборки, он
// мал и ограничен пределом (maxAssemblySegments, maxAssemblyBytes), решение
// принимается один раз, после чего поток уходит с пути. Сборка прекращается
// (удержанное досылается сырьём, поток settled) при разрыве нумерации
// (ретрансмит, переупорядочение) или исчерпании предела — соединение при этом
// не ломается: удержанные байты уходят в сеть, а их потерю на крайний случай
// подстраховал бы и ретрансмит TCP.
//
// # Переполнение (4.4)
//
// При исчерпании ёмкости новые потоки не берутся под наблюдение и идут
// прозрачно, без изменений. Вытеснения и отбрасывания нет: рвать соединения
// из-за переполнения внутренней структуры недопустимо. Таблица лишь сообщает
// признаком, что поток не взят из-за ёмкости; тревогу (4.4) поднимает
// вызывающий — громко, но это его решение, не таблицы.
//
// # Владение и детектор
//
// Таблицей владеет одна горутина — цикл захвата, поэтому блокировок нет (4.2
// правило 2). Детектор ClientHello инъектируется: ядро таблицы не зависит от
// tlsparse и проверяется с поддельным детектором. Настоящий детектор (на
// tlsparse) придёт вместе с packetexec, который таблицу и приводит в движение.
//
// Ключ нормализован так, что пакеты обеих сторон одного соединения дают один
// ключ. Исходящая сторона несёт решение, но единый ключ нужен для будущего
// разбора входящих (RST как пассивный сигнал, 5.10) и для освобождения потока
// по FIN/RST.
