// Пакет events собирает структурированные события жизненного цикла движка в
// один поток, пригодный для живого наблюдения, отладки и внешних
// автоматизаций.
//
// Инвариант 1.4 блюпринта (`docs/ARCHITECTURE.md`) требует: каждое решение
// движка — наблюдаемое событие, и события одного соединения можно
// скоррелировать по общему идентификатору.
//
// Что внутри:
//
//   - Event: структура с полями At (время), Kind (вид), FlowID (корреляция),
//     Attrs (map параметров). Сериализуется в JSON Lines (одна строка на
//     событие), что делает поток пригодным для `jq`, `grep`, `tail -f`.
//   - Writer: асинхронный приёмник. Приём не блокирует горячий путь (как у
//     store.Writer): переполнение очереди — отбрасывание со счётчиком, а не
//     ожидание. Запись в файл идёт пакетами, с периодическим flush, чтобы
//     последние события не исчезали при аварийной остановке.
//   - Ротация: при превышении размера активный файл замыкается и
//     переименовывается, открывается новый. Старые ограничены по числу.
//
// Чем отличается от slog. Slog журнал — для оператора: уровни, формат, тексты.
// События — для машины: стабильная структура, предсказуемая по полям,
// самодостаточная (можно восстановить картину без доступа к коду). Два потока
// независимы: один оператор может читать `events.jsonl` через `jq`, другой —
// `movok-engine.log` через `grep`. Дублирования записи нет, пересечение полей
// минимально.
