// Пакет intercept — контур перехвата этапа 1: связывает захват, таблицу
// потоков, выбор стратегии и пакетное исполнение в один цикл.
//
// Это пакетный аналог пакета proxy: там начало соединения вычленяется из потока
// сокета, здесь — из перехваченных пакетов. Решение то же (4.2 правило 3): тронуть
// первые пакеты соединения и уйти с пути, а остальной трафик пропускать без
// изменений.
//
// Цикл на каждый пакет:
//
//   - входящие и не-TCP пакеты, а также всё в прозрачном режиме — пропустить
//     как есть (повторная инъекция в sink);
//   - исходящий TCP: отдать таблице потоков; пока она копит до ClientHello —
//     пропускать;
//   - на ClientHello: выбрать стратегию по SNI, применить её пакетным
//     исполнителем (он отправит сформированные пакеты в sink), а оригинал НЕ
//     пропускать — его заменили;
//   - если стратегии нет, она неисполнима или не применилась до первой
//     отправки — пропустить оригинал без изменений (прозрачный откат, 1.6).
//
// # Killswitch (1.6)
//
// Прозрачный режим — атомарный признак, который сторож (Guard) поднимает при
// потере связности с контрольными целями и снимает при восстановлении. В
// прозрачном режиме цикл не трогает ни один пакет. Это страховка пакетного
// пути: ошибка здесь стоит связности всей машины, поэтому откат к «ничего не
// делать» обязан быть мгновенным и не зависеть от остального контура.
//
// # Границы и швы
//
// Разбор TLS (признак ClientHello, SNI, точки разреза) инъектируется функциями,
// а не зашит: ядро цикла проверяется без tlsparse, а настоящие адаптеры (на
// tlsparse) берёт команда запуска. Выбор стратегии идёт через тот же
// proxy.StrategyProvider, что у прокси, поэтому policy при переходе на этап 1 не
// меняется. Откуда берутся пакеты и куда уходят — дело capture; какой стратегией
// — дело policy; что с пакетом делать — дело packetexec.
