package probe

import (
	"time"

	"github.com/fitting-1c/evasion/internal/core"
)

// Result — результат одной пробы.
//
// Содержит измерение и его обстоятельства, но не оценку: вес исхода и его
// влияние на портфель определяет scoring. Поля подобраны так, чтобы наблюдение
// можно было положить в хранилище целиком и позже пересчитать оценки по другой
// формуле, не теряя исходных данных (6.3).
//
// Словарь исходов, уровней и причин живёт в core: на него ссылаются store,
// scoring и control, которым машинерия проб не нужна (4.1).
//
// # Правило о нулевых значениях
//
// Три признака — StrategyApplied, ThroughputMeasured, Connected — существуют
// потому, что ноль в соседних числовых полях является законным значением, а не
// признаком отсутствия данных. Все три добавлены после настоящей ошибки, а не
// из предусмотрительности:
//
//	ConnectRTT = 0     соединение установилось быстрее разрешения таймера;
//	Throughput = 0     окно наблюдения короче разрешения таймера;
//	StrategyID задан   но стратегия могла и не примениться.
//
// Если в наблюдение добавляется числовое поле, где ноль законен, рядом обязан
// появиться признак измерения. Иначе потребитель примет ноль за отсутствие
// данных или наоборот, и стратегия получит оценку, которой не заслужила.
type Result struct {
	// Target — цель пробы в виде host:port.
	Target string
	// SNI — имя сервера, отправленное в ClientHello.
	SNI string
	// StrategyID — применённая стратегия; пусто, если стратегии не было.
	StrategyID core.StrategyID
	// Phase — уровень оценки.
	Phase core.Phase
	// Outcome — исход.
	Outcome core.Outcome
	// Reason — машинно-читаемая причина исхода.
	Reason core.Reason
	// StrategyApplied — стратегия действительно была применена.
	//
	// Отдельное поле, потому что «стратегия задана» и «стратегия применена» —
	// разные вещи, и путать их нельзя: иначе непроверенная стратегия попадёт в
	// статистику как проверенная.
	StrategyApplied bool
	// Started — момент начала пробы.
	Started time.Time
	// Elapsed — полная длительность пробы.
	Elapsed time.Duration
	// Connected — соединение TCP было установлено.
	//
	// На Windows разрешение таймера грубое, и установка соединения по петле или
	// в локальной сети измеряется ровно нулём. Без этого признака потребитель
	// не отличил бы «соединение установилось мгновенно» от «не установилось
	// вовсе» и мог бы отбросить годный образец RTT.
	Connected bool
	// ConnectRTT — время установки соединения TCP. Осмысленно только при
	// Connected; ноль при Connected означает «быстрее разрешения таймера».
	ConnectRTT time.Duration
	// HandshakeTime — время от начала рукопожатия до его завершения.
	HandshakeTime time.Duration
	// BytesDown — принято байт (медленный уровень).
	BytesDown int64
	// Throughput — байт в секунду за окно наблюдения (медленный уровень).
	// Осмысленно только при ThroughputMeasured.
	Throughput int64
	// ThroughputMeasured — скорость действительно измерена.
	//
	// Ноль в Throughput означал бы «очень медленно», тогда как на деле это
	// «окно наблюдения оказалось короче разрешения таймера, измерить нечем».
	// Спутать эти два случая — значит объявить мгновенный ответ замедлением.
	ThroughputMeasured bool
	// Err — подробности ошибки для журнала. Решения по ней не принимаются:
	// для этого есть Reason.
	Err string
}
