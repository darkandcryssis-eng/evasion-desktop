package probe

import (
	"errors"
	"syscall"
)

// isReset сообщает, что соединение было сброшено другой стороной или сетью.
//
// Сброс — главный признак активного вмешательства: цензор, отвечающий RST,
// отличается от цензора, который молча отбрасывает пакеты, и различать их
// нужно, потому что обходятся они по-разному.
//
// Проверяется через syscall.ECONNRESET, а не по тексту ошибки: текст зависит
// от языка системы, и на русской Windows сравнение со строкой вида
// "connection reset" не сработало бы.
func isReset(err error) bool {
	if errors.Is(err, syscall.ECONNRESET) {
		return true
	}
	// Обрыв канала записи означает, что другой стороны уже нет: мы писали
	// ClientHello в соединение, которое к тому моменту закрыли. Для цензора
	// это обычное поведение — сбросить соединение, не ответив, — и считать
	// такое местной ошибкой значило бы потерять полноценное наблюдение.
	if errors.Is(err, syscall.EPIPE) {
		return true
	}
	// Windows возвращает собственный код для сброса соединения. Значение
	// проверяется через errno-подобный тип, объявленный в platform-файлах,
	// чтобы пакет собирался и там, где такого кода нет.
	return isResetPlatform(err)
}
