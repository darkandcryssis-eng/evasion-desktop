// Пакет probe — активные пробы: движок сам устанавливает соединение, применяет
// к нему стратегию и выносит вердикт.
//
// Зачем существует. Живой трафик даёт наблюдения бесплатно, но только о тех
// целях, куда пользователь и так ходит, и только с теми стратегиями, которые
// уже допущены к трафику. Проверить кандидата, не затрагивая пользователя,
// можно лишь на соединении, которое движок инициировал сам (5.1): у кандидата
// риск для пользователя нулевой именно потому, что он живёт на этих
// соединениях.
//
// Что знает: как установить соединение, провести через него ClientHello по
// стратегии, дождаться ответа сервера и честно классифицировать исход.
//
// Чего знать не должен: как исходы взвешиваются и как по ним принимаются
// решения — это scoring и control. Пакет отдаёт измерение, а не оценку.
//
// # Два уровня оценки
//
// Время прогонов съедают таймауты и замер полосы, а генетическому алгоритму
// замер полосы не нужен: ему достаточно двоичного «обманулся ли DPI», что видно
// по рукопожатию (5.3).
//
//	быстрый уровень  ~100 мс  рукопожатие TCP и TLS, вердикт по RST или зависанию
//	медленный уровень ~8 с    форма полосы за окно
//
// Медленный уровень применяется только к стратегиям, дошедшим до решения о
// повышении, иначе бюджет живых прогонов уходит в таймауты.
//
// # Проба без стратегии — базовая линия
//
// Request со Strategy == nil — законный и нужный случай: измеряется сама цель.
// Такая проба отвечает на вопрос, без которого исходы остальных проб нельзя
// истолковать: блокируется ли цель вообще. StrategyApplied у её результата
// ложен, и это верно — применять было нечего.
//
// Расписание ведёт такие пробы наравне с остальными (PlanItem.Baseline), со
// своим сроком на цель: базовая линия устаревает так же, как оценки, — цель
// могли разблокировать.
//
// # Почему «не определено» — отдельный исход, а не разновидность провала
//
// Вес такого наблюдения равен нулю (5.7): оно не учитывается вовсе. Поэтому
// ошибиться в его сторону безопаснее, чем назвать провалом то, что провалом не
// было. Главное правило классификации: если ClientHello не был отправлен,
// стратегия не проверялась, и исход «не определено» — независимо от причины.
// Назвать такое провалом значило бы приписать стратегии чужую неудачу, а это
// тот же класс порчи измерений, что молчаливое игнорирование непосильного
// примитива (4.7 п. 2).
//
// # Проверка подлинности сертификата
//
// Пробы НЕ проверяют сертификат сервера, и это осознанный выбор с ценой.
// Измеряется достижимость, а не подлинность: проверка добавила бы исходы,
// не связанные с цензурой (сбитые часы, отсутствие корневого сертификата,
// подмена сертификата на стороне сети), и они загрязнили бы функцию
// приспособленности.
//
// Цена: проба не заметит подмену сертификата. Это приемлемо ровно потому, что
// через пробу не идут данные пользователя — она отправляет рукопожатие и, на
// медленном уровне, один запрос без полезной нагрузки. Отключение проверки
// обязано остаться внутри этого пакета: на пути пользовательского трафика
// (proxy) оно недопустимо.
