// Пакет windivert — живой источник и приёмник пакетов этапа 1 через WinDivert.
//
// Реализует capture.PacketSource и capture.PacketSink поверх пользовательской
// библиотеки перехвата WinDivert. Это единственная часть движка, работающая
// только на Windows и требующая драйвера; на прочих ОС пакет собирается, но все
// операции возвращают ошибку (стаб), чтобы команда запуска компоновалась и
// тестировалась везде.
//
// # Поставка и права (3.1)
//
// WinDivert поставляется отдельно под LGPLv3 и связывается ТОЛЬКО динамически:
// `WinDivert.dll` и `WinDivert.sys` кладутся рядом с бинарником, и библиотеку
// можно заменить. Связывание здесь — загрузка DLL во время выполнения
// (LazyDLL), без cgo и без статической компоновки, что требование лицензии и
// заодно запрет CGO (3.1) выполняет само собой.
//
// Открытие требует прав администратора: WinDivert при первом обращении
// устанавливает драйвер. Проверку прав и внятное сообщение делает команда
// запуска (doctor и run), а не этот пакет.
//
// # Непрозрачный адрес и реинъекция
//
// WinDivert при приёме отдаёт пакет вместе со структурой адреса
// (WINDIVERT_ADDRESS), и её обязательно вернуть при отправке, иначе инъекция не
// состоится. Адрес носится в capture.Packet.Reinject как непрозрачное значение
// (Address); толкуется из него только бит направления, чтобы проставить
// capture.Packet.Dir. Контракт владения буфером — как у всего capture: Data
// действителен лишь до следующего Recv, буфер приёма переиспользуется.
//
// Контрольные суммы инъектируемых пакетов пересчитывает packetexec до отправки:
// Windows отвергает пакеты с неверной суммой даже при offloading (см.
// capture/doc.go). Поэтому помощник WinDivert для сумм здесь не нужен.
