// Пакет vantage определяет точку наблюдения — где именно находится движок
// относительно цензора.
//
// Зачем существует отдельным пакетом. Точка наблюдения формирует часть ключа
// любого наблюдения (6.1), поэтому она не деталь хранилища и не поле конфига, а
// самостоятельное понятие. Оценка стратегии не является свойством стратегии:
// она свойство четвёрки «стратегия × цель × точка наблюдения × время».
// Поведение DPI существенно различается между операторами и регионами, и
// вопрос «работает ли стратегия X» без указания, у кого именно, ответа не
// имеет.
//
// Что знает: как собрать признаки точки наблюдения из метки конфига и из
// локальных свойств сетевых интерфейсов, как вычислить устойчивый
// идентификатор и как заметить смену сети.
//
// Чего знать не должен: как наблюдения хранятся и как по ним считаются оценки.
// Пакет отдаёт признаки и идентификатор, а не решения.
//
// Внешних запросов по умолчанию нет — это согласовано с требованиями к сбору
// данных (6.6): определение точки наблюдения не должно само становиться
// утечкой. Запрос собственного публичного адреса и номера автономной системы
// возможен только по явному включению и в этом пакете не реализован.
//
// Порядок определения (6.2):
//
//  1. метка из конфига — основной способ, задаётся владельцем;
//  2. локальные признаки — подсказка и средство обнаружения смены сети;
//  3. внешнее определение — только по явному включению, пока не реализовано.
