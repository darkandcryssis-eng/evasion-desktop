// Пакет quicfake собирает безобидные QUIC-пакеты для подстановки в decoy'ы
// движка.
//
// Назначение одно: дать UDP-decoy'у голоса Discord (74 байта, тип IP discovery
// 0x0001) содержимое, похожее на начало QUIC-соединения к безобидному
// серверу. В этом усиление приёма «decoy»:
//
//   - текущий decoy копирует реальный пакет Discord IP discovery, но с коротким
//     TTL (или битой суммой). DPI, разбирая первые пакеты UDP-потока, видит
//     строгую форму Discord IP discovery и классифицирует поток как голос
//     Discord — приём работает ПОТОМУ ЧТО decoy с коротким TTL до сервера не
//     долетает, а DPI уже «успел посмотреть».
//
//   - новый decoy подменяет содержимое 74 байт на валидный ПО ВИДУ QUIC Initial
//     long-header с нейтральным DCID. DPI смотрит на первый пакет UDP-потока:
//     первый байт `0xc0`, версия `0x00000001` — явная сигнатура QUIC v1 Initial.
//     Поток классифицируется как QUIC к постороннему хосту, а не как голос
//     Discord. Настоящий IP discovery, идущий следом, уже не возвращает
//     классификацию в «голос»: решение принято на первом пакете.
//
// Что внутри. QUIC Initial собирается строго по RFC 9000 §17.2.2: long header,
// version, DCID, SCID, token (пустой), length (variable integer), packet number,
// payload. Внутренняя целостность не критична — пакет никогда не декодируется
// сервером (он уходит с низким TTL/битой суммой). Но первые ~20 байт должны
// быть разборчивы для DPI, иначе приём не сработает по технической причине.
//
// Что НЕ делает. Не шифрует payload: QUIC Initial шифруется AES-GCM с ключом,
// производным от version-salt и DCID. DPI это тоже не проверяет (ему некогда,
// а ключ он мог бы вывести), и шифрование лишь увеличило бы сложность кода без
// практической пользы. Для настоящего клиентского QUIC шифрование обязательно —
// но для decoy, который никогда не доходит до сервера, оно избыточно.
